import type { PrismaService } from "../prisma.service";

/**
 * Разделы сметы, приведённые к верхнему уровню.
 *
 * Правило одно: позиция вложенного раздела принадлежит своему верхнему.
 * Прораб на объекте различает «электрику», а не «электрику / штробление»,
 * и приёмка идёт разделами верхнего уровня. От этого же правила зависит
 * фактическая готовность этапа: этап ведёт верхний раздел, и его выработка
 * складывается из позиций всех вложенных.
 *
 * Написано один раз. Приёмка и график считают по одной карте, иначе две
 * вкладки показывали бы по одному разделу разные числа — тот же класс
 * молчаливого расхождения, что закрыт стадией D.
 *
 * Вложенность разбирается до самого верха, а не на один шаг. Разбор файла
 * сметы даёт два уровня, и на двух уровнях шаг и обход совпадают; на трёх
 * шаг отнёс бы позицию к разделу, которого нет среди верхних, и её позиции
 * исчезли бы из приёмки вовсе. Счётчик оборотов страхует от кольца в
 * данных: оно невозможно по построению импорта, но цена страховки — одно
 * сравнение.
 */
export async function topLevelSections(
  prisma: PrismaService,
  estimateId: string,
): Promise<Map<string, string>> {
  const sections = await prisma.estimateSection.findMany({
    where: { estimateId },
    select: { id: true, parentId: true },
  });

  const родитель = new Map(sections.map((section) => [section.id, section.parentId]));
  const верхний = new Map<string, string>();
  for (const { id } of sections) {
    let текущий = id;
    for (let шаг = 0; шаг < 16; шаг += 1) {
      const выше = родитель.get(текущий);
      if (выше === null || выше === undefined) break;
      текущий = выше;
    }
    верхний.set(id, текущий);
  }
  return верхний;
}
