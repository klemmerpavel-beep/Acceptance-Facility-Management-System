import type { PrismaService } from "../prisma.service";

/*
 * Обложка объекта — опознаватель его последнего снимка приёмки.
 *
 * Отдельным помощником, а не запросом внутри службы объектов: обложка нужна
 * и списку портфеля, и карточке, и второе правило «какой снимок считать
 * последним» разошлось бы с первым — на одном экране объект получил бы одну
 * обложку, на другом другую.
 *
 * Величина производная: снимок уже лежит в приёмке, и хранить его
 * опознаватель у объекта значило бы завести второе место для той же
 * величины. Миграции под обложку нет намеренно.
 */

/**
 * Обложки набора объектов **одним** запросом на весь портфель.
 *
 * Запрос один на список, а не один на объект: портфель — это десятки строк,
 * и обращение на строку выродилось бы в десятки обращений к базе на один
 * экран, ради которого обложка и заводится. Снимки всех объектов берутся
 * разом и раскладываются по объектам в памяти — та же причина, по которой
 * так устроены `estimateFacts` и `openTranches`.
 *
 * Prisma разворачивает этот вызов в два оператора SQL: выборку со стыковкой
 * ради порядка и чтение связи. Оба не зависят от длины списка — замерено на
 * стенде, один объект и девять дают ровно по два оператора, — и цена
 * обложки не растёт вместе с портфелем.
 *
 * Сторнированные пакеты из отбора не исключаются. Сторно отменяет
 * начисление, а не съёмку: помещение было снято, и снимок остаётся
 * свидетельством того, что на объекте происходила работа (БП-04 — история
 * не переписывается). Исключить их значило бы показать пустую плитку у
 * объекта, где работа шла и снимки есть, — и вдобавок потребовало бы читать
 * приёмки пакета, то есть второго запроса ради худшего ответа.
 */
export async function coverPhotos(
  prisma: PrismaService,
  projectIds: readonly string[],
): Promise<Map<string, string>> {
  if (projectIds.length === 0) return new Map();

  /* Порядок задаётся базой и полон: дата пакета решает, «последний» ли
     снимок, а опознаватель снимка разводит равные даты. Равные даты бывают
     не случайно — пакет несёт несколько снимков, и все получают его время,
     а на стенде приёмки заводятся одним заходом. Без второго ключа выбор
     между ними остался бы за порядком выдачи базы и менялся бы от прогона
     к прогону. */
  const снимки = await prisma.acceptancePhoto.findMany({
    where: { batch: { projectId: { in: [...projectIds] } } },
    orderBy: [{ batch: { createdAt: "desc" } }, { id: "desc" }],
    select: { id: true, batch: { select: { projectId: true } } },
  });

  const обложки = new Map<string, string>();
  for (const снимок of снимки) {
    // Первый встреченный снимок объекта и есть последний: порядок задан выше.
    if (!обложки.has(снимок.batch.projectId)) обложки.set(снимок.batch.projectId, снимок.id);
  }
  return обложки;
}
