import { BadRequestException } from "@nestjs/common";
import sharp from "sharp";
import type { ImageType } from "../measure/image-type";

/**
 * Снимок без метаданных.
 *
 * Снимки приёмки, чеков и планы хранились и отдавались как сняты — с EXIF:
 * координаты места съёмки (квартира заказчика), модель устройства, время.
 * Снимки отчёта уходят заказчику, а от него — куда угодно (полный аудит
 * 30.09.2026, П-39). Вырезать сегмент метаданных без декодирования нельзя:
 * ориентация кадра с телефона живёт в том же сегменте, и снимок, снятый
 * вертикально, лёг бы набок. Поэтому кадр поворачивается по ориентации и
 * перекодируется без метаданных — зависимостью `sharp`, принятой решением
 * заказчика от 01.10.2026.
 *
 * Тип файла сохраняется: ключ хранилища и заголовок ответа выведены из
 * него раньше. Качество JPEG и WebP — 90: снимок приёмки — свидетельство
 * сделанной работы, и мелкие детали в нём читают.
 */
export async function безМетаданных(body: Buffer, type: ImageType): Promise<Buffer> {
  const кадр = sharp(body, { failOn: "error" }).rotate();
  try {
    switch (type) {
      case "image/jpeg": return await кадр.jpeg({ quality: 90 }).toBuffer();
      case "image/png": return await кадр.png().toBuffer();
      case "image/webp": return await кадр.webp({ quality: 90 }).toBuffer();
    }
  } catch {
    /* Подпись файла совпала, а изображение не читается: обрезанная
       передача или подделанный заголовок. Отказ — словами, а не 500. */
    throw new BadRequestException({
      message: "Снимок не читается как изображение: файл повреждён или обрезан при передаче. Снимите заново.",
    });
  }
}
