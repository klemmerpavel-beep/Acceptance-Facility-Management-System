/**
 * Частота запросов входа (ADR-0008, пп. 5–6; K7 фазы 0, П-63).
 *
 * Пауза кода действовала, только пока жил непогашенный код: цикл «запрос
 * кода, пять догадок, гашение» повторялся без паузы и без предела, а ссылка
 * по почте заводила строку токена на каждый запрос. Решение заказчика —
 * ответ 15 «б» раунда 1 фазы 0: ограничение своим кодом, без новой
 * зависимости (пакет `@fastify/rate-limit` не вводится, ADR-0008, п. 9).
 *
 * Пределы задаются переменными окружения с умолчаниями; умолчания записаны
 * в `.env.example` и в ADR-0008 и подтверждаются заказчиком при приёмке.
 * Здесь — только правила: ни базы, ни HTTP. Счёт строк ведёт служба входа.
 */

const МИНУТА_МС = 60 * 1000;
export const ЧАС_МС = 60 * МИНУТА_МС;
export const СУТКИ_МС = 24 * ЧАС_МС;

export interface ПределыВхода {
  /** Пауза между кодами на номер: от последнего выданного кода, погашен он или нет. */
  readonly паузаКодаМс: number;
  /** Кодов на номер за скользящий час. */
  readonly кодовВЧас: number;
  /** Кодов на номер за скользящие сутки. */
  readonly кодовВСутки: number;
  /** Непогашенных ссылок по почте на адрес за скользящий час. */
  readonly ссылокВЧас: number;
}

/** Переменные окружения и умолчания. Одно место: его читают служба, `.env.example` и ADR. */
export const ПЕРЕМЕННЫЕ_ПРЕДЕЛОВ = {
  AUTH_SMS_RESEND_SECONDS: 60,
  AUTH_SMS_PER_HOUR: 5,
  AUTH_SMS_PER_DAY: 10,
  AUTH_LINKS_PER_HOUR: 5,
} as const;

type Переменная = keyof typeof ПЕРЕМЕННЫЕ_ПРЕДЕЛОВ;

/**
 * Пределы из окружения. Значение — целое не меньше единицы; иное — отказ
 * запуска, а не молчаливое умолчание: опечатка в `.env`, снявшая предел,
 * выяснилась бы первым перебором, а не первым запуском.
 */
export function пределыИз(env: Readonly<Record<string, string | undefined>>): ПределыВхода {
  const прочесть = (имя: Переменная): number => {
    const сырое = env[имя];
    if (сырое === undefined || сырое.trim() === "") return ПЕРЕМЕННЫЕ_ПРЕДЕЛОВ[имя];
    const число = Number(сырое);
    if (!Number.isInteger(число) || число < 1) {
      throw new Error(`${имя}=${сырое}: предел частоты входа — целое число не меньше 1.`);
    }
    return число;
  };
  return {
    паузаКодаМс: прочесть("AUTH_SMS_RESEND_SECONDS") * 1000,
    кодовВЧас: прочесть("AUTH_SMS_PER_HOUR"),
    кодовВСутки: прочесть("AUTH_SMS_PER_DAY"),
    ссылокВЧас: прочесть("AUTH_LINKS_PER_HOUR"),
  };
}

export type РешениеОКоде =
  | { readonly вид: "выдать" }
  /** Пауза: код не выдаётся, ответ называет, через сколько секунд можно снова. */
  | { readonly вид: "ждать"; readonly секунд: number }
  /** Предел за окно: отказ 429 с числом минут. */
  | { readonly вид: "предел"; readonly минут: number };

/**
 * Через сколько миллисекунд число выданных за окно станет меньше предела.
 * `null` — предел не достигнут. Метки упорядочиваются здесь: вызывающий
 * не обязан помнить порядок выборки.
 */
function ждатьОкна(выданы: readonly number[], сейчас: number, окно: number, предел: number): number | null {
  const вОкне = выданы.filter((метка) => сейчас - метка < окно).sort((a, b) => a - b);
  if (вОкне.length < предел) return null;
  /* Окно освобождается, когда из него выходит метка, после которой внутри
     остаётся на одну меньше предела. Предел, сниженный между запусками,
     даёт вОкне длиннее предела — поэтому индекс, а не первая метка. */
  const выходит = вОкне[вОкне.length - предел] ?? сейчас;
  return выходит + окно - сейчас;
}

/**
 * Можно ли выдать код на номер сейчас.
 *
 * `выданы` — мгновения кодов, выданных на этот номер за последние сутки,
 * погашенных и нет: пауза считается от последнего выданного, а не от
 * последнего живого. Сначала пределы за окно, затем пауза: превышенный
 * предел называет срок в минутах, пауза — в секундах.
 */
export function решениеОКоде(
  выданы: readonly Date[], сейчас: Date, пределы: ПределыВхода,
): РешениеОКоде {
  const метки = выданы.map((мгновение) => мгновение.getTime());
  const теперь = сейчас.getTime();
  const час = ждатьОкна(метки, теперь, ЧАС_МС, пределы.кодовВЧас);
  const сутки = ждатьОкна(метки, теперь, СУТКИ_МС, пределы.кодовВСутки);
  if (час !== null || сутки !== null) {
    const ждать = Math.max(час ?? 0, сутки ?? 0);
    return { вид: "предел", минут: Math.max(1, Math.ceil(ждать / МИНУТА_МС)) };
  }
  const последний = метки.length === 0 ? null : Math.max(...метки);
  if (последний !== null && теперь - последний < пределы.паузаКодаМс) {
    return { вид: "ждать", секунд: Math.max(1, Math.ceil((пределы.паузаКодаМс - (теперь - последний)) / 1000)) };
  }
  return { вид: "выдать" };
}

/** Текст отказа 429. Один на сервер: экран входа показывает его как прочие отказы. */
export const текстПредела = (минут: number): string =>
  `Слишком много запросов. Повторите через ${String(минут)} мин.`;

/**
 * Журнал выдач на номера, которых нет в системе.
 *
 * Ответ на запрос кода не различает существующий и несуществующий номер:
 * иначе форма входа становится проверялкой того, кто есть в системе. Пауза
 * и предел считаются строками кодов, а у несуществующего номера строк нет —
 * и без этого журнала шестой запрос отвечал бы 429 только существующему
 * номеру, а пауза называла бы оставшиеся секунды только ему. Журнал держит
 * те же мгновения «выдачи», которые у существующего номера легли бы строками,
 * и ровно на те же сутки.
 *
 * Живёт в памяти процесса: персональных данных в нём нет — номер, которого
 * в системе нет, — и после перезапуска он пуст, как пусты были бы и строки
 * свежего номера. Размер ограничен: перебор миллиона выдуманных номеров не
 * должен съесть память сервера; вытесняется давнее.
 */
export class ЖурналНеизвестныхНомеров {
  private readonly выдачи = new Map<string, number[]>();

  constructor(private readonly предел = 10_000) {}

  /** Мгновения «выдач» номеру за последние сутки. */
  выданы(номер: string, сейчас: Date): Date[] {
    const метки = (this.выдачи.get(номер) ?? []).filter((метка) => сейчас.getTime() - метка < СУТКИ_МС);
    if (метки.length === 0) this.выдачи.delete(номер);
    else this.выдачи.set(номер, метки);
    return метки.map((метка) => new Date(метка));
  }

  /** Отмечает «выдачу». Номер переезжает в конец порядка вытеснения. */
  отметить(номер: string, сейчас: Date): void {
    const метки = (this.выдачи.get(номер) ?? []).filter((метка) => сейчас.getTime() - метка < СУТКИ_МС);
    this.выдачи.delete(номер);
    this.выдачи.set(номер, [...метки, сейчас.getTime()]);
    while (this.выдачи.size > this.предел) {
      const давний = this.выдачи.keys().next().value;
      if (давний === undefined) break;
      this.выдачи.delete(давний);
    }
  }

  get размер(): number {
    return this.выдачи.size;
  }
}
