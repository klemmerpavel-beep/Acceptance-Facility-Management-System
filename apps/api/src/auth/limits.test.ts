import { describe, expect, it } from "vitest";
import {
  ЖурналНеизвестныхНомеров, ПЕРЕМЕННЫЕ_ПРЕДЕЛОВ, пределыИз, решениеОКоде, текстПредела, ЧАС_МС, СУТКИ_МС,
} from "./limits";

/**
 * Пределы частоты входа (ADR-0008, пп. 5–6; П-63). Свойства, которые стенд
 * проверяет только на умолчаниях и только в пределах часа: сутки, снижение
 * предела, порядок предела и паузы, отказ запуска на опечатке.
 */
const СЕЙЧАС = new Date("2026-11-07T12:00:00Z");
const назад = (мс: number): Date => new Date(СЕЙЧАС.getTime() - мс);
const МИН = 60 * 1000;
const умолчания = пределыИз({});

describe("пределы из окружения", () => {
  it("без переменных — умолчания ADR-0008", () => {
    expect(умолчания).toEqual({ паузаКодаМс: 60_000, кодовВЧас: 5, кодовВСутки: 10, ссылокВЧас: 5 });
    expect(ПЕРЕМЕННЫЕ_ПРЕДЕЛОВ).toEqual({
      AUTH_SMS_RESEND_SECONDS: 60, AUTH_SMS_PER_HOUR: 5, AUTH_SMS_PER_DAY: 10, AUTH_LINKS_PER_HOUR: 5,
    });
  });

  it("переменная задаёт свой предел, пустая — умолчание", () => {
    expect(пределыИз({ AUTH_SMS_RESEND_SECONDS: "1", AUTH_LINKS_PER_HOUR: "", AUTH_SMS_PER_DAY: " 20 " }))
      .toEqual({ паузаКодаМс: 1000, кодовВЧас: 5, кодовВСутки: 20, ссылокВЧас: 5 });
  });

  it("ноль, дробь и слово — отказ запуска, а не снятый предел", () => {
    for (const плохое of ["0", "-3", "1.5", "пять", "Infinity"]) {
      expect(() => пределыИз({ AUTH_SMS_PER_HOUR: плохое })).toThrow(/AUTH_SMS_PER_HOUR/u);
    }
  });
});

describe("решение о выдаче кода", () => {
  it("первый код выдаётся", () => {
    expect(решениеОКоде([], СЕЙЧАС, умолчания)).toEqual({ вид: "выдать" });
  });

  it("пауза — от последнего выданного кода, погашен он или нет", () => {
    expect(решениеОКоде([назад(20_000)], СЕЙЧАС, умолчания)).toEqual({ вид: "ждать", секунд: 40 });
    expect(решениеОКоде([назад(60_000)], СЕЙЧАС, умолчания)).toEqual({ вид: "выдать" });
    // Порядок меток не важен: берётся последний по времени.
    expect(решениеОКоде([назад(2 * МИН), назад(500)], СЕЙЧАС, умолчания)).toEqual({ вид: "ждать", секунд: 60 });
  });

  it("шестой код за час — предел, срок — до выхода старейшего из окна", () => {
    const пять = [50, 40, 30, 20, 10].map((минут) => назад(минут * МИН));
    expect(решениеОКоде(пять, СЕЙЧАС, умолчания)).toEqual({ вид: "предел", минут: 10 });
    const четыре = пять.slice(1);
    expect(решениеОКоде(четыре, СЕЙЧАС, умолчания)).toEqual({ вид: "выдать" });
  });

  it("код старше часа в часовой предел не входит, но входит в суточный", () => {
    const старые = [23, 22, 21, 20, 19].map((часов) => назад(часов * ЧАС_МС));
    const свежие = [50, 40, 30, 20].map((минут) => назад(минут * МИН));
    expect(решениеОКоде([...старые, ...свежие], СЕЙЧАС, умолчания)).toEqual({ вид: "выдать" });
    const десятый = [...старые, ...свежие, назад(5 * МИН)];
    // Час: пять за час — до выхода кода 50 минут назад 10 минут; сутки: десять — до выхода кода 23 часа назад 60 минут.
    expect(решениеОКоде(десятый, СЕЙЧАС, умолчания)).toEqual({ вид: "предел", минут: 60 });
  });

  it("предел, сниженный между запусками, считается по своему месту в окне", () => {
    const пять = [50, 40, 30, 20, 10].map((минут) => назад(минут * МИН));
    // Предел 3: окно освободится, когда выйдет код 30 минут назад — третий с конца.
    expect(решениеОКоде(пять, СЕЙЧАС, { ...умолчания, кодовВЧас: 3 })).toEqual({ вид: "предел", минут: 30 });
  });

  it("предел называет хотя бы минуту, пауза — хотя бы секунду", () => {
    const пять = [ЧАС_МС - 100, 40 * МИН, 30 * МИН, 20 * МИН, 10 * МИН].map(назад);
    expect(решениеОКоде(пять, СЕЙЧАС, умолчания)).toEqual({ вид: "предел", минут: 1 });
    expect(решениеОКоде([назад(59_999)], СЕЙЧАС, умолчания)).toEqual({ вид: "ждать", секунд: 1 });
  });

  it("код старше суток не считается вовсе", () => {
    const древние = Array.from({ length: 30 }, (_, i) => назад(СУТКИ_МС + i * МИН));
    expect(решениеОКоде(древние, СЕЙЧАС, умолчания)).toEqual({ вид: "выдать" });
  });

  it("текст отказа — тот, что записан в ADR-0008", () => {
    expect(текстПредела(7)).toBe("Слишком много запросов. Повторите через 7 мин.");
  });
});

describe("журнал номеров, которых нет в системе", () => {
  it("копит выдачи номера за сутки и забывает старше", () => {
    const журнал = new ЖурналНеизвестныхНомеров();
    журнал.отметить("+79990000001", назад(СУТКИ_МС + 1));
    журнал.отметить("+79990000001", назад(10 * МИН));
    журнал.отметить("+79990000001", СЕЙЧАС);
    expect(журнал.выданы("+79990000001", СЕЙЧАС).map((мгновение) => мгновение.getTime()))
      .toEqual([назад(10 * МИН).getTime(), СЕЙЧАС.getTime()]);
    expect(журнал.выданы("+79990000002", СЕЙЧАС)).toEqual([]);
  });

  it("решение для несуществующего номера — то же, что для существующего", () => {
    const журнал = new ЖурналНеизвестныхНомеров();
    const выданы: Date[] = [];
    for (let i = 0; i < 6; i += 1) {
      const когда = new Date(СЕЙЧАС.getTime() + i * 2 * МИН);
      const решение = решениеОКоде(журнал.выданы("+79990000003", когда), когда, умолчания);
      expect(решение).toEqual(решениеОКоде(выданы, когда, умолчания));
      if (решение.вид === "выдать") { журнал.отметить("+79990000003", когда); выданы.push(когда); }
    }
    expect(выданы).toHaveLength(5);
  });

  it("размер ограничен: вытесняется давний номер", () => {
    const журнал = new ЖурналНеизвестныхНомеров(3);
    for (const номер of ["a", "b", "c"]) журнал.отметить(номер, СЕЙЧАС);
    журнал.отметить("a", СЕЙЧАС);
    журнал.отметить("d", СЕЙЧАС);
    expect(журнал.размер).toBe(3);
    expect(журнал.выданы("b", СЕЙЧАС)).toEqual([]);
    expect(журнал.выданы("a", СЕЙЧАС)).toHaveLength(2);
  });
});
