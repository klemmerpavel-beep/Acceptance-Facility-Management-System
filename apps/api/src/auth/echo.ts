/**
 * Код подтверждения и токен ссылки входа в теле ответа — только на стенде.
 *
 * Прежде эхо включалось всяким режимом, кроме `production`, а поставка
 * по умолчанию запускалась в `development`: стенд, поднятый по
 * `.env.example`, пускал любого руководителем, назвав его почту (полный
 * аудит 30.09.2026, П-28). Решение заказчика от 01.10.2026: эхо — только по
 * явному флагу `AUTH_ECHO=1`, отсутствие флага означает «код уходит
 * сообщением». Отправщик писем и сообщений подключается к пилоту.
 */
export const AUTH_ECHO_FLAG = "AUTH_ECHO";

export function echoesSecrets(): boolean {
  return process.env[AUTH_ECHO_FLAG] === "1";
}

/**
 * Флаг стенда в промышленном режиме — ошибка поставки, а не выбор: такой
 * сервер отдавал бы код входа любому, кто знает почту. Запуск отказывает
 * сразу, а не выясняется первым чужим входом.
 */
export function assertEchoAllowed(): void {
  if (echoesSecrets() && process.env.NODE_ENV === "production") {
    throw new Error(
      `${AUTH_ECHO_FLAG}=1 при NODE_ENV=production: код входа ушёл бы в ответ. `
      + "Флаг стенда в промышленном режиме не допускается — снимите его.",
    );
  }
}
