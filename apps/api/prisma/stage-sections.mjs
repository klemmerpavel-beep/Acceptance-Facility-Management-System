/**
 * Связь этапов графика с разделами сметы для наполнения стенда.
 *
 * Живёт отдельным модулем, потому что нужна двум скриптам: `seed.mjs`
 * заводит этапы, `scripts/seed-estimate.mjs` — смету, а связать одно с
 * другим можно только когда есть оба. Первый вызов на пустой базе ничего не
 * находит и молча уходит; второй, после импорта сметы, связь проставляет.
 *
 * Связаны не все разделы. «Малярные под обои», «Чистовой электромонтаж»,
 * «Кондиционирование» и «Дополнительные расходы» этапа не имеют намеренно:
 * на них проверяется отказ приёмки «у раздела нет этапа», и стенд без
 * такого раздела эту ветку не показал бы вовсе.
 */

/** Имя этапа → имя раздела верхнего уровня действующей сметы. */
export const РАЗДЕЛ_ЭТАПА = {
  "Демонтаж": "ПОДГОТОВИТЕЛЬНЫЕ РАБОТЫ",
  "Черновая электрика": "ЧЕРНОВОЙ ЭЛЕКТРОМОНТАЖ ( ПО ФАКТУ)",
  "Разводка воды": "САНТЕХНИКА И ОТОПЛЕНИЕ (ПО ФАКТУ)",
  "Штукатурка стен": "МАЛЯРНЫЕ РАБОТЫ И ЧИСТОВАЯ ОТДЕЛКА (ПОД ОКРАСКУ)",
  "Стяжка пола": "ГИПСОКАРТОН, ВОЗВЕДЕНИЕ ПЕРЕГОРОДОК",
  "Плиточные работы": "ВАННАЯ/САН УЗЕЛ",
  "Чистовая отделка": "МОНТАЖНЫЕ РАБОТЫ",
};

/**
 * Проставить этапам объекта раздел действующей редакции сметы.
 * Возвращает число связанных этапов.
 */
export async function связатьЭтапыСРазделами(prisma, projectId) {
  const смета = await prisma.estimate.findFirst({
    where: { projectId },
    orderBy: { version: "desc" },
    select: { id: true },
  });
  if (смета === null) return 0;

  const разделы = await prisma.estimateSection.findMany({
    where: { estimateId: смета.id, parentId: null },
    select: { id: true, name: true },
  });
  const поИмени = new Map(разделы.map((раздел) => [раздел.name, раздел.id]));

  const этапы = await prisma.workStage.findMany({
    where: { projectId },
    select: { id: true, name: true },
  });

  let связано = 0;
  for (const этап of этапы) {
    const имяРаздела = РАЗДЕЛ_ЭТАПА[этап.name];
    const sectionId = имяРаздела === undefined ? null : поИмени.get(имяРаздела) ?? null;
    await prisma.workStage.update({ where: { id: этап.id }, data: { sectionId } });
    if (sectionId !== null) связано += 1;
  }
  return связано;
}
