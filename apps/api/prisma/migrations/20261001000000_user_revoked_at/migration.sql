-- Мягкое снятие доступа: человек остаётся записью с датой снятия.
--
-- Решение заказчика от 01.10.2026 по замечанию П-51 полного аудита. Прежде
-- снятие доступа удаляло строку человека, и связи `onDelete: SetNull` стирали
-- его авторство в журнале, пакетах приёмки, чеках и снимках: «кто принял эту
-- позицию» через год было не узнать. Теперь строка остаётся, вход и выдача
-- ссылок её не находят, а повторная выдача входа по той же почте или телефону
-- возвращает ту же запись.
ALTER TABLE "users" ADD COLUMN "revokedAt" TIMESTAMP(3);
