-- Позиция сметы узнаёт своё помещение.
--
-- До этой правки помещение в продукте было, а работам недоступно: подстановка
-- «из обмера» в правке позиции брала итог по всему объекту, и на позицию
-- «плитка пола, санузел» подставлялась площадь пола всей квартиры. Связь
-- закрывает это и даёт смете вторую группировку — по помещениям.
--
-- Столбец обнуляемый по необходимости, а не про запас: смета приходит из
-- файла, а импортёр помещений не знает — обмер делают отдельно и нередко
-- позже. Обязательный столбец сделал бы импорт невозможным.
--
-- ON DELETE SET NULL, а не RESTRICT: помещение удаляют в обмере, и смета не
-- вправе запрещать правку обмера. Обрыв связи виден на экране словами, а не
-- молчит.

ALTER TABLE "estimate_items" ADD COLUMN "roomId" UUID;

ALTER TABLE "estimate_items"
  ADD CONSTRAINT "estimate_items_roomId_fkey"
  FOREIGN KEY ("roomId") REFERENCES "measure_rooms"("id")
  ON DELETE SET NULL ON UPDATE CASCADE;

CREATE INDEX "estimate_items_roomId_idx" ON "estimate_items"("roomId");
