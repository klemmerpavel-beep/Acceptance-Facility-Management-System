-- Порядок позиции — место ВНУТРИ раздела, а не сквозной счётчик по смете.
--
-- Прежде `order` вёлся сквозным счётчиком при импорте и он же печатался
-- колонкой «№». Перетаскивание при таком хранении означало бы перенумерацию
-- всех ста тридцати двух строк на каждый жест, а всякая перестановка — запись
-- в сто тридцать две строки вместо двух.
--
-- Номер строки документа с этой правки считается при сборке вида, обходом
-- дерева в порядке показа: он производная величина и в хранении не нужен.
--
-- Перенумерация детерминированна и идемпотентна: порядок внутри раздела
-- сохраняется, ключом сортировки идут прежний порядок, строка исходного
-- файла и опознаватель — последний разрывает ничью однозначно.

UPDATE "estimate_items" AS i
SET "order" = n.rn
FROM (
  SELECT id,
         ROW_NUMBER() OVER (
           PARTITION BY "sectionId"
           ORDER BY "order", "sourceRow" NULLS LAST, id
         ) AS rn
  FROM "estimate_items"
) AS n
WHERE i.id = n.id AND i."order" <> n.rn;
