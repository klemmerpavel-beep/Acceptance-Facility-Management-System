import { useEffect, useId, useRef, useState } from "react";

/**
 * Правка значения на месте.
 *
 * Продукт правил поля объекта только листами: чтобы сдвинуть срок, человек
 * открывал лист, находил в нём поле среди прочих, менял одно и сохранял все.
 * Для одного значения это три лишних шага и экран, закрывающий то, ради чего
 * его открыли, — саму карточку.
 *
 * Здесь значение правится там, где оно написано. Пока правки нет, стоит
 * обычный текст и кнопка «Изменить»; по нажатию на её месте появляется поле
 * с двумя кнопками. Ничего не «превращается» в поле по щелчку по тексту:
 * текст, который нельзя выделить, не скопировав случайно в правку, — это
 * ловушка, а адрес объекта копируют часто.
 *
 * Что обеспечивается сверх вида:
 *
 *   — **Escape отменяет.** Правка, из которой нельзя выйти иначе как мышью,
 *     заставляет искать кнопку глазами.
 *   — **Фокус возвращается.** После сохранения и после отмены фокус уходит
 *     на кнопку «Изменить» — туда, откуда он пришёл. Иначе он падает на
 *     `body`, и следующий Tab начинает обход страницы заново.
 *   — **Исход объявляется.** Сохранение меняет текст молча: для того, кто
 *     слушает страницу, ничего не произошло. Объявление несёт имя поля и
 *     новое значение, а не слово «Сохранено» — сохранено что.
 *   — **Отказ виден рядом с полем**, а не общим сообщением наверху: поле,
 *     которое сервер не принял, человек ищет сам.
 */
export function FieldEdit({
  подпись,
  значение,
  показ,
  вид = "text",
  варианты,
  onSave,
}: {
  /** Имя поля. Идёт в доступное имя поля ввода и в объявление исхода. */
  подпись: string;
  /** Значение для правки: строка поля ввода. Пусто — значения нет. */
  значение: string;
  /** Как значение выглядит в покое. Отличается от `значение`: дата
   *  печатается «12.09.2026», а правится «2026-09-12». */
  показ: React.ReactNode;
  вид?: "text" | "date" | "number" | "select";
  /** Для `select`: что выбирать. Пустое значение — «снять». */
  варианты?: readonly { значение: string; подпись: string }[];
  /** Сохранение. Отказ бросает — сообщение показывается у поля. */
  onSave: (новое: string) => Promise<void>;
}): React.JSX.Element {
  const [правим, setПравим] = useState(false);
  const [черновик, setЧерновик] = useState(значение);
  const [идёт, setИдёт] = useState(false);
  const [отказ, setОтказ] = useState<string | null>(null);
  const [объявление, setОбъявление] = useState("");
  const кнопка = useRef<HTMLButtonElement>(null);
  const поле = useRef<HTMLInputElement | HTMLSelectElement>(null);
  const id = useId();

  /* Черновик задаётся в самом открытии, а не следствием его.
 
     Первая редакция сбрасывала черновик эффектом по `правим`, и это была
     гонка: поле появляется при отрисовке, а эффект отрабатывает после неё —
     ввод, сделанный между этими мгновениями, затирался сбросом. Внешне всё
     выглядело исправным: правка закрывалась, отказа не было, — но на сервер
     уходило прежнее значение, и журнал молчал. Дефект нашёл замер обхода:
     глазом он неотличим от «сохранилось». */
  const открыть = (): void => {
    setЧерновик(значение);
    setОтказ(null);
    setПравим(true);
  };

  /* Фокус на поле — уже следствием: до отрисовки поля его нет. */
  useEffect(() => {
    if (правим) поле.current?.focus();
  }, [правим]);

  /* Возврат фокуса — следствием закрытия, а не его частью. Первая редакция
     звала `focus` прямо в обработчике, сразу за `setПравим(false)`, и фокус
     не возвращался: кнопки в этот миг ещё нет в разметке — React
     перерисовывает после обработчика, и ссылка на неё пуста. Фокус падал на
     `body`, и следующий Tab начинал обход страницы заново. Нашёл это не
     глаз, а замер обхода: пропажу фокуса не видно. */
  const возврат = useRef(false);
  useEffect(() => {
    if (!правим && возврат.current) {
      возврат.current = false;
      кнопка.current?.focus();
    }
  }, [правим]);

  const закрыть = (): void => {
    возврат.current = true;
    setПравим(false);
  };

  const сохранить = (): void => {
    if (идёт) return;
    setИдёт(true);
    setОтказ(null);
    void onSave(черновик)
      .then(() => {
        setОбъявление(`${подпись}: ${черновик === "" ? "значение снято" : черновик}`);
        закрыть();
      })
      .catch((ошибка: unknown) => {
        setОтказ(ошибка instanceof Error ? ошибка.message : "Не удалось сохранить.");
      })
      .finally(() => { setИдёт(false); });
  };

  if (!правим) {
    return (
      <span className="fieldedit">
        <span className="fieldedit__value">{показ}</span>
        <button
          type="button"
          className="btn btn--text fieldedit__open"
          ref={кнопка}
          onClick={открыть}
          aria-label={`Изменить: ${подпись}`}
        >
          Изменить
        </button>
        {/* Живая область остаётся в разметке и когда объявлять нечего:
            область, добавленная вместе с текстом, читалкой не объявляется —
            она узнаёт об изменении внутри уже существующей области. */}
        <span role="status" className="visually-hidden">{объявление}</span>
      </span>
    );
  }

  return (
    <span className="fieldedit fieldedit--open">
      <label className="visually-hidden" htmlFor={`${id}-поле`}>{подпись}</label>
      {вид === "select" ? (
        <select
          id={`${id}-поле`}
          className="input fieldedit__input"
          ref={поле as React.RefObject<HTMLSelectElement>}
          value={черновик}
          disabled={идёт}
          aria-describedby={отказ === null ? undefined : `${id}-отказ`}
          aria-invalid={отказ === null ? undefined : true}
          onChange={(event) => { setЧерновик(event.target.value); }}
          onKeyDown={(event) => { if (event.key === "Escape") закрыть(); }}
        >
          <option value="">Не назначен</option>
          {(варианты ?? []).map((вариант) => (
            <option key={вариант.значение} value={вариант.значение}>{вариант.подпись}</option>
          ))}
        </select>
      ) : (
        <input
          id={`${id}-поле`}
          type={вид}
          className="input fieldedit__input"
          ref={поле as React.RefObject<HTMLInputElement>}
          value={черновик}
          disabled={идёт}
          aria-describedby={отказ === null ? undefined : `${id}-отказ`}
          aria-invalid={отказ === null ? undefined : true}
          onChange={(event) => { setЧерновик(event.target.value); }}
          onKeyDown={(event) => {
            if (event.key === "Escape") закрыть();
            if (event.key === "Enter") сохранить();
          }}
        />
      )}
      <button
        type="button"
        className="btn btn--primary"
        disabled={идёт}
        data-loading={идёт}
        onClick={сохранить}
      >
        Сохранить
      </button>
      <button type="button" className="btn btn--text" disabled={идёт} onClick={закрыть}>
        Отмена
      </button>
      {отказ !== null && (
        <span className="error fieldedit__error" id={`${id}-отказ`} role="alert">{отказ}</span>
      )}
    </span>
  );
}
