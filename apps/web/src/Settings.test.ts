import { describe, expect, it } from "vitest";
import { тарифВКопейках } from "./Settings.js";

/**
 * Тариф типа ремонта — деньги, и разбирается он целыми числами.
 *
 * Лист разбирал тариф `Number(…) * 100` с `Math.round`: запись «1e3»
 * становилась тарифом 1 000 ₽ за метр, «0x10» — шестнадцатью рублями, а
 * третий знак после запятой молча съедала плавающая точка (БП-08; полный
 * аудит 30.09.2026, П-34). Тариф уходит в вилку ориентировочной цены
 * заявки, и неверная строка доходила до заказчика ценой.
 */
describe("тариф за метр: рубли → копейки", () => {
  it.each([
    ["1 150,50", "115050"],
    ["1150.5", "115050"],
    ["12 345,67", "1234567"],
    ["90071992547409,93", "9007199254740993"],
  ])("«%s» → %s копеек", (ввод, копейки) => {
    expect(тарифВКопейках(ввод)).toBe(копейки);
  });

  it.each(["", "0", "-5", "1e3", "0x10", "10,005", "Infinity", "12,3,4", "сто"])(
    "«%s» — не тариф",
    (ввод) => {
      expect(тарифВКопейках(ввод)).toBeNull();
    },
  );
});
