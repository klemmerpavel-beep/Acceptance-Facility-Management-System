import { readdirSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { formatDay } from "./status.js";
import { деньМгновения, местныйДень, поМестнымДням } from "./today.js";

/**
 * «Сегодня» форм чека и платежа — местный день, а не UTC (фаза 0, дефект
 * K10). Служба уже считала день организации, а форма чека — по UTC: в
 * Воронеже с полуночи до трёх ночи она подставляла вчерашнюю дату и
 * отклоняла сегодняшний чек как чек из будущего, не дойдя до сервера.
 *
 * Граница та же, что у теста служб (`apps/api/src/common/org-day.test.ts`):
 * 00:30 седьмого ноября по Москве — по UTC ещё шестое. Рендер-тестов в
 * клиенте нет, поэтому второй рубеж — сами формы: правило дня у них одно,
 * и вписанный рядом день по UTC вернул бы дефект молча.
 */
const ГРАНИЦА = new Date("2026-11-06T21:30:00Z");

describe("местный день форм (K10)", () => {
  it("в 00:30 по Москве день — седьмое, хотя по UTC ещё шестое", () => {
    expect(ГРАНИЦА.toISOString().slice(0, 10)).toBe("2026-11-06");
    expect(местныйДень(ГРАНИЦА, "Europe/Moscow")).toBe("2026-11-07");
  });

  it("без пояса — день по часам браузера", () => {
    const сейчас = new Date();
    const двумя = (число: number): string => String(число).padStart(2, "0");
    expect(местныйДень(сейчас))
      .toBe(`${String(сейчас.getFullYear())}-${двумя(сейчас.getMonth() + 1)}-${двумя(сейчас.getDate())}`);
  });

  it.each(["ExpenseSheet.tsx", "PaymentSheet.tsx"])("%s берёт день помощником, а не срезом UTC", (имя) => {
    const текст = readFileSync(new URL(`./${имя}`, import.meta.url), "utf8");
    expect(текст).toContain('import { местныйДень } from "./today.js";');
    expect(текст).not.toMatch(/\.slice\(0, 10\)/u);
  });

  /* П-68: дни фиксации, поправки и скана акта в двойнике демонстрации —
     тот же помощник, что у форм; сервер считает их днём организации. Раздел
     актов двойника вырезается по его заголовкам: срезы UTC в других
     разделах двойника к актам не относятся. */
  it("двойник демонстрации: дни акта — местный день, а не срез UTC", () => {
    const текст = readFileSync(new URL("./api.demo.ts", import.meta.url), "utf8");
    const начало = текст.indexOf("--- акты выполненных работ");
    const конец = текст.indexOf("--- шаблоны документов организации");
    expect(начало).toBeGreaterThan(0);
    expect(конец).toBeGreaterThan(начало);
    const акты = текст.slice(начало, конец);
    expect(акты).not.toMatch(/\.slice\(0, 10\)/u);
    expect(акты.match(/местныйДень\(\)/gu)?.length).toBe(3);
  });
});

/**
 * П-74: «сегодня» оболочки и день мгновения события — местные (класс K10).
 *
 * Оболочка передавала экранам «сегодня» срезом UTC, а лента событий клала
 * событие под день по срезу UTC его мгновения, хотя время рядом писала
 * местным: проверка ветки 07.11.2026 в 00:50 по Москве восьмого ноября
 * увидела события этого часа под заголовком «Сб, 07 ноября». Граница — та же,
 * что выше: 00:30 по Москве — по UTC ещё вчера.
 */
describe("день мгновения и лента по дням (П-74)", () => {
  it("событие в 00:30 по Москве — московский день, а не вчерашний UTC", () => {
    expect("2026-11-06T21:30:00.000Z".slice(0, 10)).toBe("2026-11-06");
    expect(деньМгновения("2026-11-06T21:30:00.000Z", "Europe/Moscow")).toBe("2026-11-07");
    expect(деньМгновения("2026-11-06T20:59:59.000Z", "Europe/Moscow")).toBe("2026-11-06");
  });

  it("без пояса — день по часам браузера, тем же правилом, что «сегодня»", () => {
    const сейчас = new Date();
    expect(деньМгновения(сейчас.toISOString())).toBe(местныйДень(сейчас));
  });

  it("событие в 00:30 по Москве встаёт под свой день, а не под вчерашний", () => {
    const лента = [
      { at: "2026-11-07T21:50:00.000Z", title: "Транш № 7 закрыт" },
      { at: "2026-11-07T21:30:00.000Z", title: "Приёмка" },
      { at: "2026-11-07T20:30:00.000Z", title: "Чек подтверждён" },
    ];
    const дни = поМестнымДням(лента, "Europe/Moscow");
    expect(дни.map((день) => день.day)).toEqual(["2026-11-08", "2026-11-07"]);
    expect(дни[0]?.rows.map((запись) => запись.title)).toEqual(["Транш № 7 закрыт", "Приёмка"]);
    expect(дни[1]?.rows.map((запись) => запись.title)).toEqual(["Чек подтверждён"]);
    /* Заголовок пишет сам день группы: строка дня не сдвигается поясом. */
    expect(formatDay(дни[0]?.day ?? "")).toBe("вс, 08 ноября");
  });

  it("порядок ленты сохраняется: день, встреченный снова после другого, — новая группа", () => {
    const дни = поМестнымДням([
      { at: "2026-11-07T21:30:00.000Z" },
      { at: "2026-11-07T08:00:00.000Z" },
      { at: "2026-11-07T22:00:00.000Z" },
    ], "Europe/Moscow");
    expect(дни.map((день) => [день.day, день.rows.length])).toEqual([
      ["2026-11-08", 1], ["2026-11-07", 1], ["2026-11-08", 1],
    ]);
  });

  /* Страж: срез дня из мгновения по UTC — `.slice(0, 10)` строки ISO,
     `toISOString().split("T")` — не встречается ни в одном модуле клиента и
     двойника демонстрации. Рендер-тестов в клиенте нет, и вписанный рядом
     срез вернул бы дефект молча: день мгновения — `деньМгновения`, «сегодня»
     — `местныйДень`, календарная дата из API (`paidOn`, `signedAt`, дата
     документа) уже день и среза не требует. Тесты обходом не проверяются:
     граница суток в них показана срезом намеренно. */
  it("в модулях клиента нет среза дня по UTC", () => {
    const СРЕЗ = /\.(?:slice|substring|substr)\(\s*0\s*,\s*10\s*\)|\.split\(\s*["'`]T["'`]\s*\)/u;
    const корень = new URL("./", import.meta.url);
    const модули = readdirSync(корень, { recursive: true, encoding: "utf8" })
      .filter((путь) => /\.tsx?$/u.test(путь) && !/\.test\.tsx?$/u.test(путь));
    expect(модули).toContain("App.tsx");
    expect(модули).toContain("Dashboard.tsx");
    expect(модули).toContain("api.demo.ts");
    const срезы = модули.flatMap((путь) => readFileSync(new URL(путь, корень), "utf8")
      .split("\n")
      .flatMap((строка, номер) => (СРЕЗ.test(строка) ? [`${путь}:${String(номер + 1)}: ${строка.trim()}`] : [])));
    expect(срезы, "П-74: день мгновения срезом UTC — нужен деньМгновения или местныйДень (today.ts)").toEqual([]);
  });
});
