import { useState } from "react";
import { demoRole, setDemoRole, type DemoRole as Роль } from "./api.demo.js";

/**
 * Переключатель роли демонстрации.
 *
 * Существовал прежде и был снят доводом «пользователь у продукта один».
 * Довод отпал: ролей три — руководитель, прораб, заказчик, — и они
 * различаются составом экранов, а не только набором полей в ответе.
 * Посмотреть продукт глазами каждой иначе негде: демонстрация раздаётся
 * статикой и входа не имеет.
 *
 * **Это не разграничение доступа.** Запрет живёт в страже ролей на сервере,
 * которого у демонстрации нет. Переключатель меняет набор данных двойника —
 * тот самый, который сервер отдал бы вошедшему этой ролью; наборы сняты
 * тремя отдельными заходами съёмки со стенда. На живом сервере роль
 * приходит с сессией и переключению не поддаётся.
 *
 * Живёт только в демонстрации, как и приём замечаний: в продукте органа с
 * таким действием нет.
 */

const ПОДПИСИ: readonly { роль: Роль; подпись: string; что: string }[] = [
  { роль: "OWNER", подпись: "Руководитель", что: "весь продукт" },
  { роль: "FOREMAN", подпись: "Прораб", что: "свои объекты и приёмка" },
  { роль: "CLIENT", подпись: "Заказчик", что: "свой объект: ход работ и бумаги" },
];

export function DemoRoleSwitch({ onChange }: { onChange: () => void }): React.JSX.Element {
  const [роль, setРоль] = useState<Роль>(demoRole());
  const текущая = ПОДПИСИ.find((строка) => строка.роль === роль);

  return (
    <div className="demorole">
      <span className="demorole__label t-cap">Смотреть глазами</span>
      <div className="segmented" role="group" aria-label="Роль в демонстрации">
        {ПОДПИСИ.map((строка) => (
          <button
            key={строка.роль}
            type="button"
            className="segmented__option"
            aria-pressed={роль === строка.роль}
            onClick={() => {
              setDemoRole(строка.роль);
              setРоль(строка.роль);
              onChange();
            }}
          >
            {строка.подпись}
          </button>
        ))}
      </div>
      {/* Что видит выбранная роль — рядом с выбором, а не под ним: иначе
          переключатель отвечает на «кто», не отвечая на «что». */}
      <span className="demorole__note t-sm t-muted">{текущая?.что}</span>
    </div>
  );
}
