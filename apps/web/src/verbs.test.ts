import { readdirSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { ГЛАГОЛЫ } from "./verbs.js";

/**
 * Один глагол на одно действие.
 *
 * Продукт называл заведение записи четырьмя глаголами, и пара «кнопка раздела
 * → кнопка листа» расходилась в строю во всех четырёх случаях: «Добавить
 * объект» открывал лист с кнопкой «Завести объект». Свести их мало — без
 * стража пятый глагол напишется на следующем экране тем же способом, каким
 * написались первые четыре.
 *
 * Стережётся свойство, а не список мест: снятые глаголы не должны стоять в
 * коде экрана строковым литералом. Ищется литерал в двойных кавычках — тот
 * вид, в каком его пишет разметка; слово в русских кавычках внутри
 * комментария правилом не затрагивается.
 */
const КОРЕНЬ = new URL("./", import.meta.url).pathname;
const СВОЙ = "verbs.ts";

/**
 * Снятые глаголы кнопок.
 *
 * Глаголы правки и подтверждения сюда не входят: «Сохранить», «Принять»,
 * «Подтвердить» называют другие действия, и сводить их к одному слову
 * значило бы стереть разницу, которая есть.
 *
 * «Новый объект» и «Новая заявка» тоже не входят, и это не послабление:
 * лист называет вещь, кнопка называет действие. «Новый объект» заголовком
 * листа и «Добавить объект» кнопкой в нём — не разнобой, а разделение ролей.
 * Разнобоем было то, что «Новая заявка» стояла подписью кнопки раздела; эта
 * подпись снята, и от возврата её стережёт не запрет слова, а то, что все
 * подписи заведения берутся из перечня ниже.
 */
const СНЯТЫЕ = ["Завести", "Внести"];

const экраны = readdirSync(КОРЕНЬ, { withFileTypes: true })
  .filter((узел) => узел.isFile())
  .map((узел) => узел.name)
  .filter((имя) => /\.tsx?$/u.test(имя) && !имя.endsWith(".test.ts") && имя !== СВОЙ);

const разметка = (): string =>
  экраны.map((имя) => readFileSync(КОРЕНЬ + имя, "utf8")).join("\n");

describe("глаголы действий", () => {
  it.each(СНЯТЫЕ)("«%s» не открывает подпись кнопки заведения", (глагол) => {
    /* Ищется глагол с существительным следом: «Завести объект» — подпись
       кнопки, а «Заведите первый объект» внутри пустого состояния — речь, и
       запрещать её значило бы запрещать язык.

       Кавычки вокруг подписи не требуются. Первая редакция правила искала
       литерал в двойных кавычках и пропустила откат, вернувший подпись голым
       текстом разметки, — а это и есть самый вероятный вид возврата: в JSX
       подпись кнопки пишется без кавычек.

       Блочные комментарии и русские кавычки вырезаются до проверки.
       Комментарий объясняет, а не печатается, и «завести график из разделов
       сметы» в описании доменного правила — речь о действии, а не подпись
       кнопки. Запрещать слово в описании значило бы запрещать язык там, где
       его никто не читает с экрана; подписи в комментарии не живут, и слепота
       к ним ничего не стоит. */
    const нарушители = экраны.filter((имя) => {
      const текст = readFileSync(КОРЕНЬ + имя, "utf8")
        .replace(/\/\*[\s\S]*?\*\//gu, "")
        .replace(/«[^»]*»/gu, "");
      /* Граница слова `\\b` определена на латинице: перед кириллической «З»
         её нет, и выражение с ней не находило ничего — правило молчало на
         возвращённом глаголе. Тот же недосмотр уже чинился в страже чисел
         документов. */
      return new RegExp(`${глагол} [а-яё]`, "u").test(текст);
    });
    expect(нарушители).toEqual([]);
  });

  it("в перечне глаголов нет мёртвых записей", () => {
    const текст = разметка();
    const мёртвые = Object.keys(ГЛАГОЛЫ)
      .filter((ключ) => !new RegExp(`завести\\("${ключ}"`, "u").test(текст));
    expect(мёртвые).toEqual([]);
  });

  it("все подписи начинаются одним глаголом", () => {
    const чужие = Object.entries(ГЛАГОЛЫ)
      .filter(([, подпись]) => !подпись.startsWith("Добавить "))
      .map(([ключ]) => ключ);
    expect(чужие).toEqual([]);
  });
});
