import { dayInZone } from "@priyomka/domain";

/**
 * Сегодняшний день по часам и поясу браузера в виде `ГГГГ-ММ-ДД`.
 *
 * Формы чека и платежа проверяют дату до обращения к сети тем же правилом,
 * что сервер, а сервер считает «сегодня» днём организации по её часовому
 * поясу (фаза 0, дефект K10). Форма чека брала день по UTC: в Воронеже с
 * полуночи до трёх ночи она подставляла вчерашнюю дату, а чек с
 * сегодняшней отклоняла как чек из будущего ещё до сервера — исправление
 * службы до человека не доходило. Форма платежа брала сегодняшний день по
 * часам браузера, а день открытия транша — по UTC; помощник у двух форм
 * теперь один.
 *
 * День считается тем же правилом `dayInZone`, что `orgDay` сервера; пояс —
 * браузера: прораб и руководитель работают в поясе своей организации.
 * Мгновение и пояс — доводы, иначе граница суток не испытывается.
 */
export function местныйДень(
  at: Date = new Date(),
  timeZone: string = Intl.DateTimeFormat().resolvedOptions().timeZone,
): string {
  return dayInZone(at, timeZone);
}

/**
 * День мгновения события `ГГГГ-ММ-ДД` в поясе браузера (П-74).
 *
 * Время события экраны показывают по часам браузера (`formatTime`), а день
 * того же события брали срезом UTC его мгновения: в Воронеже с полуночи до
 * трёх ночи событие стояло под вчерашней датой рядом со своим верным
 * временем. День и время одного события читаются в одном поясе; правило дня
 * — то же `местныйДень`, что у «сегодня» оболочки и форм.
 *
 * Календарную дату из ответа API (`paidOn`, `signedAt`, день из сервера)
 * сюда не передают: она уже день, и перевод сдвинул бы её к западу от
 * Гринвича на вчера.
 */
export function деньМгновения(мгновение: string, timeZone?: string): string {
  return местныйДень(new Date(мгновение), timeZone);
}

/**
 * Лента событий по местным дням (П-74): подряд идущие записи одного дня —
 * одна группа, порядок записей сохраняется. Лента приходит от новых к
 * старым, и группа дня собирается из соседей, а не сортировкой: порядок —
 * дело сервера.
 */
export function поМестнымДням<T extends { readonly at: string }>(
  записи: readonly T[],
  timeZone?: string,
): { day: string; rows: T[] }[] {
  const дни: { day: string; rows: T[] }[] = [];
  for (const запись of записи) {
    const day = деньМгновения(запись.at, timeZone);
    const последний = дни.at(-1);
    if (последний?.day === day) последний.rows.push(запись);
    else дни.push({ day, rows: [запись] });
  }
  return дни;
}
