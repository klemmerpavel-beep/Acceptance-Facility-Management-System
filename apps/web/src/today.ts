import { dayInZone } from "@priyomka/domain";

/**
 * Сегодняшний день по часам и поясу браузера в виде `ГГГГ-ММ-ДД`.
 *
 * Формы чека и платежа проверяют дату до обращения к сети тем же правилом,
 * что сервер, а сервер считает «сегодня» днём организации по её часовому
 * поясу (фаза 0, дефект K10). Форма чека брала день по UTC: в Воронеже с
 * полуночи до трёх ночи она подставляла вчерашнюю дату, а чек с
 * сегодняшней отклоняла как чек из будущего ещё до сервера — исправление
 * службы до человека не доходило. Форма платежа брала сегодняшний день по
 * часам браузера, а день открытия транша — по UTC; помощник у двух форм
 * теперь один.
 *
 * День считается тем же правилом `dayInZone`, что `orgDay` сервера; пояс —
 * браузера: прораб и руководитель работают в поясе своей организации.
 * Мгновение и пояс — доводы, иначе граница суток не испытывается.
 */
export function местныйДень(
  at: Date = new Date(),
  timeZone: string = Intl.DateTimeFormat().resolvedOptions().timeZone,
): string {
  return dayInZone(at, timeZone);
}
