import { readdirSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * Объявленная роль обязывает целиком.
 *
 * `role="dialog"` с `aria-modal="true"` — не подпись, а обещание поведения:
 * Escape закрывает, Tab не уходит за лист, фокус возвращается к тому, что
 * лист открыло. Девятнадцать листов держали это обещание общим
 * `useModalDialog`, а лист «Новый человек» и лист правки шаблона объявляли
 * роль и не держали ничего: Escape их не закрывал, Tab уводил под лист
 * (полный аудит 30.09.2026, П-30). Тот же довод записан нормативом
 * `03_DESIGN_SYSTEM.md`, раздел 33.1, для вкладок.
 *
 * Проверяется свойство, а не список листов: модуль, объявивший роль диалога,
 * обязан позвать общий контракт и повесить его опору на сам лист.
 */
const КОРЕНЬ = new URL("./", import.meta.url).pathname;

const листы = readdirSync(КОРЕНЬ)
  .filter((имя) => имя.endsWith(".tsx"))
  .map((имя) => ({ имя, текст: readFileSync(`${КОРЕНЬ}${имя}`, "utf8") }))
  .filter(({ текст }) => текст.includes('role="dialog"'));

describe("лист держит клавиатурный контракт", () => {
  it("листов с ролью диалога больше одного: правило проверяет не пустое место", () => {
    expect(листы.length).toBeGreaterThan(10);
  });

  it.each(листы.map(({ имя }) => имя))("%s", (имя) => {
    const текст = листы.find((лист) => лист.имя === имя)?.текст ?? "";
    const диалогов = (текст.match(/role="dialog"/gu) ?? []).length;
    const контрактов = (текст.match(/useModalDialog\s*(?:<[^>]*>)?\s*\(/gu) ?? []).length;
    const опор = (текст.match(/role="dialog"[^>]*ref=\{/gu) ?? []).length;
    expect({ диалогов, контрактов: Math.min(контрактов, диалогов), опор })
      .toEqual({ диалогов, контрактов: диалогов, опор: диалогов });
  });
});
