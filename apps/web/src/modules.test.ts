import { readdirSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * Мёртвые модули.
 *
 * `Directory.tsx` прожил в дереве 116 строк, ни разу не будучи
 * импортированным: живым экраном контрагентов давно был `Contacts.tsx`, а
 * прежняя версия осталась рядом и читалась как действующая. Вреда от неё
 * больше, чем пустого места: два разных словаря одного справочника
 * («Заказчики» и «Бригады» против «Справочник» и «Тип») жили в одном
 * каталоге, и правка попадала то в один, то в другой.
 *
 * Проверка общая, а не именная: модуль клиента обязан быть кому-то нужен.
 */
const КОРЕНЬ = new URL("./", import.meta.url).pathname;

/**
 * Точки входа и файлы, которые по устройству не импортируются по имени.
 *
 * `api.demo.ts` подставляется вместо `api.ts` подключаемым модулем сборки
 * демонстрации (`apps/web/vite.demo.config.ts`): экраны просят `./api.js`,
 * и запрос разрешается в двойника. Искать его имя в импортах бессмысленно —
 * его там нет и быть не должно.
 */
const ВХОДЫ = new Set(["main.tsx", "main.demo.tsx", "api.demo.ts"]);

const исходники = readdirSync(КОРЕНЬ, { withFileTypes: true })
  .filter((узел) => узел.isFile())
  .map((узел) => узел.name)
  .filter((имя) => /\.tsx?$/u.test(имя))
  .filter((имя) => !имя.endsWith(".test.ts") && !имя.endsWith(".test.tsx"))
  .filter((имя) => !ВХОДЫ.has(имя));

const тексты = исходники.map((имя) => readFileSync(`${КОРЕНЬ}${имя}`, "utf8"));
const все = [
  ...тексты,
  readFileSync(`${КОРЕНЬ}main.tsx`, "utf8"),
  readFileSync(`${КОРЕНЬ}main.demo.tsx`, "utf8"),
].join("\n");

describe("мёртвые модули", () => {
  it.each(исходники)("%s кем-то импортируется", (имя) => {
    const основа = имя.replace(/\.tsx?$/u, "");
    /* Импорт пишется с расширением `.js` — так требует `verbatimModuleSyntax`
       вместе с резолвером Node: `./Contacts.js` для файла `Contacts.tsx`. */
    const образец = new RegExp(`from "\\./${основа}\\.js"|from "\\./${основа}"`, "u");
    /* Из общего текста вычитается сам модуль: файл, импортирующий себя,
       импортированным не считается. */
    const чужие = исходники
      .filter((другое) => другое !== имя)
      .map((другое) => readFileSync(`${КОРЕНЬ}${другое}`, "utf8"))
      .concat([
        readFileSync(`${КОРЕНЬ}main.tsx`, "utf8"),
        readFileSync(`${КОРЕНЬ}main.demo.tsx`, "utf8"),
      ])
      .join("\n");
    expect(образец.test(чужие), `${имя} не импортирован ниоткуда`).toBe(true);
  });

  it("общий текст модулей прочитан", () => {
    expect(все.length).toBeGreaterThan(1000);
  });
});
