import type React from "react";

/**
 * Объявление изменения для чтения с экрана.
 *
 * Экран показывает результат действия перерисовкой: принятая позиция
 * меняет число, закрытый транш — пилюлю состояния. Тот, кто экран не видит,
 * узнаёт об этом только из живой области — иначе действие проходит молча, и
 * подтверждением остаётся лишь то, что кнопка не выдала отказа.
 *
 * **Область стоит в разметке всегда, даже когда объявлять нечего.**
 * Область, добавленная в дерево вместе с текстом, читалкой не объявляется:
 * она замечает изменение внутри уже существующей области, а не появление
 * новой. Правило найдено на правке поля объекта (`FieldEdit.tsx`) и с тех
 * пор общее.
 *
 * Объявляется то, что иначе не узнать: «принято», «сторнировано»,
 * «подписан». Область, читающая каждое движение, перестаёт нести смысл —
 * её выключают вместе с полезным.
 */
export function Announce({ text }: { text: string | null }): React.JSX.Element {
  return <span role="status" className="visually-hidden">{text ?? ""}</span>;
}
