import { useRef } from "react";

/**
 * Список «Ещё»: служебные экраны и выход.
 *
 * Появился выносом, а не написанием. Список жил в шапке внутри `<nav
 * className="appbar__nav">`, а это правило скрывает целиком ниже 768 px —
 * вместе с ним пропадали «Что дальше» и «Выйти». Нижняя таб-панель собиралась
 * только из разделов, шестого пункта в ней не было, и на телефоне из продукта
 * нельзя было выйти ничем: единственный путь наружу лежал в скрытом узле.
 * Работает там прораб.
 *
 * Список вынесен в один компонент, а не написан второй раз для таб-панели.
 * Второе написание того же поведения расходится с первым на третьей правке —
 * так уже было с ловушкой фокуса, и так появился `modal.ts`.
 *
 * Собран на `<details>`: раскрытие, закрытие по Escape и обход с клавиатуры
 * даёт браузер. Своего состояния для этого не нужно, и состояние, которого
 * нет, не разъезжается между двумя местами вывода.
 */

export interface ПунктЕщё {
  label: string;
  onSelect: () => void;
}

export function MoreMenu({
  пункты,
  className,
  классКнопки,
  классСписка,
  children,
}: {
  пункты: readonly ПунктЕщё[];
  /** Класс самого `<details>`: в шапке и в таб-панели он стоит по-разному. */
  className: string;
  /** Класс `<summary>` — он выглядит как соседние пункты своего ряда. */
  классКнопки: string;
  /** Класс выпадающего списка: в шапке он падает вниз, в таб-панели — вверх. */
  классСписка: string;
  /** Содержимое кнопки: подпись и значок. */
  children: React.ReactNode;
}): React.JSX.Element {
  /* Список закрывается сам после выбора: раскрытый список поверх нового
     экрана — забытое состояние, а не подсказка. */
  const узел = useRef<HTMLDetailsElement>(null);
  const закрыть = (): void => {
    if (узел.current !== null) узел.current.open = false;
  };

  return (
    <details className={className} ref={узел}>
      <summary className={классКнопки}>{children}</summary>
      <div className={классСписка}>
        {пункты.map((пункт) => (
          <button
            key={пункт.label}
            type="button"
            className="appbar__menu-item"
            onClick={() => { закрыть(); пункт.onSelect(); }}
          >
            {пункт.label}
          </button>
        ))}
      </div>
    </details>
  );
}
