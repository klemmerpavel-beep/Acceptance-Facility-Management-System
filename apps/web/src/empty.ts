/**
 * Отсутствие величины: три случая — три вида.
 *
 * Продукт обозначал отсутствие четырьмя способами и двенадцатью разными
 * формулировками. Прочерк, слово, ноль и молчание стояли вперемешку: срок
 * объекта на одном экране печатался и как «не задан», и как «—», а честный
 * ноль в колонке «Итог смет» подменялся прочерком — «смет нет» становилось
 * неотличимо от «смет на ноль рублей».
 *
 * Случаев ровно три, и различать их обязательно: читатель, увидевший одно
 * обозначение на все три, перестаёт верить и остальным числам экрана.
 *
 *   1. **Величина есть и равна нулю** — печатается числом. Ноль есть факт, и
 *      прятать его нельзя: «принято 0,00 ₽» — сведение, «—» — умолчание.
 *   2. **Величину не заполнили** — печатается словом из закрытого словаря
 *      ниже. Слово называет, чего недостаёт, и потому подсказывает действие;
 *      прочерк на его месте заставляет гадать.
 *   3. **Величины нет в природе** — печатается прочерком. У бригады не бывает
 *      кода заказчика, у прораба не бывает внутренних сумм: заполнять нечего,
 *      и слово «не задано» обещало бы поле, которого не существует.
 *
 * Форм у слова две, и это не прихоть языка, а следствие раскладки. В
 * подписанной графе подпись уже назвала величину, и полная форма читается
 * дважды: «Срок: срок не задан». Отдельно стоящая строка, наоборот, без
 * существительного не понятна: «не задан» — что именно.
 *
 * Словарь закрыт намеренно. Открытый словарь — это и есть двенадцать
 * формулировок: каждый экран изобретал свою, и «не задан», «не задано», «не
 * задана», «нет», «сметы нет», «не начаты» жили рядом, означая одно.
 */

/** Прочерк для случая 3. Тире, а не дефис: это типографский знак, не перенос. */
export const ПРОЧЕРК = "—";

interface Отсутствие {
  /** В подписанной графе: подпись уже назвала величину. */
  краткое: string;
  /** Отдельной строкой: без существительного непонятно, о чём речь. */
  полное: string;
}

export const НЕ_ЗАПОЛНЕНО = {
  срок: { краткое: "не задан", полное: "срок не задан" },
  сроки: { краткое: "не заданы", полное: "сроки не заданы" },
  началоРабот: { краткое: "не начаты", полное: "работы не начаты" },
  прораб: { краткое: "не назначен", полное: "прораб не назначен" },
  бригада: { краткое: "не назначена", полное: "бригада не назначена" },
  смета: { краткое: "нет", полное: "сметы нет" },
  график: { краткое: "не заведён", полное: "график не заведён" },
  готовность: { краткое: "не задана", полное: "готовность не задана" },
  приёмка: { краткое: "нет", полное: "приёмки нет" },
  транш: { краткое: "нет", полное: "открытого транша нет" },
  снимки: { краткое: "нет", полное: "снимков пока нет" },
  основание: { краткое: "не указано", полное: "основание не указано" },
  причина: { краткое: "не названа", полное: "причина не названа" },
} as const satisfies Record<string, Отсутствие>;

export type ЧегоНет = keyof typeof НЕ_ЗАПОЛНЕНО;

/**
 * Слово для случая 2.
 *
 * Через функцию, а не прямым обращением к словарю: так все места
 * употребления находятся поиском по одному имени, и тринадцатая формулировка
 * не проскочит мимо словаря незамеченной.
 */
export const пусто = (что: ЧегоНет, форма: keyof Отсутствие = "полное"): string =>
  НЕ_ЗАПОЛНЕНО[что][форма];

/**
 * Слово с прописной: там, где оно начинает строку — заголовок пустого
 * состояния, отдельное предложение. Помощником, а не второй записью словаря:
 * заглавная копия слова разошлась бы со строчной на первой же правке.
 */
export const Пусто = (что: ЧегоНет, форма: keyof Отсутствие = "полное"): string => {
  const слово = пусто(что, форма);
  return слово.charAt(0).toUpperCase() + слово.slice(1);
};
