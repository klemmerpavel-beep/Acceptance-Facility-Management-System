import type { ExpenseStatus, Tranche } from "@priyomka/contracts";
import { plural } from "./status.js";

/**
 * Чей ход — закрытый словарь (этап Э8, ДР-4).
 *
 * Пилюли называли состояние — «Закрыт», «Не подписан», «Черновик», — но не
 * называли, чьего действия ждут и сколько. Ответ «кто должен действовать»
 * читался из трёх мест сразу: пилюли, даты и знания процесса. Строка «чей
 * ход» говорит это одной фразой до чтения подробностей.
 *
 * Словарь закрыт тем же правилом, что шкала срочности (`due.ts`) и словарь
 * отсутствия (`empty.ts`): фраза собирается только здесь. Экран, написавший
 * «ждёт подписи» своими словами, разошёлся бы со словарём на первой правке,
 * и одно состояние называлось бы двумя оборотами. Обход ловит
 * `turn.test.ts`.
 */

/** День и месяц: «05.10». Год не пишется — строка о текущих делах. */
const ДЕНЬ_МЕСЯЦ = (iso: string): string => {
  const [, месяц = "", число = ""] = iso.slice(0, 10).split("-");
  return `${число}.${месяц}`;
};

/** Обороты словаря. Других фраз «чей ход» в продукте нет. */
export const ХОД = {
  оплата: "ждёт оплаты заказчиком",
  подпись: "Сформирован · ждёт подписи заказчика",
  черновик: "Черновик · ждёт руководителя",
  ждём: "Ждём",
} as const;

/** Сколько ждёт: «3 дня»; меньше суток — «меньше дня», а не «0 дней». */
const СКОЛЬКО = (дней: number): string =>
  дней === 0 ? "меньше дня" : `${String(дней)} ${plural(дней, "день", "дня", "дней")}`;

/**
 * Транш: закрыт и ждёт оплаты — «Закрыт 12.09 · ждёт оплаты заказчиком ·
 * 3 дня». Открытый транш копит выработку, оплаченный — ничего не ждёт:
 * у обоих строки нет. Дни приходят с сервера тем же правилом и тем же днём
 * организации, что «ждёт N дней» в бухгалтерии.
 */
export function trancheTurn(
  транш: Pick<Tranche, "status" | "closedAt" | "awaitingDays">,
): string | null {
  if (транш.status !== "CLOSED" || транш.closedAt === null || транш.awaitingDays === null) return null;
  return `Закрыт ${ДЕНЬ_МЕСЯЦ(транш.closedAt)} · ${ХОД.оплата} · ${СКОЛЬКО(транш.awaitingDays)}`;
}

/** Акт: сформирован и ждёт подписи заказчика либо подписан — с датой. */
export function actTurn(signedAt: string | null): string {
  return signedAt === null ? ХОД.подпись : `Подписан ${ДЕНЬ_МЕСЯЦ(signedAt)}`;
}

/** Чек: черновик ждёт руководителя; подтверждённый и отклонённый — ничего. */
export function expenseTurn(status: ExpenseStatus): string | null {
  return status === "DRAFT" ? ХОД.черновик : null;
}

/** Объект в «Ждёт ответа»: «Ждём: что и от кого». Поля нет — строки нет. */
export function waitingTurn(waitingFor: string | null): string | null {
  return waitingFor === null ? null : `${ХОД.ждём}: ${waitingFor}`;
}
