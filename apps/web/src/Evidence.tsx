/**
 * Значок доказательности на строке (этап Э8, ДР-7).
 *
 * Чем подтверждена запись, читалось только после открытия: снимок пакета
 * приёмки лежал в отчёте, снимок чека — за нажатием, скан акта — в его
 * листе. Значок говорит это до открытия: у строки есть снимок или приложен
 * скан.
 *
 * Значок не цветной намеренно: смысл несёт рисунок и имя для программы
 * чтения экрана, а не тон (правило 1 норматива — цвет только второй канал).
 * Имя записано полностью, а не собрано из частей: поиск по подписи в
 * проверках и в коде находит его целиком.
 */
const ЗНАК = {
  photo: { href: "#i-photo", подпись: "Есть снимок" },
  scan: { href: "#i-scan", подпись: "Приложен скан" },
} as const;

export function EvidenceMark({ kind }: { kind: keyof typeof ЗНАК }): React.JSX.Element {
  const знак = ЗНАК[kind];
  return (
    <span className="evidence" role="img" aria-label={знак.подпись} title={знак.подпись}>
      <svg className="icon icon--sm" aria-hidden="true"><use href={знак.href} /></svg>
    </span>
  );
}
