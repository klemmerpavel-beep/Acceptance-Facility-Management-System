import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * Айдентика: одно написание и один знак.
 *
 * Продукт называл себя тремя способами сразу. `DOLSTUDIO` стоял в шапке, на
 * экране входа и в заголовке вкладки; `DOLGIY STUDIO` приходил из данных и
 * печатался крошкой обложки на каждом экране; «Приёмка» жила только в
 * заголовках файлов стилей и в документах, то есть нигде, где её видит
 * человек. Знаков было два: бирка в шапке и квадрат с галочкой на входе,
 * причём второй — рабочий значок отметки позиции, повторяющийся на экране
 * приёмки девять раз подряд.
 *
 * Правило стережётся тестом, а не обходом страницы. Обход видит одну
 * собранную страницу и не видит ни второго шаблона, ни сборщика
 * демонстрации: написание, вернувшееся в `index.demo.html`, он пропустил бы
 * молча.
 *
 * Написание студии выбрано не вкусом: `DOLGIY STUDIO` лежит в начальном
 * наполнении базы и в слепке демонстрации, и всякое другое потребовало бы
 * правки данных — то есть обратной совместимости и пересъёмки слепка.
 */
const КОРЕНЬ = new URL("../", import.meta.url).pathname;
const прочитать = (путь: string): string => readFileSync(`${КОРЕНЬ}${путь}`, "utf8");

const МЕСТА = [
  "src/App.tsx",
  "src/SignIn.tsx",
  "index.html",
  "index.demo.html",
  "../../scripts/build-demo.mjs",
];

const ЗАГОЛОВОК = "Приёмка — DOLGIY STUDIO";

describe("айдентика", () => {
  it.each(МЕСТА)("в %s нет снятого написания DOLSTUDIO", (путь) => {
    expect(прочитать(путь)).not.toContain("DOLSTUDIO");
  });

  it("шапка называет продукт и студию", () => {
    const шапка = прочитать("src/App.tsx");
    expect(шапка).toContain(">Приёмка<");
    expect(шапка).toContain(">DOLGIY STUDIO<");
  });

  it("экран входа несёт тот же лока́п", () => {
    const вход = прочитать("src/SignIn.tsx");
    expect(вход).toContain(">Приёмка<");
    expect(вход).toContain(">DOLGIY STUDIO<");
  });

  it.each(["index.html", "index.demo.html", "../../scripts/build-demo.mjs"])(
    "заголовок вкладки в %s один и тот же",
    (путь) => {
      expect(прочитать(путь)).toContain(`<title>${ЗАГОЛОВОК}</title>`);
    },
  );

  /**
   * Знак один на три знаковых места. Сравниваются сами контуры, а не имя
   * символа: значок страницы объявлен строкой данных в шаблоне и на набор
   * значков не ссылается — совпадение имён там невозможно в принципе, а
   * совпадение рисунка проверяемо.
   */
  it("знак страницы рисует то же, что знак шапки", () => {
    const набор = прочитать("src/Sprite.tsx");
    const символ = набор.slice(набор.indexOf('id="i-mark"'));
    const контуры = [...символ.slice(0, символ.indexOf("</symbol>"))
      .matchAll(/\sd="([^"]+)"/gu)].map((пара) => пара[1]);
    expect(контуры.length).toBeGreaterThan(0);
    for (const шаблон of ["index.html", "index.demo.html"]) {
      const значок = прочитать(шаблон);
      for (const контур of контуры) expect(значок).toContain(контур);
    }
  });

  it("экран входа и шапка ссылаются на один символ", () => {
    for (const путь of ["src/App.tsx", "src/SignIn.tsx"]) {
      expect(прочитать(путь)).toContain('href="#i-mark"');
      expect(прочитать(путь)).not.toContain('<use href="#i-acceptance" />\n        <span');
    }
  });
});
