import { readdirSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * Одна роль — одно слово.
 *
 * Роль `CLIENT` продукт называет «заказчиком»: так она подписана в выборе
 * роли, в справочнике, на карточке и в документах — больше ста тридцати
 * мест. В пяти местах рядом стоял «клиент»: «Итог сметы для клиента» на
 * карточке при «итоге для заказчика» в подвале сметы той же карточки,
 * «Сумма платежа клиента» в листе транша, «Клиентский» вид акта и имя
 * печатного файла (полный аудит 30.09.2026, П-44). Человек, встретив два
 * слова, ищет два понятия.
 *
 * Проверяется текст разметки, а не комментарии: в них «клиентская
 * проекция» — имя механизма из документов, а не подпись на экране.
 */
const КОРЕНЬ = new URL("./", import.meta.url).pathname;
const безКомментариев = (текст: string): string => текст
  .replace(/\{\/\*[\s\S]*?\*\/\}/gu, "")
  .replace(/\/\*[\s\S]*?\*\//gu, "")
  .replace(/^\s*\/\/.*$/gmu, "");

const модули = readdirSync(КОРЕНЬ)
  .filter((имя) => имя.endsWith(".tsx"))
  .map((имя) => ({ имя, текст: безКомментариев(readFileSync(`${КОРЕНЬ}${имя}`, "utf8")) }));

describe("словарь ролей", () => {
  it("модулей экрана достаточно: правило проверяет не пустое место", () => {
    expect(модули.length).toBeGreaterThan(30);
  });

  it("роль заказчика не называется «клиентом» ни на одном экране", () => {
    /* Видимое — строки и текст разметки; имя переменной `клиенты` видно
       только читающему код. Кусок с «;» или «=» — код между угловыми
       скобками обобщённого типа, а не текст. */
    const видимое = (текст: string): string[] => [
      ...текст.matchAll(/"[^"\n]*"|'[^'\n]*'|`[^`]*`|>[^<>{}]+</gu),
    ].map((пара) => пара[0]).filter((кусок) => !/[;=]/u.test(кусок));
    const найдено = модули.flatMap(({ имя, текст }) => видимое(текст)
      .filter((кусок) => /[Кк]лиент/u.test(кусок))
      .map((кусок) => `${имя}: ${кусок.trim().slice(0, 60)}`));
    expect(найдено).toEqual([]);
  });
});

/**
 * Число со словом — согласованно.
 *
 * Подпись, написанная под «много», читается верно только на части чисел:
 * «152 рабочих дней прошло» стояло на карточке (П-29), «1 пакетов приёмки» —
 * на траншах, «2 объектов» — в доступном имени полосы портфеля, а сервер
 * писал в журнал и в отказы «1 пунктов», «1 позиций», «2 этапов» (полный
 * аудит 30.09.2026, П-48). Правило одно и живёт в домене — `plural` и
 * `сколько`. Здесь ищется его обход: подстановка числа прямо перед
 * существительным в форме «много».
 */
const МНОГО = [
  "объектов", "позиций", "разделов", "этапов", "дней", "записей", "строк", "чеков", "пакетов",
  "траншей", "помещений", "заявок", "бригад", "шаблонов", "пунктов", "документов", "снимков",
  "задач", "заказчиков", "прорабов", "актов", "платежей", "проёмов", "единиц",
].join("|");
const ОБХОД = new RegExp(`(?:\\$\\{[^}]+\\}|\\{[^}"]+\\})\\s+(?:${МНОГО})(?![а-яё])`, "u");

const СЕРВЕР = new URL("../../api/src/", import.meta.url).pathname;
const исходники = (корень: string, путь = ""): { имя: string; текст: string }[] =>
  readdirSync(`${корень}${путь}`, { withFileTypes: true }).flatMap((запись) => {
    const имя = `${путь}${запись.name}`;
    if (запись.isDirectory()) return исходники(корень, `${имя}/`);
    if (!/\.tsx?$/u.test(запись.name) || запись.name.includes(".test.")) return [];
    return [{ имя, текст: безКомментариев(readFileSync(`${корень}${имя}`, "utf8")) }];
  });

describe("число согласовано со словом", () => {
  it.each([
    ["экраны", КОРЕНЬ],
    ["сервер", СЕРВЕР],
  ])("%s: число не подставлено перед словом в форме «много»", (_, корень) => {
    const найдено = исходники(корень).flatMap(({ имя, текст }) => текст.split("\n")
      .filter((строка) => ОБХОД.test(строка))
      .map((строка) => `${имя}: ${строка.trim().slice(0, 70)}`));
    expect(найдено).toEqual([]);
  });
});
