import { describe, expect, it } from "vitest";
import { reversePaymentSchema } from "@priyomka/contracts";
import { причинаСторноГотова } from "./PaymentSheet.js";

/**
 * Отказ показывается до обращения к сети — и тем же правилом, что применит
 * сервер. Лист сторно платежа пускал причину от одного знака при трёх в
 * контракте, и «ок» уходило на сервер за отказом, текст которого просил
 * назвать уже названную причину (полный аудит 30.09.2026, П-26).
 *
 * Сверяются граничные строки: пустая, из пробелов, короче порога, ровно на
 * пороге и обычная. Правило листа обязано совпасть с правилом контракта на
 * каждой.
 */
describe("сторно платежа: причина", () => {
  it.each(["", "   ", "ок", "  ок  ", "дубль", "платёж внесён дважды по ошибке"])(
    "«%s»: лист решает так же, как сервер",
    (причина) => {
      expect(причинаСторноГотова(причина)).toBe(reversePaymentSchema.safeParse({ reason: причина }).success);
    },
  );
});
