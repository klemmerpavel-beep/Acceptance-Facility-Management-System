/**
 * Снимки объектов демонстрации.
 *
 * Каталог `photos/` читается сборкой, а не перечисляется руками: список,
 * набранный в коде, разошёлся бы с каталогом на первом же добавленном файле,
 * и добавление снимка требовало бы правки кода — ровно того, чего здесь
 * быть не должно.
 *
 * Имя файла — код объекта. Связь по имени, а не по отдельной таблице
 * соответствия: таблица есть второе место для той же величины.
 */
const файлы = import.meta.glob<string>("./photos/*.{jpg,jpeg,png,webp}", {
  eager: true,
  query: "?url",
  import: "default",
});

const ПО_КОДУ = new Map<string, string>(
  Object.entries(файлы).map(([путь, адрес]) => {
    const имя = путь.slice(путь.lastIndexOf("/") + 1);
    return [имя.slice(0, имя.lastIndexOf(".")), адрес];
  }),
);

/** Адрес снимка объекта. Пусто — файла нет, экран нарисует подложку. */
export const снимокОбъекта = (code: string): string | null => ПО_КОДУ.get(code) ?? null;

/** Есть ли у объекта собственный снимок. */
export const естьСнимок = (code: string): boolean => ПО_КОДУ.has(code);
