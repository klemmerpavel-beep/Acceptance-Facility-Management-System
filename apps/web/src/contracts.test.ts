import * as контракт from "@priyomka/contracts";
import { describe, expect, it } from "vitest";

/**
 * Обязательное текстовое поле контракта не принимает строку из пробелов.
 *
 * Листы продукта обрезают пробелы сами, и сервер это правило повторял почти
 * везде — `.trim()` перед `.min()`. В шести полях обрезки не было: имя
 * человека, которому выдают вход, название организации, помещение обмера,
 * название и пункт шаблона документа, код объекта при выпуске. Запрос мимо
 * листа заводил человека с именем «   » — сервер отвечал 201 (полный аудит
 * 30.09.2026, П-45). Правило экрана и правило сервера расходились, и
 * держалось второе только потому, что первое стояло на пути.
 *
 * Проверяется свойство всего контракта, а не перечень полей: новое поле без
 * обрезки упадёт здесь в день появления.
 */
interface Схема {
  _def: { typeName?: string; innerType?: Схема; schema?: Схема; checks?: { kind: string; value?: number }[] };
  safeParse: (значение: unknown) => { success: boolean };
  shape?: Record<string, Схема>;
}

const развернуть = (схема: Схема): Схема => {
  const { typeName, innerType, schema } = схема._def;
  if ((typeName === "ZodOptional" || typeName === "ZodNullable" || typeName === "ZodDefault") && innerType) {
    return развернуть(innerType);
  }
  if (typeName === "ZodEffects" && schema) return развернуть(schema);
  return схема;
};

/* Телефон разбирается после схемы доменным `parsePhone`, строка из пробелов
   отвергается им; ссылка входа сверяется хешем и пробелами не подделывается. */
const РАЗБИРАЮТСЯ_ДАЛЬШЕ = new Set(["phone", "token"]);

const поля = Object.entries(контракт).flatMap(([схемаИмя, значение]) => {
  /* Среди выгрузок контракта есть и не схемы — константы и функции. */
  const схема = значение as unknown as Partial<Схема>;
  if (схема._def?.typeName !== "ZodObject" || схема.shape === undefined) return [];
  return Object.entries(схема.shape).flatMap(([поле, тип]) => {
    const строка = развернуть(тип);
    if (строка._def.typeName !== "ZodString") return [];
    const минимум = строка._def.checks?.find((проверка) => проверка.kind === "min")?.value ?? 0;
    return минимум >= 1 && !РАЗБИРАЮТСЯ_ДАЛЬШЕ.has(поле) ? [{ имя: `${схемаИмя}.${поле}`, строка, минимум }] : [];
  });
});

describe("контракт: обязательный текст не из пробелов", () => {
  it("обязательных текстовых полей много: правило проверяет не пустое место", () => {
    expect(поля.length).toBeGreaterThan(20);
  });

  it("ни одно обязательное текстовое поле не принимает строку из пробелов", () => {
    const пускают = поля
      .filter(({ строка, минимум }) => строка.safeParse(" ".repeat(Math.max(минимум, 3))).success)
      .map(({ имя }) => имя);
    expect(пускают).toEqual([]);
  });
});
