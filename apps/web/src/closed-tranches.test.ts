import { describe, expect, it } from "vitest";
import type { ClosedTranches } from "@priyomka/contracts";
import { предупреждениеОЗакрытых, сторноЗапрещено } from "./closed-tranches.js";

/**
 * Предупреждение о закрытых траншах (полный аудит 30.09.2026, П-27; решение
 * заказчика от 01.10.2026; фиксация подписанного акта — этап Э9, ДР-3).
 * Свойства, ради которых оно заведено: молчит, когда правка ничего
 * закрытого не задевает; называет номера траншей и актов, которые изменятся,
 * и отдельно — оплаченные; подписанный акт называет зафиксированным, который
 * правка не изменит, с тем, чем он исправляется.
 */
const ПОЗИЦИЯ = "11111111-1111-4111-8111-111111111111";
const ДРУГАЯ = "22222222-2222-4222-8222-222222222222";
const транши: ClosedTranches["tranches"] = [
  { number: 1, paid: true, signedAt: "2026-09-12", fixed: true, items: [ПОЗИЦИЯ] },
  { number: 2, paid: true, signedAt: null, fixed: false, items: [ПОЗИЦИЯ, ДРУГАЯ] },
  { number: 3, paid: false, signedAt: null, fixed: false, items: [ДРУГАЯ] },
];

describe("предупреждение о закрытых траншах", () => {
  it("молчит, когда закрытых траншей нет", () => {
    expect(предупреждениеОЗакрытых([], "надбавка")).toBeNull();
    expect(предупреждениеОЗакрытых([], { позиция: ПОЗИЦИЯ })).toBeNull();
  });

  it("молчит о позиции, не принятой ни в одном закрытом транше", () => {
    expect(предупреждениеОЗакрытых(транши, { позиция: "33333333-3333-4333-8333-333333333333" })).toBeNull();
  });

  it("называет только транши, где позиция принята; изменятся — только неподписанные", () => {
    const текст = предупреждениеОЗакрытых(транши, { позиция: ПОЗИЦИЯ }) ?? "";
    expect(текст).toContain("закрытом транше № 2: правка цены изменит его сумму и строку акта № 2");
    expect(текст).not.toContain("№ 3");
  });

  it("подписанный акт назван зафиксированным, с датой и способом исправления", () => {
    const текст = предупреждениеОЗакрытых(транши, { позиция: ПОЗИЦИЯ }) ?? "";
    expect(текст).toContain("Акт № 1 (12.09.2026) подписан и зафиксирован: правка его не изменит");
    expect(текст).toContain("поправка к акту на вкладке «Документы»");
    expect(текст).not.toContain("изменит их суммы и строки актов № 1");
  });

  it("называет оплаченные транши среди тех, что изменятся", () => {
    const текст = предупреждениеОЗакрытых(транши, { позиция: ДРУГАЯ }) ?? "";
    expect(текст).toContain("закрытых траншах № 2, № 3");
    expect(текст).toContain("Оплачен транш № 2");
  });

  it("сторно пакета подписанного акта запрещено и названо запретом", () => {
    expect(сторноЗапрещено(транши, 1)).toBe(true);
    expect(сторноЗапрещено(транши, 2)).toBe(false);
    expect(сторноЗапрещено(транши, null)).toBe(false);
    const текст = предупреждениеОЗакрытых(транши, { транш: 1 }) ?? "";
    expect(текст).toContain("сторно запрещено");
    expect(текст).not.toContain("сторно изменит");
  });

  it("сторно неподписанного закрытого транша называет его сумму и акт", () => {
    const текст = предупреждениеОЗакрытых(транши, { транш: 2 }) ?? "";
    expect(текст).toContain("Пакет принят в закрытом транше № 2: сторно изменит его сумму и строку акта № 2.");
    expect(текст).not.toContain("№ 1");
  });

  it("сторно пакета вне транша или в открытом транше молчит", () => {
    expect(предупреждениеОЗакрытых(транши, { транш: null })).toBeNull();
    expect(предупреждениеОЗакрытых(транши, { транш: 9 })).toBeNull();
  });

  it("надбавка: неподписанные изменятся, подписанный — нет", () => {
    const текст = предупреждениеОЗакрытых(транши, "надбавка") ?? "";
    expect(текст).toContain("суммы закрытых траншей № 2, № 3");
    expect(текст).toContain("Акт следует за сметой.");
    expect(текст).toContain("Акт № 1 (12.09.2026) подписан и зафиксирован");
  });

  it("всё закрытое подписано — о переменах ни слова", () => {
    const текст = предупреждениеОЗакрытых(транши.slice(0, 1), "надбавка") ?? "";
    expect(текст).not.toContain("Акт следует за сметой");
    expect(текст).toContain("правка его не изменит");
  });
});
