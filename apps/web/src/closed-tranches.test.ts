import { describe, expect, it } from "vitest";
import type { ClosedTranches } from "@priyomka/contracts";
import { предупреждениеОЗакрытых } from "./closed-tranches.js";

/**
 * Предупреждение о закрытых траншах (полный аудит 30.09.2026, П-27; решение
 * заказчика от 01.10.2026). Свойства, ради которых оно заведено: молчит,
 * когда правка ничего закрытого не задевает; называет номера траншей и
 * актов; отдельно называет подписанные акты и оплаченные транши — именно их
 * правка делает спорными.
 */
const ПОЗИЦИЯ = "11111111-1111-4111-8111-111111111111";
const ДРУГАЯ = "22222222-2222-4222-8222-222222222222";
const транши: ClosedTranches["tranches"] = [
  { number: 1, paid: true, signedAt: "2026-09-12", items: [ПОЗИЦИЯ] },
  { number: 2, paid: false, signedAt: null, items: [ПОЗИЦИЯ, ДРУГАЯ] },
  { number: 3, paid: false, signedAt: null, items: [ДРУГАЯ] },
];

describe("предупреждение о закрытых траншах", () => {
  it("молчит, когда закрытых траншей нет", () => {
    expect(предупреждениеОЗакрытых([], "надбавка")).toBeNull();
    expect(предупреждениеОЗакрытых([], { позиция: ПОЗИЦИЯ })).toBeNull();
  });

  it("молчит о позиции, не принятой ни в одном закрытом транше", () => {
    expect(предупреждениеОЗакрытых(транши, { позиция: "33333333-3333-4333-8333-333333333333" })).toBeNull();
  });

  it("называет только транши, где позиция принята", () => {
    const текст = предупреждениеОЗакрытых(транши, { позиция: ПОЗИЦИЯ }) ?? "";
    expect(текст).toContain("закрытых траншах № 1, № 2");
    expect(текст).toContain("строки актов № 1, № 2");
    expect(текст).not.toContain("№ 3");
  });

  it("одиночное число — одиночной формой", () => {
    const текст = предупреждениеОЗакрытых(транши.slice(2), { позиция: ДРУГАЯ }) ?? "";
    expect(текст).toContain("закрытом транше № 3: правка цены изменит его сумму и строку акта № 3");
  });

  it("называет подписанные акты с датой и оплаченные транши", () => {
    const текст = предупреждениеОЗакрытых(транши, { позиция: ПОЗИЦИЯ }) ?? "";
    expect(текст).toContain("Подписан акт № 1 (12.09.2026)");
    expect(текст).toContain("Оплачен транш № 1");
  });

  it("сторно называет транш своего пакета, а не прочие", () => {
    const текст = предупреждениеОЗакрытых(транши, { транш: 1 }) ?? "";
    expect(текст).toContain("Пакет принят в закрытом транше № 1: сторно изменит его сумму и строку акта № 1.");
    expect(текст).toContain("Подписан акт № 1 (12.09.2026)");
    expect(текст).not.toContain("№ 2");
  });

  it("сторно пакета вне транша или в открытом транше молчит", () => {
    expect(предупреждениеОЗакрытых(транши, { транш: null })).toBeNull();
    expect(предупреждениеОЗакрытых(транши, { транш: 9 })).toBeNull();
  });

  it("надбавка задевает все закрытые транши", () => {
    const текст = предупреждениеОЗакрытых(транши, "надбавка") ?? "";
    expect(текст).toContain("суммы закрытых траншей № 1, № 2, № 3");
    expect(текст).toContain("Акт следует за сметой.");
  });
});
