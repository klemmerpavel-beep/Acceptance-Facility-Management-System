import { describe, expect, it } from "vitest";
import { ПРЕДЛАГАЮТСЯ_К_ПРИВЯЗКЕ, подсказкаСоседБезСтен } from "./walls.js";

/**
 * Подсказка листа проёма у соседа без стен обещает ровно то, что строка
 * стены соседа покажет (П-84): дверь она предложит привязать, окно — нет.
 * Перечень предложений один на строку стены и подсказку, поэтому подсказка
 * сверяется с ним, а не с выписанным рядом списком.
 */
describe("подсказка листа проёма у соседа без стен", () => {
  it.each(["WINDOW", "DOOR"] as const)("%s: обещание предложения — только у вида, который строка стены предлагает", (kind) => {
    const текст = подсказкаСоседБезСтен(kind, "Коридор");
    expect(текст).toContain("В помещении «Коридор» стен нет — вторая сторона не привязана.");
    const обещает = текст.includes("строка его стены предложит привязать");
    expect(обещает).toBe(ПРЕДЛАГАЮТСЯ_К_ПРИВЯЗКЕ.includes(kind));
  });

  it("окно: вторую сторону привязывают из листа окна", () => {
    expect(подсказкаСоседБезСтен("WINDOW", "Лоджия")).toBe(
      "В помещении «Лоджия» стен нет — вторая сторона не привязана. «Лоджия» вычитает окна своими итогами;"
      + " вторую сторону привяжете из листа этого окна, когда у «Лоджия» будут стены.",
    );
  });

  it("дверь: строка стены соседа предложит привязать её одним касанием", () => {
    expect(подсказкаСоседБезСтен("DOOR", "Коридор")).toBe(
      "В помещении «Коридор» стен нет — вторая сторона не привязана. «Коридор» вычитает двери своими итогами;"
      + " когда ему заведут стены, строка его стены предложит привязать эту дверь.",
    );
  });
});
