import { StrictMode, useState } from "react";
import { createRoot } from "react-dom/client";
import "@priyomka/ui/styles.css";
import { App } from "./App.js";
import { DemoRoleSwitch } from "./DemoRole.js";
import { Feedback } from "./Feedback.js";
import { Sprite } from "./Sprite.js";

/**
 * Оболочка демонстрации. Экраны продукта не изменены и ничем не обрамлены:
 * пояснительная полоса снята решением заказчика — демонстрацию показывают
 * заказчику, и подпись «это демонстрация» отвечает на вопрос, которого он
 * не задавал, занимая первую строку экрана.
 *
 * Переключатель роли вернулся. Он был снят доводом «пользователь у продукта
 * один»; довод отпал — ролей три, и различаются они составом экранов, а не
 * только набором полей в ответе. Посмотреть продукт глазами прораба или
 * заказчика иначе негде.
 *
 * Смена роли перемонтирует продукт целиком, а не правит его состояние:
 * приложение читает пользователя и объекты один раз при запуске, и подмена
 * данных под работающим экраном показала бы полупереключённую картину —
 * шапку одной роли поверх объектов другой.
 *
 * Приём замечаний живёт здесь, а не в `App`: он относится к обзору
 * демонстрации, а не к продукту. В продукте его нет вовсе — там замечание
 * идёт в работу, а не в таблицу обзора.
 */
/* Имя латиницей: правило «компонент начинается с заглавной» определено на
   латинском алфавите и кириллическую «Д» заглавной не считает. Третий случай
   той же слепоты в этом продукте после границы слова в выражении поиска —
   правило, написанное для одного алфавита, молчит на другом. */
function DemoShell(): React.JSX.Element {
  /* Ключ растёт при смене роли и перемонтирует продукт: он читает
     пользователя и объекты при запуске, и иначе роль сменилась бы в шапке,
     не сменившись в данных. */
  const [заход, setЗаход] = useState(0);
  return (
    <>
      <DemoRoleSwitch onChange={() => { setЗаход((было) => было + 1); }} />
      <App key={заход} />
    </>
  );
}

const container = document.getElementById("root");
if (!container) throw new Error("Разметка страницы не содержит корневого узла");
createRoot(container).render(
  <StrictMode>
    <Sprite />
    <DemoShell />
    <Feedback />
  </StrictMode>,
);
