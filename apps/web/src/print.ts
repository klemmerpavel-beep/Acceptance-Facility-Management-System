/**
 * Печать бланка и получение файла.
 *
 * Ответ заказчика на вопрос 1 квиза требует акт файлом в двух видах. Файл
 * собирает браузер печатью, а не сервер — решение от 18.09.2026. Довод
 * измеренный: базовые шрифты PDF кириллицы не несут, поэтому сборка PDF на
 * сервере потребовала бы и новой зависимости, и файла шрифта в репозитории,
 * тогда как печатный лист даёт тот же документ и не стоит ничего. Регламент
 * при этом соблюдён буквально: «Новых зависимостей в `package.json` сборка не
 * вводит» (`02_DEV_PROMPT.md`).
 *
 * Цена решения названа прямо: файл рождается у человека, а не у системы.
 * Система его не хранит, ссылкой не отдаёт и в журнал не пишет. Когда
 * понадобится обратное — например, чтобы акт уходил заказчику письмом, — это
 * отдельное решение о зависимости, а не доработка этого модуля.
 */

/**
 * Имя сохраняемого файла браузер берёт из заголовка вкладки. Без подмены все
 * акты сохранялись бы под одним именем «Приёмка», и папка заказчика через
 * месяц состояла бы из «Приёмка (3).pdf».
 *
 * Заголовок возвращается на место по событию `afterprint`: оно приходит и
 * после печати, и после отмены. Восстанавливать сразу за `print()` нельзя —
 * в части браузеров вызов не ждёт закрытия диалога, и вкладка успела бы
 * вернуть прежнее имя до того, как файл назван.
 */
/** Имя вкладки до первой печати. `null` — подмены сейчас нет. */
let прежний: string | null = null;

const вернуть = (): void => {
  if (прежний !== null) document.title = прежний;
  прежний = null;
  window.removeEventListener("afterprint", вернуть);
};

export function печать(заголовок: string): void {
  /* Вторая печать до возврата не запоминает подменённое имя. Первая редакция
     запоминала, и «прежним» у второго листа становилось имя первого: после
     двух нажатий подряд вкладка навсегда оставалась названа актом. Нашлось
     замером — правило печати сверяет имя вкладки после печати с именем до
     неё, и обход нажимает печать дважды, по разу на каждый вид. */
  if (прежний === null) {
    прежний = document.title;
    window.addEventListener("afterprint", вернуть);
  }
  document.title = заголовок;
  window.print();
}

/**
 * Имя листа: что за бумага, по какому объекту и в каком виде.
 *
 * Собирается здесь, а не на каждом экране: два экрана печатают одну и ту же
 * бумагу, и два способа её назвать разошлись бы на первой правке. Разделитель
 * — тире с пробелами: косая черта и двоеточие в именах файлов заменяются
 * операционной системой, и человек получил бы «Акт _ 3 _ R-99».
 */
export const имяЛиста = (
  бумага: string,
  код: string,
  вид?: string,
): string => [бумага, код, вид].filter((часть) => часть !== undefined).join(" — ");
