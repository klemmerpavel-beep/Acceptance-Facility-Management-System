/**
 * Глаголы действий: один глагол на одно действие.
 *
 * Продукт называл заведение записи четырьмя глаголами — «Добавить», «Завести»,
 * «Внести», «Новая», — и пара «кнопка раздела → кнопка листа» расходилась в
 * строю во всех четырёх случаях: «Добавить объект» открывал лист с кнопкой
 * «Завести объект». Человек не знает, одно это действие или два, и проверяет
 * догадку нажатием.
 *
 * Глагол заведения — **«Добавить»**. Довод не вкусовой: «завести» в речи
 * стройки значит иное («завести бригаду на объект» — привести людей), «внести»
 * относится к вносимой величине, а не к записи, а «Новая заявка» — не глагол
 * вовсе и в паре с кнопкой листа не согласуется никак.
 *
 * Кнопка раздела и кнопка листа несут **одну и ту же подпись**. Лист — это не
 * второе действие, а его продолжение: назвать его другим глаголом значит
 * сказать, что делается что-то ещё.
 *
 * Глаголы правки и подтверждения этим правилом не затрагиваются: «Сохранить»,
 * «Принять», «Подтвердить» называют другие действия, и сводить их к одному
 * слову значило бы стереть разницу, которая есть.
 *
 * По тому же доводу в перечне нет транша. «Открыть транш» — не заведение
 * записи, а начало срока её жизни, и на том же экране стоит его пара,
 * «Закрыть транш». Заведение пары не имеет: добавленный объект не
 * «удаляется» кнопкой рядом. Сведя «Открыть» к «Добавить», продукт потерял
 * бы различие между «транша не было» и «транш закрыт», а это разные
 * состояния денег заказчика. Правка была сделана и снята по этому доводу.
 */

const ДОБАВИТЬ = {
  объект: "Добавить объект",
  заявка: "Добавить заявку",
  контакт: "Добавить контакт",
  заказчик: "Добавить заказчика",
  бригада: "Добавить бригаду",
  мастер: "Добавить мастера",
  этап: "Добавить этап",
  помещение: "Добавить помещение",
  чек: "Добавить чек",
  шаблон: "Добавить шаблон",
  человек: "Добавить человека",
} as const;

export type ЧтоЗаводим = keyof typeof ДОБАВИТЬ;

/**
 * Подпись кнопки заведения. Одна на раздел и на лист.
 *
 * Через функцию, а не прямым обращением: так все места употребления находятся
 * поиском по одному имени, и пятый глагол не проскочит мимо правила.
 */
export const завести = (что: ЧтоЗаводим): string => ДОБАВИТЬ[что];

export const ГЛАГОЛЫ = ДОБАВИТЬ;
