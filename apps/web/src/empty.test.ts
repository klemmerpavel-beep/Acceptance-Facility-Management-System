import { readdirSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { НЕ_ЗАПОЛНЕНО } from "./empty.js";

/**
 * Закрытый словарь остаётся закрытым.
 *
 * Двенадцать формулировок отсутствия появились не разом: каждый новый экран
 * писал своё слово, и «не задан», «не задано», «не задана», «нет», «сметы
 * нет», «не начаты» сошлись на одном продукте, означая одно. Свести их к
 * словарю мало — без стража тринадцатая напишется на следующем экране тем же
 * способом, каким написались первые двенадцать.
 *
 * Проверяется свойство, а не список мест: слово словаря не должно стоять в
 * коде экрана строковым литералом. Стоять оно обязано за вызовом `пусто`.
 *
 * Ищется литерал в двойных кавычках — тот вид, в каком его пишет разметка.
 * Слово в русских кавычках внутри комментария правилом не затрагивается:
 * комментарий объясняет, а не печатается.
 */
const КОРЕНЬ = new URL("./", import.meta.url).pathname;
const СВОЙ = "empty.ts";

const экраны = readdirSync(КОРЕНЬ, { withFileTypes: true })
  .filter((узел) => узел.isFile())
  .map((узел) => узел.name)
  .filter((имя) => /\.tsx?$/u.test(имя) && !имя.endsWith(".test.ts") && имя !== СВОЙ);

const слова = Object.values(НЕ_ЗАПОЛНЕНО)
  .flatMap((пара) => [пара.краткое, пара.полное])
  /* Короткие формы вроде «нет» встречаются в обычной речи интерфейса
     («Объектов пока нет»), и запрещать их целиком значило бы запрещать язык.
     Стережётся то, что отличает словарь от речи: формулировки длиннее
     одного слова. */
  .filter((слово) => слово.includes(" "));

describe("словарь отсутствия", () => {
  it.each([...new Set(слова)])("«%s» не написано литералом мимо словаря", (слово) => {
    const нарушители = экраны.filter((имя) =>
      readFileSync(`${КОРЕНЬ}${имя}`, "utf8").includes(`"${слово}"`));
    expect(нарушители).toEqual([]);
  });

  /* Литерал в кавычках — не единственный вид, в каком слово попадает на
     экран. Текст разметки пишется без кавычек, а смысл переставляется
     словами: «нет сметы» в колонке реестра и «смета не загружена» в
     карточке жили рядом со словарным «сметы нет» и не ловились ничем
     (полный аудит 30.09.2026, П-9). Стережётся текст разметки и обратный
     порядок слов, а «смета не загружена» — пересказ словарного «сметы нет»,
     которым продукт уже пользовался. «Снимок плана не загружен» пересказом
     не является: он называет незагруженный файл, а не отсутствие величины. */
  const разметкой = (слово: string): RegExp =>
    new RegExp(`>\\s*${слово}\\s*<`, "u");
  const обратно = (слово: string): string => слово.split(" ").reverse().join(" ");
  it.each([...new Set(слова)])("«%s» не написано текстом разметки ни в каком порядке слов", (слово) => {
    const нарушители = экраны.filter((имя) => {
      const текст = readFileSync(`${КОРЕНЬ}${имя}`, "utf8");
      return разметкой(слово).test(текст) || разметкой(обратно(слово)).test(текст)
        || текст.includes(`"${обратно(слово)}"`);
    });
    expect(нарушители).toEqual([]);
  });

  it("пересказа «смета не загружена» на экранах нет", () => {
    const нарушители = экраны.filter((имя) =>
      /["'>`]\s*[Сс]мет[аы]? не загружен/u.test(readFileSync(`${КОРЕНЬ}${имя}`, "utf8")));
    expect(нарушители).toEqual([]);
  });

  /* Проверка «краткая форма не равна полной» была написана и снята: типы
     доказывают её сами — литералы не пересекаются, и упасть она не могла
     ни при какой правке. Непадающая проверка не стережёт ничего.

     Стережётся то, что проверить можно: мёртвая запись словаря. Слово,
     заведённое и никем не употреблённое, переживает правку молча и
     копится — тем же способом, каким накопились двенадцать формулировок. */
  it("в словаре нет мёртвых записей", () => {
    const разметка = экраны
      .map((имя) => readFileSync(КОРЕНЬ + имя, "utf8"))
      .join("\n");
    const мёртвые = Object.keys(НЕ_ЗАПОЛНЕНО)
      /* Обе формы считаются употреблением: прописная «Пусто» — тот же
         словарь, и страж, знавший одну строчную, объявлял мёртвыми записи,
         употреблённые в заголовках пустых состояний. */
      .filter((ключ) => !new RegExp(`[Пп]усто\\("${ключ}"`, "u").test(разметка));
    expect(мёртвые).toEqual([]);
  });
});
