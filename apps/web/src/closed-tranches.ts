import type { ClosedTranches } from "@priyomka/contracts";
import { plural } from "@priyomka/domain";
import { formatDate } from "./status.js";

/**
 * Предупреждение о закрытых траншах и выпущенных актах.
 *
 * Акт следует за сметой: правка цены принятой позиции или надбавки меняет
 * суммы закрытых траншей и строки актов по ним — в том числе подписанных и
 * оплаченных (полный аудит 30.09.2026, П-27). Решение заказчика от
 * 01.10.2026 — оставить так и предупреждать до сохранения, называя номера:
 * «изменятся закрытые транши» без номеров не отвечает на вопрос, какой акт
 * переподписывать.
 *
 * Третий случай — сторно: обратная запись ложится в пакет исходной приёмки и
 * потому в её транш. Решение называло листы правки позиции и надбавки, сторно
 * добавлено заказчиком 02.10.2026 — тем же текстом о подписи и оплате.
 *
 * `null` — правка ничего закрытого не задевает, и предупреждать не о чем.
 */
export function предупреждениеОЗакрытых(
  транши: ClosedTranches["tranches"],
  что: { позиция: string } | { транш: number | null } | "надбавка",
): string | null {
  const задетые = что === "надбавка"
    ? транши
    : "позиция" in что
      ? транши.filter((транш) => транш.items.includes(что.позиция))
      : транши.filter((транш) => транш.number === что.транш);
  if (задетые.length === 0) return null;

  const номера = задетые.map((транш) => `№ ${String(транш.number)}`).join(", ");
  const много = задетые.length > 1;
  const начало = что === "надбавка"
    ? `Надбавка входит в ${много ? "суммы закрытых траншей" : "сумму закрытого транша"} ${номера} `
      + `и ${много ? "актов" : "акта"} по ${много ? "ним" : "нему"}: правка изменит их.`
    : "позиция" in что
      ? `Позиция принята в ${много ? "закрытых траншах" : "закрытом транше"} ${номера}: правка цены `
        + `изменит ${много ? "их суммы и строки актов" : "его сумму и строку акта"} ${номера}.`
      : `Пакет принят в закрытом транше ${номера}: сторно изменит его сумму и строку акта ${номера}.`;

  const подписаны = задетые.filter((транш) => транш.signedAt !== null);
  const оплачены = задетые.filter((транш) => транш.paid);
  const подписи = подписаны.length === 0
    ? ""
    : ` ${plural(подписаны.length, "Подписан акт", "Подписаны акты", "Подписаны акты")} `
      + подписаны.map((транш) => `№ ${String(транш.number)} (${formatDate(транш.signedAt ?? "")})`).join(", ")
      + " — заказчик подписал прежние суммы.";
  const оплата = оплачены.length === 0
    ? ""
    : ` ${plural(оплачены.length, "Оплачен транш", "Оплачены транши", "Оплачены транши")} `
      + оплачены.map((транш) => `№ ${String(транш.number)}`).join(", ")
      + ": новая сумма разойдётся с полученными деньгами.";
  return `${начало}${подписи}${оплата} Акт следует за сметой.`;
}
