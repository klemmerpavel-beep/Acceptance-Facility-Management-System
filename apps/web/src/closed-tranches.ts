import type { ClosedTranches } from "@priyomka/contracts";
import { plural } from "@priyomka/domain";
import { formatDate } from "./status.js";

/**
 * Предупреждение о закрытых траншах и выпущенных актах.
 *
 * Неподписанный акт следует за сметой: правка цены принятой позиции или
 * надбавки меняет суммы закрытых траншей и строки актов по ним (полный аудит
 * 30.09.2026, П-27). Решение заказчика от 01.10.2026 — предупреждать до
 * сохранения, называя номера: «изменятся закрытые транши» без номеров не
 * отвечает на вопрос, какой акт перепроверять.
 *
 * Подписанный акт с этапа Э9 зафиксирован (ДР-3, решение допроса 07.10.2026):
 * правка его не меняет, и лист говорит это прямо — с тем, чем ошибка в нём
 * исправляется. Иначе руководитель искал бы новую сумму в подписанном акте.
 *
 * Третий случай — сторно: обратная запись ложится в пакет исходной приёмки и
 * потому в её транш. Сторно пакета подписанного акта запрещено
 * (`сторноЗапрещено`), остальное — тем же текстом, что у правки.
 *
 * `null` — правка ничего закрытого не задевает, и предупреждать не о чем.
 */
export function предупреждениеОЗакрытых(
  транши: ClosedTranches["tranches"],
  что: { позиция: string } | { транш: number | null } | "надбавка",
): string | null {
  const задетые = что === "надбавка"
    ? транши
    : "позиция" in что
      ? транши.filter((транш) => транш.items.includes(что.позиция))
      : транши.filter((транш) => транш.number === что.транш);
  const меняются = задетые.filter((транш) => !транш.fixed);
  const зафиксированы = задетые.filter((транш) => транш.fixed);
  if (меняются.length === 0 && зафиксированы.length === 0) return null;

  const части: string[] = [];
  if (меняются.length > 0) {
    const номера = меняются.map((транш) => `№ ${String(транш.number)}`).join(", ");
    const много = меняются.length > 1;
    части.push(что === "надбавка"
      ? `Надбавка входит в ${много ? "суммы закрытых траншей" : "сумму закрытого транша"} ${номера} `
        + `и ${много ? "актов" : "акта"} по ${много ? "ним" : "нему"}: правка изменит их.`
      : "позиция" in что
        ? `Позиция принята в ${много ? "закрытых траншах" : "закрытом транше"} ${номера}: правка цены `
          + `изменит ${много ? "их суммы и строки актов" : "его сумму и строку акта"} ${номера}.`
        : `Пакет принят в закрытом транше ${номера}: сторно изменит его сумму и строку акта ${номера}.`);
    const подписаны = меняются.filter((транш) => транш.signedAt !== null);
    if (подписаны.length > 0) {
      части.push(`${plural(подписаны.length, "Подписан акт", "Подписаны акты", "Подписаны акты")} `
        + подписаны.map((транш) => `№ ${String(транш.number)} (${formatDate(транш.signedAt ?? "")})`).join(", ")
        + " — заказчик подписал прежние суммы.");
    }
    const оплачены = меняются.filter((транш) => транш.paid);
    if (оплачены.length > 0) {
      части.push(`${plural(оплачены.length, "Оплачен транш", "Оплачены транши", "Оплачены транши")} `
        + оплачены.map((транш) => `№ ${String(транш.number)}`).join(", ")
        + ": новая сумма разойдётся с полученными деньгами.");
    }
    части.push("Акт следует за сметой.");
  }
  if (зафиксированы.length > 0) {
    const номера = зафиксированы
      .map((транш) => `№ ${String(транш.number)}${транш.signedAt === null ? "" : ` (${formatDate(транш.signedAt)})`}`)
      .join(", ");
    const много = зафиксированы.length > 1;
    части.push(что !== "надбавка" && "транш" in что
      ? `Пакет вошёл в акт ${номера}: акт подписан, сторно запрещено — подписанный акт не меняется. `
        + "Ошибку исправляет поправка к акту на вкладке «Документы»."
      : `${много ? "Акты" : "Акт"} ${номера} ${много ? "подписаны и зафиксированы" : "подписан и зафиксирован"}: `
        + `правка ${много ? "их" : "его"} не изменит. Ошибку в ${много ? "них" : "нём"} исправляет поправка `
        + "к акту на вкладке «Документы».");
  }
  return части.join(" ");
}

/**
 * Запрещено ли сторно пакета: пакет вошёл в подписанный, а значит
 * зафиксированный акт (ДР-3). Сервер откажет и сам; лист говорит это до
 * отправки, а не после.
 */
export function сторноЗапрещено(транши: ClosedTranches["tranches"], номер: number | null): boolean {
  return транши.some((транш) => транш.number === номер && транш.fixed);
}
