/**
 * Приёмка выполненных работ.
 *
 * Единственное место, где живут правила приёмки. Сервер зовёт отсюда, чтобы
 * отказать до записи; экран — чтобы отказать до обращения к сети. Два
 * независимых свода разошлись бы на третьей правке, и человек получал бы
 * отказ там, где экран обещал согласие (тот же довод, что у `stageDateFault`).
 *
 * Почему принятое хранится записями, а не числом в позиции
 * -------------------------------------------------------
 * Поле «принято» в позиции сметы пришлось бы уменьшать при отмене, то есть
 * переписывать. БП-04 запрещает: отмена приёмки — сторно, обратная запись,
 * история не переписывается никогда. Поэтому принятое есть сумма записей,
 * среди которых сторно даёт отрицательное количество. Сумма пары
 * «приёмка + её сторно» равна нулю точно, без накопления погрешности:
 * количества целые, а деньги считаются одним правилом округления
 * (`divideRoundHalfUp`, половина вверх по модулю).
 *
 * Единицы: количество — тысячные доли единицы измерения (`Milliunits`),
 * деньги — целые копейки (`Kopecks`). Дробных типов здесь нет ни одного.
 */

import {
  basisPoints,
  divideRoundHalfUp,
  milliunits,
  multiplyByQuantity,
  sum,
  type BasisPoints,
  type Kopecks,
  type Milliunits,
} from "./money.js";

/** Запись приёмки в том виде, в каком её читает арифметика. */
export interface AcceptanceRecord {
  /** Тысячные доли единицы. У сторно отрицательное. */
  readonly qty: Milliunits;
}

/**
 * Принято по позиции: сумма количеств, включая отрицательные у сторно.
 *
 * Пустой список даёт ноль — это честный ноль «ничего не принято», а не
 * отсутствие данных: позиция сметы существует всегда, приёмок у неё может
 * не быть.
 */
export function acceptedQty(records: readonly AcceptanceRecord[]): Milliunits {
  let total = 0n;
  for (const record of records) total += record.qty;
  return total as Milliunits;
}

/**
 * Остаток по смете: количество позиции минус принятое.
 *
 * Отрицательным быть не может, пока действует БП-02, но и не подрезается:
 * отрицательный остаток означает, что правило где-то обошли, и прятать это
 * нулём значило бы скрыть дефект от того, кто смотрит на экран.
 */
export function remainingQty(qty: Milliunits, accepted: Milliunits): Milliunits {
  return (qty - accepted) as Milliunits;
}

/* Неразрывный пробел между числом и единицей — тот же, что в `formatMeasure`
   витрины: «12,00» и «м²» не должны разъезжаться по строкам. Записан
   escape-последовательностью: невидимый символ в исходнике неотличим от
   обычного пробела, и расхождение находится только падением проверки. */
const NBSP = "\u00A0";

/**
 * «12,00 м²» — количество, названное человеку.
 *
 * Вынесено наружу ради правки сметы (`estimate.ts`): её отказы называют те
 * же величины теми же словами, и второе написание разошлось бы с первым —
 * человек получил бы одно число в двух видах. Только для текстов отказа:
 * оформление величин на экране живёт в `packages/ui`.
 */
export const количествоТекстом = (value: Milliunits, unit: string): string => {
  const отрицательное = value < 0n;
  const сотые = divideRoundHalfUp(отрицательное ? -(value as bigint) : value, 10n);
  const целое = сотые / 100n;
  const дробь = (сотые % 100n).toString().padStart(2, "0");
  return `${отрицательное ? "−" : ""}${целое.toString()},${дробь}${NBSP}${unit}`;
};

/* Разряды не разделяются: количества позиций сметы редко переходят тысячу,
   а разделитель разрядов живёт в `packages/ui` и сюда не тянется — домен
   от оформления не зависит. */

/** Что именно принимают: количество, позиция и то, сколько уже принято. */
export interface AcceptanceRequest {
  /** Сколько принимают сейчас. */
  readonly requested: Milliunits;
  /** Количество позиции по смете. */
  readonly qty: Milliunits;
  /** Уже принято по этой позиции, с учётом сторно. */
  readonly accepted: Milliunits;
  /** Единица измерения позиции: «м²», «шт», «м.п.». */
  readonly unit: string;
}

/**
 * Причина, по которой принять нельзя, или `null`.
 *
 * Правила в объявленном порядке, первый отказ возвращается сразу: человеку
 * нужна одна причина, а не список.
 *
 * 1. Количество положительно. Ноль и отрицательное — не приёмка: снятие
 *    принятого делается сторно, у которого есть автор и причина.
 * 2. Принять больше остатка нельзя (БП-02). Отказ называет остаток и говорит,
 *    что делать, — по образцу норматива (`03_DESIGN_SYSTEM.md`, раздел 12).
 *
 * Количества показаны с двумя знаками, как везде в продукте: «8,4» рядом с
 * «8,40» заставляет проверять, одно ли это число. Норматив приводит текст с
 * одним знаком, но там он иллюстративный.
 */
export function acceptanceFault(request: AcceptanceRequest): string | null {
  if (request.requested <= 0n) {
    return "Количество должно быть больше нуля. Снятие принятого делается сторно.";
  }

  const остаток = remainingQty(request.qty, request.accepted);
  if (request.requested > остаток) {
    return `Нельзя принять ${количествоТекстом(request.requested, request.unit)} — `
      + `по смете осталось ${количествоТекстом(остаток, request.unit)}. `
      + "Уменьшите количество или измените смету.";
  }

  return null;
}

/**
 * Сумма начисления: снимок ставки, умноженный на количество.
 *
 * Знак следует за количеством: сторно с отрицательным количеством даёт
 * отрицательное начисление, и пара складывается в ноль. Округление половины
 * вверх по модулю обеспечивает это точно — при округлении «половина вверх»
 * пара −4,5 и +4,5 дала бы копейку расхождения.
 */
export function accrualAmount(unitWage: Kopecks, qty: Milliunits): Kopecks {
  return multiplyByQuantity(unitWage, qty);
}

/** Принятая строка: сколько принято и почём. */
export interface AcceptedRow {
  readonly qty: Milliunits;
  readonly unitPrice: Kopecks;
}

/**
 * Выполнено на сумму: Σ принятое × цена единицы (БП-05).
 *
 * Считается по позициям, а не по пакетам: сторно уже учтено в количестве
 * позиции, и второй проход по пакетам вычел бы его дважды.
 */
export function acceptedTotal(rows: readonly AcceptedRow[]): Kopecks {
  return sum(rows.map((row) => multiplyByQuantity(row.unitPrice, row.qty)));
}

/**
 * Доля принятого в итоге раздела — фактическая готовность.
 *
 * Мерится деньгами, а не числом позиций: раздел на миллион с одной принятой
 * позицией из тридцати и тот же раздел с двадцатью принятыми дешёвыми — это
 * разный объём выполненного, а счёт строк приравнивает вынос мусора к
 * штукатурке стен. Цена уже выверена заказчиком, число строк — нет.
 *
 * `null`, когда делить не на что: раздел без позиций или с нулевым итогом.
 * Ноль означал бы «ничего не принято», а это иное утверждение — то же
 * правило, по которому `projectReadiness` возвращает `null` без графика.
 *
 * Верхняя граница не ставится: перевыработка законна и должна быть видна.
 * Сторно учтено само собой — оно уже вычтено из принятого количества.
 */
export function acceptedShare(accepted: Kopecks, total: Kopecks): BasisPoints | null {
  if (total === 0n) return null;
  return basisPoints(divideRoundHalfUp(accepted * 10_000n, total));
}

/**
 * Наименьшее количество, до которого позицию можно уменьшить (Р17).
 *
 * Уменьшить позицию ниже принятого значит объявить непринятым то, что уже
 * принято и начислено. Точка применения появится вместе с редактором сметы
 * (стадия C.2); правило написано здесь, чтобы редактор не завёл своё.
 */
export function minimumQty(accepted: Milliunits): Milliunits {
  return accepted > 0n ? accepted : milliunits(0);
}

/** Строка свода начислений: получатель и сумма. Только руководителю. */
export interface AccrualRow {
  readonly brigadeId: string;
  readonly brigadeName: string;
  readonly amount: Kopecks;
}

/** Начисление в том виде, в каком его читает свод. */
export interface AccrualRecord {
  readonly brigadeId: string;
  readonly brigadeName: string;
  readonly amount: Kopecks;
  /** ГГГГ-ММ-ДД. */
  readonly at: string;
}

/**
 * Свод начислений по бригадам за период, по убыванию суммы.
 *
 * Бригада, у которой начисления сложились в ноль (всё сторнировано),
 * из свода не выпадает: ноль здесь — сведение, а не отсутствие работы,
 * и молчание о нём выглядело бы как потерянная запись.
 *
 * Разрез «за транш» живёт отдельной функцией `accrualsByTranche`
 * (`tranche.ts`): она отбирает записи по траншу и зовёт этот же свод. Здесь
 * отбор только по датам — период и транш суть разные основания, и сведение
 * их в один список параметров породило бы взаимоисключающие сочетания.
 */
export function accrualSummary(
  records: readonly AccrualRecord[],
  period?: { readonly from: string; readonly to: string },
): readonly AccrualRow[] {
  const внутри = period === undefined
    ? records
    : records.filter((row) => period.from <= row.at && row.at <= period.to);

  const своды = new Map<string, AccrualRow>();
  for (const record of внутри) {
    const прежнее = своды.get(record.brigadeId);
    своды.set(record.brigadeId, {
      brigadeId: record.brigadeId,
      brigadeName: record.brigadeName,
      amount: ((прежнее?.amount ?? 0n) + record.amount) as Kopecks,
    });
  }

  return [...своды.values()].sort((left, right) =>
    right.amount === left.amount ? left.brigadeName.localeCompare(right.brigadeName)
      : right.amount > left.amount ? 1 : -1);
}
