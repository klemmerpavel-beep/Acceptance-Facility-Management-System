/**
 * Шаблон документа: метки переменных и подстановка.
 *
 * Правила чистые — ни базы, ни сети. Их зовут и сервер перед выпуском
 * документа, и экран при показе шаблона: одно правило, два места применения,
 * ни одной копии. Тем же устройством живут `expenseFault` и `nextProjectCode`.
 *
 * **Метка остаётся видимой в шаблоне.** Это записано на утверждённом макете
 * («переменная подставляется при генерации файла и в шаблоне остаётся видимой
 * меткой») и держится здесь: разбор возвращает метку как есть, а подстановка
 * делается отдельным вызовом на отдельных данных.
 *
 * **Неизвестная метка называется, а не подставляется пустотой.** Документ, из
 * которого молча пропал реквизит, подписывают не глядя: пустое место читается
 * как «здесь ничего и не было». Отказ дороже в момент выпуска и дешевле
 * потом.
 */

/** Группы переменных по утверждённому макету. Порядок — порядок макета. */
export const VARIABLE_GROUPS = [
  "организация", "исполнитель", "контрагент", "документ", "объект", "система",
] as const;

export type VariableGroup = (typeof VARIABLE_GROUPS)[number];

export interface VariableSpec {
  /** Полное имя метки: «объект.код». */
  readonly name: string;
  readonly group: VariableGroup;
  /** Что подставится. Показывается в палитре рядом с меткой. */
  readonly title: string;
}

/**
 * Перечень известных переменных.
 *
 * Список закрытый: метка, которой здесь нет, при выпуске документа
 * отвергается. Открытый список означал бы, что опечатка в метке проходит до
 * подписи — а там её замечает уже заказчик.
 */
/* Телефона заказчика в перечне нет: у `Client` такого поля нет, и метка,
   которой нечем подставиться, обещает данные, которых в продукте не
   существует. Заводить поле ради метки — отдельное решение заказчика. */
export const VARIABLES: readonly VariableSpec[] = [
  { name: "организация.наименование", group: "организация", title: "Наименование организации" },
  { name: "организация.телефон", group: "организация", title: "Телефон организации" },
  { name: "организация.почта", group: "организация", title: "Почта организации" },
  { name: "исполнитель.наименование", group: "исполнитель", title: "Наименование исполнителя" },
  { name: "исполнитель.реквизиты", group: "исполнитель", title: "Реквизиты исполнителя" },
  { name: "контрагент.наименование", group: "контрагент", title: "Наименование заказчика" },
  { name: "контрагент.реквизиты", group: "контрагент", title: "Реквизиты заказчика" },
  { name: "документ.номер", group: "документ", title: "Порядковый номер документа" },
  { name: "документ.дата", group: "документ", title: "Дата создания документа" },
  { name: "объект.код", group: "объект", title: "Код объекта" },
  { name: "объект.адрес", group: "объект", title: "Адрес объекта" },
  { name: "объект.площадь", group: "объект", title: "Площадь по обмеру" },
  { name: "объект.смета", group: "объект", title: "Итог сметы для заказчика" },
  { name: "система.сегодня", group: "система", title: "Сегодняшняя дата" },
  { name: "система.автор", group: "система", title: "Кто выпустил документ" },
];

const ИЗВЕСТНЫЕ = new Set(VARIABLES.map((переменная) => переменная.name));

/* Метка: два открывающих знака, имя из букв, точек и дефисов, два
   закрывающих. Пробелы внутри допускаются и отбрасываются — вписанное
   руками «{{ объект.код }}» это та же метка, и отвергать её значило бы
   отвергать опечатку, которой нет. */
const МЕТКА = /\{\{\s*([А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z0-9.\-_]*)\s*\}\}/gu;

/** Имена меток, встреченных в тексте, по одному разу и в порядке появления. */
export function templateVariables(текст: string): readonly string[] {
  const найдено: string[] = [];
  for (const совпадение of текст.matchAll(МЕТКА)) {
    const имя = совпадение[1];
    if (имя !== undefined && !найдено.includes(имя)) найдено.push(имя);
  }
  return найдено;
}

/** Метки, которых нет в перечне известных. */
export function unknownVariables(текст: string): readonly string[] {
  return templateVariables(текст).filter((имя) => !ИЗВЕСТНЫЕ.has(имя));
}

/**
 * Подстановка значений в текст.
 *
 * Известная метка без значения — не то же самое, что неизвестная: значения
 * может не быть законно (реквизиты не заполнены, обмера нет). Такая метка
 * заменяется прочерком, а не исчезает: прочерк виден глазу и его дописывают
 * ручкой, пустое место — нет.
 */
export function fillTemplate(
  текст: string,
  значения: Readonly<Record<string, string | null>>,
): string {
  return текст.replace(МЕТКА, (_целиком, имя: string) => {
    if (!ИЗВЕСТНЫЕ.has(имя)) return `{{${имя}}}`;
    const значение = значения[имя];
    return значение === undefined || значение === null || значение === "" ? "—" : значение;
  });
}

/** Отказ при заведении шаблона. `null` — возражений нет. */
export function templateFault(input: {
  readonly name: string;
  readonly clauses: readonly { readonly title: string; readonly body: string }[];
}): string | null {
  if (input.name.trim() === "") return "У шаблона нет наименования: в списке его будет не найти.";
  if (input.clauses.length === 0) {
    return "В шаблоне нет ни одного пункта: выпускать нечего.";
  }
  for (const пункт of input.clauses) {
    if (пункт.title.trim() === "") return "У пункта нет заголовка.";
    const чужие = unknownVariables(`${пункт.title}\n${пункт.body}`);
    if (чужие.length > 0) {
      return `Неизвестные переменные: ${чужие.join(", ")}. `
        + "Подставить их нечем, и в документе они останутся меткой.";
    }
  }
  return null;
}
