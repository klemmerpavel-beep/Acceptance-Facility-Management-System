import { describe, expect, it } from "vitest";
import { kopecks } from "./money.js";
import { planFromSections, type SectionWeight } from "./plan.js";

const раздел = (id: string, total: number, positions = 1): SectionWeight =>
  ({ id, name: id, total: kopecks(BigInt(total)), positions });

describe("раскладка графика по разделам сметы", () => {
  it("пустая смета даёт пустую раскладку, а не окно без этапов", () => {
    expect(planFromSections([], { from: "2026-03-02", to: "2026-08-15" })).toEqual([]);
  });

  it("один раздел занимает окно целиком", () => {
    const [этап] = planFromSections([раздел("s1", 100)], { from: "2026-03-02", to: "2026-03-11" });
    expect(этап?.startsOn).toBe("2026-03-02");
    expect(этап?.endsOn).toBe("2026-03-11");
    expect(этап?.days).toBe(10);
  });

  it("этапы идут подряд, без разрывов и перекрытий", () => {
    const этапы = planFromSections(
      [раздел("s1", 300), раздел("s2", 500), раздел("s3", 200)],
      { from: "2026-03-02", to: "2026-04-10" },
    );
    for (const [индекс, этап] of этапы.entries()) {
      if (индекс === 0) continue;
      const предыдущий = этапы[индекс - 1];
      const следующийДень = new Date(`${предыдущий?.endsOn ?? ""}T00:00:00Z`);
      следующийДень.setUTCDate(следующийДень.getUTCDate() + 1);
      expect(этап.startsOn).toBe(следующийДень.toISOString().slice(0, 10));
    }
  });

  it("последний этап заканчивается ровно в срок: округления не копятся", () => {
    /* Три доли, каждая с остатком. Порознь округлённые длительности дали бы
       промах мимо окна — накопительный счёт его исключает. */
    const этапы = planFromSections(
      [раздел("s1", 1), раздел("s2", 1), раздел("s3", 1)],
      { from: "2026-03-02", to: "2026-03-12" },
    );
    expect(этапы[этапы.length - 1]?.endsOn).toBe("2026-03-12");
  });

  it("дорогой раздел получает больше дней, чем дешёвый", () => {
    const [дешёвый, дорогой] = planFromSections(
      [раздел("s1", 100), раздел("s2", 900)],
      { from: "2026-03-02", to: "2026-03-31" },
    );
    expect(дешёвый?.days).toBeLessThan(дорогой?.days ?? 0);
    expect((дешёвый?.days ?? 0) + (дорогой?.days ?? 0)).toBe(30);
  });

  it("раздел получает не меньше дня, даже если стоит копейки", () => {
    const этапы = planFromSections(
      [раздел("s1", 1), раздел("s2", 1_000_000)],
      { from: "2026-03-02", to: "2026-03-31" },
    );
    expect(этапы[0]?.days).toBe(1);
    expect(этапы[0]?.startsOn).toBe("2026-03-02");
    expect(этапы[1]?.startsOn).toBe("2026-03-03");
  });

  it("разделов больше, чем дней: раскладка выходит за окно, а не схлопывается", () => {
    /* Отказывать нечему: график, показывающий срыв, полезнее отсутствующего.
       То же правило, по которому валидатор дат принимает срок позже сдачи. */
    const этапы = planFromSections(
      [раздел("s1", 1), раздел("s2", 1), раздел("s3", 1)],
      { from: "2026-03-02", to: "2026-03-03" },
    );
    expect(этапы).toHaveLength(3);
    expect(этапы.every((этап) => этап.days === 1)).toBe(true);
    expect(этапы[2]?.endsOn).toBe("2026-03-04");
  });

  it("смета без цен делит окно поровну, а не отказывает", () => {
    const этапы = planFromSections(
      [раздел("s1", 0), раздел("s2", 0), раздел("s3", 0)],
      { from: "2026-03-02", to: "2026-03-31" },
    );
    expect(этапы.map((этап) => этап.days)).toEqual([10, 10, 10]);
  });

  it("окно в один день: этап длится день, а не ноль", () => {
    const [этап] = planFromSections([раздел("s1", 100)], { from: "2026-03-02", to: "2026-03-02" });
    expect(этап?.days).toBe(1);
    expect(этап?.startsOn).toBe("2026-03-02");
    expect(этап?.endsOn).toBe("2026-03-02");
  });

  it("раздел без позиций этапом не становится: это заголовок, а не работа", () => {
    const этапы = planFromSections(
      [раздел("работы", 100), раздел("заголовок", 0, 0)],
      { from: "2026-03-02", to: "2026-03-11" },
    );
    expect(этапы.map((этап) => этап.sectionId)).toEqual(["работы"]);
    expect(этапы[0]?.days).toBe(10);
  });

  it("смета из одних заголовков даёт пустую раскладку", () => {
    expect(planFromSections(
      [раздел("a", 0, 0), раздел("b", 0, 0)],
      { from: "2026-03-02", to: "2026-03-31" },
    )).toEqual([]);
  });

  it("порядок разделов сохраняется: его задаёт смета", () => {
    const этапы = planFromSections(
      [раздел("демонтаж", 100), раздел("электрика", 900), раздел("отделка", 500)],
      { from: "2026-03-02", to: "2026-05-31" },
    );
    expect(этапы.map((этап) => этап.sectionId)).toEqual(["демонтаж", "электрика", "отделка"]);
  });

  it("раскладка переходит через месяц и год по календарю", () => {
    const этапы = planFromSections(
      [раздел("s1", 1), раздел("s2", 1)],
      { from: "2026-12-30", to: "2027-01-02" },
    );
    expect(этапы[0]?.endsOn).toBe("2026-12-31");
    expect(этапы[1]?.startsOn).toBe("2027-01-01");
    expect(этапы[1]?.endsOn).toBe("2027-01-02");
  });
});
