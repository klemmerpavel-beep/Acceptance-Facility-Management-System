import { multiplyByQuantity, type Kopecks, type Milliunits } from "./money.js";

/**
 * Поправка к подписанному акту (этап Э9, ДР-3; решение допроса 07.10.2026).
 *
 * Подписанный акт зафиксирован: его строки хранятся снимком и правкой сметы
 * не меняются. Ошибка в нём — неверная цена или лишний объём — исправляется
 * не правкой акта, а строкой акта текущего транша: «было → стало» и разница
 * суммой. Так подписанная бумага остаётся той, что подписана, а исправление
 * приходит заказчику следующим актом, который он подписывает целиком.
 *
 * Поправка меняет только сумму для заказчика. Начисление бригаде ею не
 * меняется: ставка и начисление — внутренние величины, и их исправление
 * идёт своим путём — приёмкой и сторно в открытом транше.
 */

/** Количество и цена строки подписанного акта — до или после поправки. */
export interface СостояниеСтроки {
  readonly qty: Milliunits;
  readonly unitPrice: Kopecks;
}

export interface ПоправкаСтроки {
  readonly было: СостояниеСтроки;
  readonly стало: СостояниеСтроки;
}

/**
 * Сумма поправки по работам, без надбавки: стало минус было. Отрицательная
 * уменьшает акт текущего транша, положительная — увеличивает. Каждая сторона
 * считается тем же правилом, что строка акта (`multiplyByQuantity`), — иначе
 * поправка «было» не совпала бы копейка в копейку со строкой подписанного
 * акта.
 */
export function correctionTotal(поправка: ПоправкаСтроки): Kopecks {
  return (multiplyByQuantity(поправка.стало.unitPrice, поправка.стало.qty)
    - multiplyByQuantity(поправка.было.unitPrice, поправка.было.qty)) as Kopecks;
}

/**
 * С чего начинается следующая поправка строки: с того, чем кончилась
 * последняя, а не со снимка. Иначе вторая поправка той же строки посчитала
 * бы разницу от подписанного акта и учла бы первую дважды.
 *
 * Поправки приходят в порядке записи.
 */
export function correctedState(
  снимок: СостояниеСтроки,
  поправки: readonly { readonly стало: СостояниеСтроки }[],
): СостояниеСтроки {
  return поправки.at(-1)?.стало ?? снимок;
}

/**
 * Что мешает записать поправку. `null` — ничего.
 *
 * Причина обязательна (решение допроса Э9-10): заказчик читает её в акте,
 * и поправка без причины — число, которому нечем верить.
 */
export function correctionFault(
  поправка: ПоправкаСтроки & { readonly причина: string },
): string | null {
  if (поправка.причина.trim() === "") {
    return "Причина поправки обязательна: заказчик прочтёт её в акте.";
  }
  if ((поправка.стало.qty as bigint) < 0n) return "Количество не может быть отрицательным.";
  if ((поправка.стало.unitPrice as bigint) < 0n) return "Цена не может быть отрицательной.";
  if (поправка.стало.qty === поправка.было.qty && поправка.стало.unitPrice === поправка.было.unitPrice) {
    return "Поправка ничего не меняет: количество и цена те же, что в акте.";
  }
  return null;
}
