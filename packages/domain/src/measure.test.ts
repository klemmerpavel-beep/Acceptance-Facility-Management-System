    expect(СТЕНЫ_КОМНАТЫ.map((w) => singleWallAreaNet(КОМНАТА_2, w))).toEqual([6_540n, 10_260n, 6_960n, 10_260n]);
    expect(СТЕНЫ_КОРИДОРА.map((w) => singleWallAreaNet(КОРИДОР_2, w))).toEqual([1_395n, 10_470n, 3_240n, 9_850n]);
