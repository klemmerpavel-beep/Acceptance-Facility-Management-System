import { describe, expect, it } from "vitest";
import { milliunits } from "./money.js";
import { measureTotals, roomVolume, wallArea, type RoomMeasure } from "./measure.js";

/**
 * Контрольные значения взяты с утверждённого артборда обмерного плана
 * (`design/canvas/Main.dc.html`), а не придуманы под реализацию. Артборд —
 * внешний источник: если формула разойдётся с ним, тест покажет это раньше,
 * чем разойдутся экран и смета.
 */

const room = (
  floorArea: number,
  floorPerimeter: number,
  ceilingPerimeter: number,
  height = 2700,
): RoomMeasure => ({
  floorArea: milliunits(floorArea),
  floorPerimeter: milliunits(floorPerimeter),
  ceilingPerimeter: milliunits(ceilingPerimeter),
  height: milliunits(height),
});

/** Спальня объекта «Московский проспект 116» — единственное помещение, все числа которого объявлены на артборде. */
const СПАЛЬНЯ = room(18_400, 17_600, 17_600);

/**
 * Обмер объекта целиком: семь помещений высотой 2,70 м. Спальня задана
 * артбордом, остальные шесть подобраны под три условия сразу:
 *
 *   1. три измеренных итога совпадают с артбордом — 80,53 / 86,07 / 97,39;
 *   2. периметр потолка каждого помещения не меньше 4·√площадь, то есть
 *      помещение геометрически осуществимо;
 *   3. столбец производных величин на экране сходится с показанным итогом.
 *
 * Третье условие нетривиально. Производные считаются в тысячных, а
 * показываются в сотых, и при неудачном наборе сумма показанных значений
 * расходится с показанным итогом на копейку: первый подобранный набор
 * давал столбец объёма 217,44 при итоге 217,43. На печатной ведомости
 * такой столбец не сходится, и объяснять это прорабу нечем. Здесь третьи
 * знаки появляются ровно у одного помещения — Гостиной.
 */
const ОБМЕР: readonly RoomMeasure[] = [
  room(12_300, 14_100, 18_600), // Коридор
  СПАЛЬНЯ,                      // Спальня
  room(12_700, 13_500, 14_400), // Кухня
  room(23_630, 19_770, 21_390), // Гостиная
  room(1_800, 4_700, 5_400),    // Санузел
  room(4_400, 7_700, 8_400),    // Ванная
  room(7_300, 8_700, 11_600),   // Лоджия
];

describe("производные величины помещения", () => {
  it("площадь стен идёт по периметру потолка", () => {
    // 17,60 м.п. × 2,70 м = 47,52 м² — число с артборда.
    expect(wallArea(СПАЛЬНЯ)).toBe(47_520n);
  });

  it("площадь стен не зависит от периметра пола", () => {
    // Проверка защищает от подмены величины: если формулу однажды переведут
    // на периметр пола, на этом обмере разницы не будет (у спальни оба
    // периметра равны 17,60), а на объекте целиком — тридцать метров.
    const ниша = room(18_400, 15_200, 17_600);
    expect(wallArea(ниша)).toBe(47_520n);
  });

  it("объём идёт по площади пола", () => {
    // 18,40 м² × 2,70 м = 49,68 м³ — число с артборда.
    expect(roomVolume(СПАЛЬНЯ)).toBe(49_680n);
  });

  it("произведение округляется по единственному правилу системы", () => {
    // 12,345 × 2,701 = 33,343845 → 33,344 тысячных: половина вверх.
    const неровное = room(1_000, 1_000, 12_345, 2_701);
    expect(wallArea(неровное)).toBe(33_344n);
  });
});

describe("итоги по объекту", () => {
  const итоги = measureTotals(ОБМЕР);

  it("считает помещения", () => {
    expect(итоги.rooms).toBe(7);
  });

  it("суммирует измеренные величины", () => {
    expect(итоги.floorArea).toBe(80_530n);         // 80,53 м²
    expect(итоги.floorPerimeter).toBe(86_070n);    // 86,07 м.п.
    expect(итоги.ceilingPerimeter).toBe(97_390n);  // 97,39 м.п.
  });

  it("суммирует производные без промежуточного округления", () => {
    // На экране это 262,95 м² и 217,43 м³ — числа с артборда. Округление
    // каждого помещения до сотых с последующим сложением дало бы 217,44.
    expect(итоги.wallArea).toBe(262_953n);
    expect(итоги.volume).toBe(217_431n);
  });

  it("объект без обмера даёт нули, а не отказ", () => {
    const пусто = measureTotals([]);
    expect(пусто.rooms).toBe(0);
    expect(пусто.floorArea).toBe(0n);
    expect(пусто.volume).toBe(0n);
  });
});
