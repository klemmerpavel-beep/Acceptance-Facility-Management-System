    expect(hasWalls(КОМНАТА_2)).toBe(true);
    expect(wallArea(КОМНАТА_2)).toBe(37_800n);
    expect(wallAreaNet(КОМНАТА_2)).toBe(34_020n);
    expect(openingsArea(КОМНАТА_2)).toBe(3_780n);
    expect(wallArea(КОРИДОР_2)).toBe(29_880n);
    expect(wallAreaNet(КОРИДОР_2)).toBe(24_955n);
