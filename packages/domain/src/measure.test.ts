import { describe, expect, it } from "vitest";
import { milliunits } from "./money.js";
import {
  measureTotals, openingsArea, roomVolume, wallArea, wallAreaNet, wallAreaNetWarning, type RoomMeasure,
} from "./measure.js";

/**
 * Контрольные значения взяты с утверждённого артборда обмерного плана
 * (`design/canvas/Main.dc.html`), а не придуманы под реализацию. Артборд —
 * внешний источник: если формула разойдётся с ним, тест покажет это раньше,
 * чем разойдутся экран и смета.
 */

const room = (
  floorArea: number,
  floorPerimeter: number,
  ceilingPerimeter: number,
  height = 2700,
): RoomMeasure => ({
  floorArea: milliunits(floorArea),
  floorPerimeter: milliunits(floorPerimeter),
  ceilingPerimeter: milliunits(ceilingPerimeter),
  height: milliunits(height),
});

/** Спальня объекта «Московский проспект 116» — единственное помещение, все числа которого объявлены на артборде. */
const СПАЛЬНЯ = room(18_400, 17_600, 17_600);

/**
 * Обмер объекта целиком: семь помещений высотой 2,70 м. Спальня задана
 * артбордом, остальные шесть подобраны под три условия сразу:
 *
 *   1. три измеренных итога совпадают с артбордом — 80,53 / 86,07 / 97,39;
 *   2. периметр потолка каждого помещения не меньше 4·√площадь, то есть
 *      помещение геометрически осуществимо;
 *   3. столбец производных величин на экране сходится с показанным итогом.
 *
 * Третье условие нетривиально. Производные считаются в тысячных, а
 * показываются в сотых, и при неудачном наборе сумма показанных значений
 * расходится с показанным итогом на копейку: первый подобранный набор
 * давал столбец объёма 217,44 при итоге 217,43. На печатной ведомости
 * такой столбец не сходится, и объяснять это прорабу нечем. Здесь третьи
 * знаки появляются ровно у одного помещения — Гостиной.
 */
const ОБМЕР: readonly RoomMeasure[] = [
  room(12_300, 14_100, 18_600), // Коридор
  СПАЛЬНЯ,                      // Спальня
  room(12_700, 13_500, 14_400), // Кухня
  room(23_630, 19_770, 21_390), // Гостиная
  room(1_800, 4_700, 5_400),    // Санузел
  room(4_400, 7_700, 8_400),    // Ванная
  room(7_300, 8_700, 11_600),   // Лоджия
];

describe("производные величины помещения", () => {
  it("площадь стен идёт по периметру потолка", () => {
    // 17,60 м.п. × 2,70 м = 47,52 м² — число с артборда.
    expect(wallArea(СПАЛЬНЯ)).toBe(47_520n);
  });

  it("площадь стен не зависит от периметра пола", () => {
    // Проверка защищает от подмены величины: если формулу однажды переведут
    // на периметр пола, на этом обмере разницы не будет (у спальни оба
    // периметра равны 17,60), а на объекте целиком — тридцать метров.
    const ниша = room(18_400, 15_200, 17_600);
    expect(wallArea(ниша)).toBe(47_520n);
  });

  it("объём идёт по площади пола", () => {
    // 18,40 м² × 2,70 м = 49,68 м³ — число с артборда.
    expect(roomVolume(СПАЛЬНЯ)).toBe(49_680n);
  });

  it("произведение округляется по единственному правилу системы", () => {
    // 12,345 × 2,701 = 33,343845 → 33,344 тысячных: половина вверх.
    const неровное = room(1_000, 1_000, 12_345, 2_701);
    expect(wallArea(неровное)).toBe(33_344n);
  });
});

describe("итоги по объекту", () => {
  const итоги = measureTotals(ОБМЕР);

  it("считает помещения", () => {
    expect(итоги.rooms).toBe(7);
  });

  it("суммирует измеренные величины", () => {
    expect(итоги.floorArea).toBe(80_530n);         // 80,53 м²
    expect(итоги.floorPerimeter).toBe(86_070n);    // 86,07 м.п.
    expect(итоги.ceilingPerimeter).toBe(97_390n);  // 97,39 м.п.
  });

  it("суммирует производные без промежуточного округления", () => {
    // На экране это 262,95 м² и 217,43 м³ — числа с артборда. Округление
    // каждого помещения до сотых с последующим сложением дало бы 217,44.
    expect(итоги.wallArea).toBe(262_953n);
    expect(итоги.volume).toBe(217_431n);
  });

  it("объект без обмера даёт нули, а не отказ", () => {
    const пусто = measureTotals([]);
    expect(пусто.rooms).toBe(0);
    expect(пусто.floorArea).toBe(0n);
    expect(пусто.volume).toBe(0n);
  });
});

describe("итоги проёмов по объекту (план, пункт 7.4)", () => {
  const комната = (openings: RoomMeasure["openings"]): RoomMeasure => ({
    floorArea: milliunits(20_000n), floorPerimeter: milliunits(18_000n),
    ceilingPerimeter: milliunits(18_000n), height: milliunits(2_700n),
    ...(openings === undefined ? {} : { openings }),
  });

  it("складывает окна и двери по видам: количество, площадь, откосы", () => {
    const итоги = measureTotals([
      комната([
        { kind: "WINDOW", count: 2, area: milliunits(3_600n), reveal: milliunits(9_800n) },
        { kind: "DOOR", count: 1, area: milliunits(1_870n), reveal: milliunits(5_070n) },
      ]),
      комната([{ kind: "WINDOW", count: 1, area: milliunits(1_500n), reveal: milliunits(4_400n) }]),
    ]);
    expect(итоги.windows).toEqual({ count: 3, area: 5_100n, reveal: 14_200n });
    expect(итоги.doors).toEqual({ count: 1, area: 1_870n, reveal: 5_070n });
  });

  it("помещение без проёмов даёт нули, а не пропуск", () => {
    const итоги = measureTotals([комната(undefined), комната([])]);
    expect(итоги.windows).toEqual({ count: 0, area: 0n, reveal: 0n });
    expect(итоги.doors).toEqual({ count: 0, area: 0n, reveal: 0n });
  });
});

/**
 * Площадь стен за вычетом проёмов (этап Э11, шаг 1; ADR-0002, вариант «б»).
 *
 * Контрольные значения — собственная вымышленная квартира (решение Д6 от
 * 07.11.2026): ни артборда, ни чужих данных. Ответы посчитаны вручную до
 * кода и записаны у каждого помещения; тест сверяет формулу с ними, а не
 * с самой собой. Все величины — тысячные доли.
 *
 * Квартира с подвесным потолком в санузле, поэтому высоты разные, и обе
 * нестандартные: 2,85 м и 2,475 м.
 *
 *   Комната      потолок 15,400 × 2,850 = 43,890 м² брутто;
 *                окно 1 шт 1,960 (1,40 × 1,40) + дверь 1 шт 1,600 (0,80 × 2,00)
 *                = 3,560; нетто 43,890 − 3,560 = 40,330.
 *   Кухня        потолок 12,200 × 2,850 = 34,770; окно 1,820 (1,30 × 1,40)
 *                + дверь 1,400 (0,70 × 2,00) = 3,220; нетто 31,550.
 *   Гардеробная  потолок 6,300 × 2,850 = 17,955; проёмов нет (открытая ниша
 *                без двери) — нетто равна брутто, 17,955.
 *   Санузел      потолок 7,300 × 2,475 = 18,0675 → 18,068 (половина вверх);
 *                дверь 1,200 (0,60 × 2,00); нетто 18,068 − 1,200 = 16,868.
 *   Тамбур       потолок 1,200 × 2,500 = 3,000; две двери 3,200 (по 1,60) —
 *                проёмы больше стен: нетто 0 и предупреждение, не отказ.
 *
 *   Итого брутто 43,890 + 34,770 + 17,955 + 18,068 + 3,000 = 117,683 м²;
 *   нетто 40,330 + 31,550 + 17,955 + 16,868 + 0 = 106,703 м².
 *   Проёмов всего 3,560 + 3,220 + 0 + 1,200 + 3,200 = 11,180, и «брутто
 *   минус проёмы объекта» дало бы 106,503 — на 0,200 меньше: лишек проёмов
 *   тамбура вычелся бы из стен соседних помещений.
 */
const помещение = (
  ceilingPerimeter: number,
  height: number,
  openings?: RoomMeasure["openings"],
): RoomMeasure => ({
  floorArea: milliunits(10_000),
  floorPerimeter: milliunits(ceilingPerimeter),
  ceilingPerimeter: milliunits(ceilingPerimeter),
  height: milliunits(height),
  ...(openings === undefined ? {} : { openings }),
});
const окно = (count: number, area: number): NonNullable<RoomMeasure["openings"]>[number] =>
  ({ kind: "WINDOW", count, area: milliunits(area), reveal: milliunits(0) });
const дверь = (count: number, area: number): NonNullable<RoomMeasure["openings"]>[number] =>
  ({ kind: "DOOR", count, area: milliunits(area), reveal: milliunits(0) });

const КОМНАТА = помещение(15_400, 2_850, [окно(1, 1_960), дверь(1, 1_600)]);
const КУХНЯ = помещение(12_200, 2_850, [окно(1, 1_820), дверь(1, 1_400)]);
const ГАРДЕРОБНАЯ = помещение(6_300, 2_850);
const САНУЗЕЛ = помещение(7_300, 2_475, [дверь(1, 1_200)]);
const ТАМБУР = помещение(1_200, 2_500, [дверь(2, 3_200)]);
const КОНТРОЛЬНАЯ = [КОМНАТА, КУХНЯ, ГАРДЕРОБНАЯ, САНУЗЕЛ, ТАМБУР] as const;

describe("площадь стен за вычетом проёмов: контрольная квартира", () => {
  it("брутто помещений — прежняя формула, проёмы её не трогают", () => {
    expect(КОНТРОЛЬНАЯ.map(wallArea)).toEqual([43_890n, 34_770n, 17_955n, 18_068n, 3_000n]);
  });

  it("проёмы складываются по всем видам: окна и двери вместе", () => {
    expect(КОНТРОЛЬНАЯ.map(openingsArea)).toEqual([3_560n, 3_220n, 0n, 1_200n, 3_200n]);
  });

  it("нетто = брутто − площадь проёмов помещения", () => {
    expect(wallAreaNet(КОМНАТА)).toBe(40_330n);
    expect(wallAreaNet(КУХНЯ)).toBe(31_550n);
  });

  it("помещение без проёмов: нетто равна брутто", () => {
    expect(wallAreaNet(ГАРДЕРОБНАЯ)).toBe(17_955n);
    expect(wallAreaNet(помещение(6_300, 2_850, []))).toBe(17_955n);
    expect(wallAreaNetWarning(ГАРДЕРОБНАЯ)).toBeNull();
  });

  it("нестандартная высота: брутто округлена один раз, нетто — точная разность", () => {
    // 7,300 × 2,475 = 18,0675 → 18,068 по правилу «половина вверх»; 18,068 − 1,200 = 16,868.
    expect(wallArea(САНУЗЕЛ)).toBe(18_068n);
    expect(wallAreaNet(САНУЗЕЛ)).toBe(16_868n);
  });

  it("проёмы больше стен: нетто — ноль, а не минус, и предупреждение называет обе величины", () => {
    expect(wallAreaNet(ТАМБУР)).toBe(0n);
    const предупреждение = wallAreaNetWarning(ТАМБУР);
    expect(предупреждение).toContain("3,20\u00A0м²");
    expect(предупреждение).toContain("3,00\u00A0м²");
    expect(предупреждение).toContain("принята равной нулю");
    // Брутто при этом не меняется: она величина помещения, а не остаток.
    expect(wallArea(ТАМБУР)).toBe(3_000n);
  });

  it("проёмы ровно во всю стену: ноль без предупреждения", () => {
    const впритык = помещение(1_200, 2_500, [дверь(2, 3_000)]);
    expect(wallAreaNet(впритык)).toBe(0n);
    expect(wallAreaNetWarning(впритык)).toBeNull();
  });

  it("у помещения с проёмами меньше стен предупреждения нет", () => {
    expect([КОМНАТА, КУХНЯ, САНУЗЕЛ].map(wallAreaNetWarning)).toEqual([null, null, null]);
  });

  it("итог объекта: брутто прежний, нетто — сумма нетто помещений", () => {
    const итоги = measureTotals(КОНТРОЛЬНАЯ);
    expect(итоги.wallArea).toBe(117_683n);
    expect(итоги.wallAreaNet).toBe(106_703n);
    // Не «брутто минус все проёмы объекта»: это дало бы 106 503 — лишек
    // проёмов тамбура вычелся бы из стен соседних помещений.
    expect(итоги.wallArea - итоги.windows.area - итоги.doors.area).toBe(106_503n);
  });

  it("объект без обмера: нетто — ноль", () => {
    expect(measureTotals([]).wallAreaNet).toBe(0n);
  });
});
