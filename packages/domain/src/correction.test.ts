import { describe, expect, it } from "vitest";
import { kopecks, milliunits } from "./money.js";
import { correctedState, correctionFault, correctionTotal } from "./correction.js";

const строка = (qty: number, цена: number) => ({ qty: milliunits(qty), unitPrice: kopecks(цена) });

describe("поправка к подписанному акту (этап Э9, ДР-3)", () => {
  it("лишний объём: разница отрицательна и считается правилом строки акта", () => {
    // 10,000 м² по 500,00 ₽ → 8,000 м²: акт текущего транша уменьшается на 1 000,00 ₽.
    expect(correctionTotal({ было: строка(10_000, 50_000), стало: строка(8_000, 50_000) })).toBe(-100_000n);
  });

  it("неверная цена: разница — принятый объём на разницу цен", () => {
    expect(correctionTotal({ было: строка(2_500, 40_000), стало: строка(2_500, 44_000) })).toBe(10_000n);
  });

  it("обе стороны округляются по отдельности — как строки актов, которые они повторяют", () => {
    // 0,333 × 1,00 ₽ = 0,33 ₽; 0,334 × 1,00 ₽ = 0,33 ₽: разница ноль, хотя объём изменился.
    expect(correctionTotal({ было: строка(333, 100), стало: строка(334, 100) })).toBe(0n);
  });

  it("следующая поправка начинается с того, чем кончилась последняя", () => {
    const снимок = строка(10_000, 50_000);
    expect(correctedState(снимок, [])).toEqual(снимок);
    expect(correctedState(снимок, [{ стало: строка(9_000, 50_000) }, { стало: строка(8_000, 50_000) }]))
      .toEqual(строка(8_000, 50_000));
  });

  it("причина обязательна; пробелы причиной не считаются", () => {
    const поправка = { было: строка(10_000, 50_000), стало: строка(8_000, 50_000) };
    expect(correctionFault({ ...поправка, причина: "   " })).toMatch(/Причина поправки обязательна/u);
    expect(correctionFault({ ...поправка, причина: "объём перемерен" })).toBeNull();
  });

  it("поправка, которая ничего не меняет, и отрицательные величины не принимаются", () => {
    const было = строка(10_000, 50_000);
    expect(correctionFault({ было, стало: было, причина: "ошибка" })).toMatch(/ничего не меняет/u);
    expect(correctionFault({ было, стало: строка(-1, 50_000), причина: "ошибка" })).toMatch(/Количество/u);
    expect(correctionFault({ было, стало: строка(10_000, -1), причина: "ошибка" })).toMatch(/Цена/u);
  });

  it("объём до нуля — законная поправка: работа не выполнялась вовсе", () => {
    expect(correctionFault({ было: строка(10_000, 50_000), стало: строка(0, 50_000), причина: "не делали" }))
      .toBeNull();
  });
});
