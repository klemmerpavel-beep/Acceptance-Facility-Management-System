/**
 * Заведение записи: номер объекта, код заказчика, вид заказчика.
 *
 * Три правила, которые до сих пор жили в формах и в сервисах порознь и
 * потому расходились. Общее у них одно: всё это решается в тот момент,
 * когда запись заводят, и человеку об этом спрашивать незачем — ответ
 * выводится из того, что уже есть в справочнике.
 *
 * Правила чистые: ни базы, ни запроса, ни текущей даты. Поэтому они
 * испытываются тестом, а не обходом страницы, — и именно поэтому здесь
 * удалось поймать дефект, проживший в продукте два места и три месяца
 * (см. `looksLikeCompany`).
 */

/** Номер объекта: латинская буква, дефис, до четырёх цифр. То же, что в контракте. */
const НОМЕР = /^([A-Z])-(\d{1,4})$/;

/** Предел номера: четыре цифры — столько же, сколько принимает контракт. */
const ПРЕДЕЛ = 9999;

/**
 * Следующий свободный номер объекта.
 *
 * Считается как «наибольший занятый плюс один», а не как «наименьший
 * свободный». Разница видна на портфеле с дырами — R-19, R-27, R-31, R-38,
 * R-42: наименьший свободный вернул бы R-20, то есть номер, который когда-то
 * кому-то уже принадлежал. Номер объекта сквозной: он стоит в теме письма,
 * в акте и в разговоре на объекте, и переиспользованный номер сводит два
 * разных объекта в одной переписке. Дыра в нумерации дешевле.
 *
 * Буква берётся не отсюда: её называет вызывающий (сервер — по последнему
 * заведённому объекту). Правило не угадывает, какую букву человек считает
 * своей, — оно продолжает ту, которая уже в ходу.
 *
 * `null` означает «предложить нечего»: буква не латинская заглавная или
 * номера кончились. Пустое поле честнее подставленного мусора.
 */
export function nextProjectCode(коды: readonly string[], буква: string): string | null {
  if (!/^[A-Z]$/.test(буква)) return null;
  let занято = 0;
  for (const код of коды) {
    const разбор = НОМЕР.exec(код);
    if (разбор?.[1] !== буква) continue;
    const номер = Number(разбор[2]);
    if (номер > занято) занято = номер;
  }
  const следующий = занято + 1;
  return следующий > ПРЕДЕЛ ? null : `${буква}-${следующий}`;
}

/** С какого числа начинается нумерация заказчиков в пустом справочнике. */
const ПЕРВЫЙ_ЗАКАЗЧИК = 100;

/**
 * Следующий свободный код заказчика.
 *
 * Код заказчика короткий и обиходный — «300», «118»: им заказчика называют
 * в разговоре и в теме письма. Правило то же, что у номера объекта:
 * наибольший занятый плюс один, дыры не переиспользуются.
 *
 * Нечисловые коды в справочнике возможны — их заводили руками, — и они
 * пропускаются, а не ломают счёт. Пустой справочник начинается со ста, а не
 * с единицы: трёхзначный код единообразен с уже заведёнными и не читается
 * как порядковый номер строки.
 */
export function nextClientCode(коды: readonly string[]): string {
  let занято = 0;
  for (const код of коды) {
    if (!/^\d{1,6}$/.test(код.trim())) continue;
    const номер = Number(код.trim());
    if (номер > занято) занято = номер;
  }
  return занято === 0 ? String(ПЕРВЫЙ_ЗАКАЗЧИК) : String(занято + 1);
}

/**
 * Организационно-правовая форма в начале названия.
 *
 * Перечень закрытый: формы, которые встречаются у заказчиков ремонта —
 * коммерческие, бюджетные и товарищества собственников. Длинные стоят
 * раньше коротких, иначе «ОАО» разобралось бы как «АО» с хвостом.
 */
const ФОРМА = "ООО|ОАО|ЗАО|ПАО|НАО|АО|ИП|НКО|АНО|ФГУП|ГУП|МУП|ГБУ|МБУ|ТСЖ|ЖСК";

/**
 * Юридическое ли лицо — по названию.
 *
 * «ООО «Гранит-Строй»» и «Анна Мещерякова» различаются без вопроса к
 * человеку, и лишний переключатель в форме заведения не окупается.
 *
 * **Выражение переписано, и это исправление, а не оформление.** Прежнее
 * стояло в двух местах — форме контакта и переводе заявки в объект — и
 * читалось `/^(ООО|АО|ЗАО|ПАО|ИП)\b/u`. Оно не срабатывало никогда: `\b` в
 * регулярных выражениях JavaScript опирается на `\w`, а `\w` — только
 * латиница, цифры и подчёркивание. После кириллического «О» и перед
 * пробелом стоят два не-словесных знака, границы между ними нет, и проверка
 * возвращала `false` на «ООО «Гранит-Строй»» ровно так же, как на «Анна
 * Мещерякова». Все заказчики, заведённые через форму, записаны физическими
 * лицами — включая общества. Комментарий рядом с прежним выражением
 * утверждал обратное, и три месяца это никем не было замечено: неверный
 * признак виден только в графе «Физическое лицо» у общества.
 *
 * Здесь вместо границы слова стоит явное условие: за формой не следует
 * кириллическая буква. Оно ловит «ИПотеку», не отвергая «ИП Смирнов», и не
 * зависит от того, что `\w` считает буквой.
 */
const ЮРЛИЦО = new RegExp(`^(?:${ФОРМА})(?![А-Яа-яЁё])`, "u");

export const looksLikeCompany = (название: string): boolean => ЮРЛИЦО.test(название.trim());
