import { describe, expect, it } from "vitest";
import { looksLikeCompany, nextClientCode, nextProjectCode } from "./directory.js";

describe("следующий номер объекта", () => {
  /* Портфель демонстрации: дыры в нумерации есть, и правило их не
     переиспользует. Наименьший свободный вернул бы R-20. */
  const портфель = ["R-19", "R-27", "R-31", "R-38", "R-42", "R-64", "R-72", "R-99"];

  it("продолжает нумерацию, а не затыкает дыры", () => {
    expect(nextProjectCode(портфель, "R")).toBe("R-100");
  });

  it("пустой портфель начинает с первого номера", () => {
    expect(nextProjectCode([], "R")).toBe("R-1");
  });

  it("чужую букву не считает занятой", () => {
    expect(nextProjectCode(["R-99", "K-7"], "K")).toBe("K-8");
  });

  it("мусор в списке пропускает, а не ломается на нём", () => {
    expect(nextProjectCode(["R-4", "склад", "", "R-abc", "RR-9"], "R")).toBe("R-5");
  });

  /* Предложить нечего — честнее пустого поля со мусором. */
  it.each([
    [["R-9999"], "R"],
    [[], "р"],
    [[], "RR"],
    [[], ""],
  ])("нечего предложить: %j при букве «%s»", (коды, буква) => {
    expect(nextProjectCode(коды, буква)).toBeNull();
  });
});

describe("следующий код заказчика", () => {
  it("продолжает нумерацию справочника", () => {
    expect(nextClientCode(["118", "204", "300", "412"])).toBe("413");
  });

  it("пустой справочник начинает с трёхзначного", () => {
    expect(nextClientCode([])).toBe("100");
  });

  it("нечисловые коды пропускает", () => {
    expect(nextClientCode(["ГС-1", "300", "склад"])).toBe("301");
  });
});

describe("вид заказчика по названию", () => {
  /* Ровно те случаи, на которых прежнее выражение с `\b` возвращало false:
     кириллица не входит в `\w`, и границы слова после «ООО» не возникает.
     Откат к `\b` опрокидывает каждую строку этого перечня. */
  it.each([
    "ООО «Гранит-Строй»",
    "ООО Гранит",
    "ООО",
    "АО Квант",
    "ЗАО Воронежстрой",
    "ПАО «Сбербанк»",
    "ИП Смирнов А. В.",
    "ФГУП НИИ приборостроения",
    "МУП «Горэлектросеть»",
    "ТСЖ «Московский, 116»",
    "  ООО «Гранит-Строй»  ",
  ])("«%s» — юридическое лицо", (название) => {
    expect(looksLikeCompany(название)).toBe(true);
  });

  /* «ИПотека» начинается с «ИП», но формой не является: условие смотрит на
     следующий знак, а не на длину совпадения. */
  it.each([
    "Анна Мещерякова",
    "Ирина Ковалёва",
    "ИПотека для всех",
    "Аонов Сергей",
    "Мастер Ким",
    "",
  ])("«%s» — физическое лицо", (название) => {
    expect(looksLikeCompany(название)).toBe(false);
  });
});
