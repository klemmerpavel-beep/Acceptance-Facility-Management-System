import { describe, expect, it } from "vitest";
import { plural, сколько } from "./plural.js";

describe("согласование числа со словом", () => {
  it.each([
    [0, "дней"], [1, "день"], [2, "дня"], [4, "дня"], [5, "дней"], [11, "дней"], [12, "дней"],
    [14, "дней"], [21, "день"], [22, "дня"], [101, "день"], [111, "дней"], [152, "дня"], [-1, "день"],
  ] as const)("%i — «%s»", (число, форма) => {
    expect(plural(число, "день", "дня", "дней")).toBe(форма);
  });

  it("число и слово одной строкой", () => {
    expect(сколько(21, "позиция", "позиции", "позиций")).toBe("21 позиция");
    expect(сколько(132, "позиция", "позиции", "позиций")).toBe("132 позиции");
  });
});
