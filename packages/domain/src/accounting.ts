/**
 * Бухгалтерия: деньги заказчиков по портфелю.
 *
 * Что раздел считает и чего не считает
 * ------------------------------------
 * Считает движение клиентских денег: сколько предъявлено, сколько ждёт
 * оплаты, сколько получено. Не считает налоги, страховые взносы и зарплаты
 * по графику — они письменно исключены из объёма (`01_PROJECT.md`, раздел
 * 6.2), и раздел с таким именем не повод их туда вернуть. Реальных выплат
 * и банковских связей здесь тоже нет: продукт ведёт запись о деньгах, а не
 * распоряжается ими.
 *
 * Транш и платёж: две величины об одних деньгах
 * ---------------------------------------------
 * До 19.09.2026 транш был единицей учёта денег целиком, и довод против
 * второй сущности звучал так: два учёта одних денег разойдутся на первой же
 * частичной оплате. Ответ заказчика на вопрос 4 квиза от 19.09.2026 завёл
 * платёж всё равно — заказчики платят частями, и это надо видеть.
 *
 * Довод не отменён, а принят к исполнению: расхождение теперь возможно, и
 * потому считается прямо. Решением заказчика от 19.09.2026 оплаченным транш
 * называет **отметка руководителя**, а не сумма платежей. Значит, отметка и
 * платежи могут разойтись — и разошлись бы молча, потому что обе величины
 * выглядят верными по отдельности. Сюда и смотрит `outstanding`: у закрытого
 * транша та же арифметика читается как долг, у оплаченного — как недобор.
 * Одна величина, два чтения, и различает их ровно отметка человека.
 *
 * Порог просрочки живёт у заказчика
 * ---------------------------------
 * Ответ на вопрос 5 квиза от 19.09.2026: порог назначается договором с
 * конкретным заказчиком. Единого порога по компании больше нет; семь дней
 * остаются умолчанием для незаполненного поля, иначе такой заказчик выпал бы
 * из учёта просрочки вовсе.
 *
 * Отсчёт идёт от закрытия транша, и платежи его не двигают — решение
 * заказчика от 19.09.2026. Цена названа: частичный платёж уменьшает
 * просроченную сумму, но не отодвигает дату, поэтому заказчик, заплативший
 * рубль, остаётся просрочившим на остаток. Обратное решение — отсчёт от
 * последнего платежа — делало бы непросроченным любого, кто платит понемногу.
 */

import { kopecks, subtract, sum, type Kopecks } from "./money.js";
import { daysBetween } from "./portfolio.js";

/**
 * Состояние денег транша. Четыре, а не три: между «ждёт оплаты» и «оплачено»
 * появилась частичная оплата, и называть её одним из соседей значило бы
 * прятать ровно то, ради чего заказчик просил её видеть.
 */
export type MoneyState = "в работе" | "ждёт оплаты" | "оплачен частично" | "оплачено";

/** Транш в том виде, в каком его читает арифметика раздела. */
export interface TrancheMoney {
  readonly status: "OPEN" | "CLOSED" | "PAID";
  readonly amount: Kopecks;
  /** Копейки. Сумма платежей по траншу с учётом сторно. */
  readonly paid: Kopecks;
  /** ГГГГ-ММ-ДД. `null` — транш ещё открыт. */
  readonly closedOn: string | null;
  /** Порог просрочки по договору в днях. `null` — действует умолчание. */
  readonly graceDays: number | null;
}

/**
 * Непокрытая платежами часть транша: сумма транша минус оплаченное.
 *
 * Одна арифметика на два вопроса, и различает их отметка руководителя:
 * у закрытого транша это долг заказчика, у оплаченного — недобор, то самое
 * расхождение отметки с платежами. Разводить их по двум функциям значило бы
 * завести два способа посчитать одно, а они расходятся на первой правке.
 *
 * Величина возвращается со знаком: отрицательная — переплата. Обрезать её
 * нулём нельзя по тому же доводу, что и у остатка транша, — переплату
 * заказчика надо видеть, а не прятать.
 */
export function outstanding(tranche: TrancheMoney): Kopecks {
  return subtract(tranche.amount, tranche.paid);
}

/**
 * Состояние денег транша.
 *
 * Открытый транш деньгами к получению не считается: по нему идёт
 * выработка, и сумма к оплате ещё не определена. Назвать её ожидаемой
 * значило бы обещать заказчику счёт, которого никто не выставлял.
 *
 * Отметка руководителя старше арифметики: транш с отметкой «оплачен»
 * называется оплаченным и при недоборе. Расхождение при этом не исчезает —
 * оно считается `outstanding` и показывается рядом с отметкой.
 */
export function moneyState(tranche: TrancheMoney): MoneyState {
  if (tranche.status === "OPEN") return "в работе";
  if (tranche.status === "PAID") return "оплачено";
  const непокрыто = outstanding(tranche) as bigint;
  return (tranche.paid as bigint) > 0n && непокрыто > 0n ? "оплачен частично" : "ждёт оплаты";
}

/**
 * Сколько дней транш закрыт и не оплачен. `null` — считать нечего:
 * транш открыт или уже оплачен.
 */
export function awaitingDays(tranche: TrancheMoney, today: string): number | null {
  if (tranche.status !== "CLOSED" || tranche.closedOn === null) return null;
  return Math.max(0, daysBetween(tranche.closedOn, today));
}

/**
 * Порог, после которого ожидание оплаты названо просрочкой, — для заказчика,
 * у которого он не назначен договором.
 *
 * Семь дней — недельный ритм студии, тот же, которым в продукте меряются
 * сроки объектов. С 19.09.2026 величина перестала быть порогом компании и
 * стала умолчанием: свой порог задаётся в карточке заказчика.
 */
export const PAYMENT_GRACE_DAYS = 7;

/** Порог этого транша: договорный, а при пустом поле — умолчание. */
export function graceDays(tranche: TrancheMoney): number {
  return tranche.graceDays ?? PAYMENT_GRACE_DAYS;
}

export function paymentOverdue(tranche: TrancheMoney, today: string): boolean {
  const дней = awaitingDays(tranche, today);
  if (дней === null || дней <= graceDays(tranche)) return false;
  /* Полностью погашенный закрытый транш просроченным не называется: денег по
     нему не ждут, а отметку руководитель ещё не поставил. Иначе аккуратный
     заказчик оказывался бы просрочившим из-за нашей неснятой отметки. */
  return (outstanding(tranche) as bigint) > 0n;
}

/** Свод денег портфеля. Все величины — копейки. */
export interface MoneyTotals {
  readonly inWork: Kopecks;
  readonly awaiting: Kopecks;
  readonly paid: Kopecks;
  /** Часть ожидающего, просроченная сверх порога. Не слагаемое сверх трёх. */
  readonly overdue: Kopecks;
  /** Часть полученного, не подтверждённая платежами. Не слагаемое сверх трёх. */
  readonly shortfall: Kopecks;
}

/**
 * Свод по портфелю.
 *
 * Просроченное не выделяется в четвёртое слагаемое, а входит в ожидающее:
 * иначе сумма трёх чисел перестала бы сходиться с предъявленным, и человек
 * складывал бы одни и те же деньги дважды. Тем же доводом недобор оставлен
 * вне слагаемых.
 *
 * Сумма трёх по-прежнему равна предъявленному, и это проверяется тестом.
 * Держится она так: у закрытого транша оплаченное уходит в «получено», а
 * непокрытое — в «ждёт оплаты»; у оплаченного в «получено» уходит вся сумма
 * транша, потому что оплаченным его назвал руководитель.
 *
 * Отсюда и берётся `shortfall`: он говорит, какая часть «получено» стоит на
 * отметке, а не на платеже. Без него решение «статус ставит человек»
 * оборачивалось бы завышенным поступлением, которое выглядит верным.
 */
export function moneyTotals(
  tranches: readonly TrancheMoney[],
  today: string,
): MoneyTotals {
  const сложить = (величины: readonly Kopecks[]): Kopecks => sum(величины);
  const непокрытое = (отбор: (t: TrancheMoney) => boolean): Kopecks =>
    сложить(tranches.filter(отбор).map(outstanding));

  return {
    inWork: сложить(tranches.filter((t) => t.status === "OPEN").map((t) => t.amount)),
    awaiting: непокрытое((t) => t.status === "CLOSED"),
    paid: сложить([
      ...tranches.filter((t) => t.status === "CLOSED").map((t) => t.paid),
      ...tranches.filter((t) => t.status === "PAID").map((t) => t.amount),
    ]),
    overdue: непокрытое((t) => paymentOverdue(t, today)),
    shortfall: непокрытое((t) => t.status === "PAID"),
  };
}

/** Сколько заказчик должен и сколько уже заплатил. */
export interface ClientDebt {
  readonly clientId: string;
  readonly name: string;
  readonly awaiting: Kopecks;
  readonly paid: Kopecks;
  readonly overdue: boolean;
  /** Порог просрочки по договору в днях. `null` — действует умолчание. */
  readonly graceDays: number | null;
}

/**
 * Долг по заказчикам, от большего к меньшему.
 *
 * Заказчики без ожидающих и без оплаченных денег в свод не попадают:
 * строка с двумя нулями сообщает ровно то же, что её отсутствие, но
 * занимает место, которого на экране денег мало.
 *
 * Порог берётся у транша, а не у строки заказчика: он и приходит от того же
 * заказчика, и класть его дважды значило бы завести второе место, где он
 * живёт. В строку он попадает затем, чтобы экран назвал, по какому порогу
 * заказчик признан просрочившим, — иначе просрочка выглядит назначенной.
 */
export function clientDebts(
  rows: readonly {
    clientId: string;
    clientName: string;
    tranche: TrancheMoney;
  }[],
  today: string,
): ClientDebt[] {
  const свод = new Map<string, {
    name: string;
    awaiting: bigint;
    paid: bigint;
    overdue: boolean;
    graceDays: number | null;
  }>();
  for (const row of rows) {
    const прежний = свод.get(row.clientId)
      ?? { name: row.clientName, awaiting: 0n, paid: 0n, overdue: false, graceDays: row.tranche.graceDays };
    if (row.tranche.status === "CLOSED") {
      прежний.awaiting += outstanding(row.tranche) as bigint;
      прежний.paid += row.tranche.paid as bigint;
    }
    if (row.tranche.status === "PAID") прежний.paid += row.tranche.amount as bigint;
    if (paymentOverdue(row.tranche, today)) прежний.overdue = true;
    свод.set(row.clientId, прежний);
  }

  return [...свод.entries()]
    .map(([clientId, запись]) => ({
      clientId,
      name: запись.name,
      awaiting: kopecks(запись.awaiting),
      paid: kopecks(запись.paid),
      overdue: запись.overdue,
      graceDays: запись.graceDays,
    }))
    .filter((строка) => (строка.awaiting as bigint) > 0n || (строка.paid as bigint) > 0n)
    .sort((левый, правый) => {
      const разница = (правый.awaiting as bigint) - (левый.awaiting as bigint);
      if (разница !== 0n) return разница > 0n ? 1 : -1;
      return левый.name.localeCompare(правый.name, "ru");
    });
}

/** Что записывают платежом и что об этом уже известно. */
export interface PaymentRequest {
  /** Копейки. Сумма пришедших денег. */
  readonly amount: Kopecks;
  /** ГГГГ-ММ-ДД. День прихода денег по выписке. */
  readonly paidOn: string;
  /** ГГГГ-ММ-ДД. Сегодня. */
  readonly today: string;
  /** Состояние транша, в счёт которого идёт платёж. */
  readonly status: TrancheMoney["status"];
  /** ГГГГ-ММ-ДД. День открытия транша. */
  readonly openedOn: string;
}

/**
 * Причина отказа при записи платежа или null.
 *
 * Единственное место правил платежа: сервер зовёт отсюда, чтобы отказать до
 * записи, экран — чтобы отказать до обращения к сети. Тот же приём, что у
 * `trancheFault` и `acceptanceFault`.
 *
 * Превышение суммы транша отказом не является. Переплату заказчика продукт
 * обязан показать, а не запретить: запрет не вернул бы денег, а спрятал бы
 * их от того, кто пришёл разбираться.
 */
export function paymentFault(request: PaymentRequest): string | null {
  if ((request.amount as bigint) <= 0n) {
    return "Сумма платежа должна быть больше нуля. Ошибочный платёж отменяется сторно.";
  }

  if (request.paidOn > request.today) {
    return "Платёж нельзя записать будущим днём: пишется пришедшее, а не обещанное.";
  }

  if (request.paidOn < request.openedOn) {
    return "Платёж раньше открытия транша. Проверьте дату: деньги в счёт транша "
      + "не приходят до того, как он заведён.";
  }

  if (request.status === "OPEN") {
    return "Транш ещё открыт и сумма к оплате не определена. "
      + "Закройте транш, прежде чем записывать оплату.";
  }

  return null;
}

/** Что известно о сторнируемом платеже. */
export interface PaymentReversal {
  /** Причина сторно, как её ввёл человек. */
  readonly reason: string;
  /** Сторнирован ли платёж уже. */
  readonly reversed: boolean;
  /** Является ли сторнируемая запись сама сторно. */
  readonly isReversal: boolean;
}

/**
 * Причина отказа при сторно платежа или null.
 *
 * Отмена платежа — сторно, а не удаление (БП-04). Причина обязательна по той
 * же причине, что и у сторно приёмки: через месяц спрашивают не «что
 * отменили», а «почему».
 */
export function paymentReversalFault(reversal: PaymentReversal): string | null {
  if (reversal.isReversal) {
    return "Сторно не сторнируется. Ошибка в сторно исправляется новым платежом.";
  }

  if (reversal.reversed) {
    return "Этот платёж уже сторнирован.";
  }

  if (reversal.reason.trim().length === 0) {
    return "Назовите причину сторно: через месяц спрашивают не что отменили, а почему.";
  }

  return null;
}
