import { describe, expect, it } from "vitest";
import { sectionTitle } from "./title.js";

describe("заголовок раздела сметы", () => {
  it.each([
    ["ПОДГОТОВИТЕЛЬНЫЕ РАБОТЫ", "Подготовительные работы"],
    ["ГИПСОКАРТОН, ВОЗВЕДЕНИЕ ПЕРЕГОРОДОК", "Гипсокартон, возведение перегородок"],
    ["ЧЕРНОВОЙ ЭЛЕКТРОМОНТАЖ ( ПО ФАКТУ)", "Черновой электромонтаж (по факту)"],
    ["САНТЕХНИКА И ОТОПЛЕНИЕ (ПО ФАКТУ)", "Сантехника и отопление (по факту)"],
    ["ВАННАЯ/САН УЗЕЛ", "Ванная/САН узел"],
    ["МОНТАЖНЫЕ РАБОТЫ", "Монтажные работы"],
  ])("«%s» → «%s»", (raw, ожидание) => {
    expect(sectionTitle(raw)).toBe(ожидание);
  });

  /* Опечатка сметчика остаётся опечаткой: продукт показывает слова
     заказчика, а не правит их. */
  it("опечатку не правит", () => {
    expect(sectionTitle("ДОПОЛНИТЕЛЬНЫЕ РАСХОДЫ ( ВХОДЕ РАБОТЫ)"))
      .toBe("Дополнительные расходы (входе работы)");
  });

  /* Аббревиатура короче четырёх букв — слово, а не крик. */
  it.each([
    ["ГВС и ХВС", "ГВС и ХВС"],
    ["Подключение ГВС", "Подключение ГВС"],
    ["СЭС", "СЭС"],
  ])("«%s» остаётся как есть", (raw, ожидание) => {
    expect(sectionTitle(raw)).toBe(ожидание);
  });

  it("строчный заголовок не трогает, кроме первой буквы", () => {
    expect(sectionTitle("черновые работы")).toBe("Черновые работы");
  });

  it("смешанный регистр не ломает", () => {
    expect(sectionTitle("ЧИСТОВОЙ ЭЛЕКТРОМОНТАЖ ( По факту)"))
      .toBe("Чистовой электромонтаж (По факту)");
  });

  /* Служебное слово прописными — крик, какой бы длины оно ни было:
     иначе «ПО ФАКТУ» превращается в «ПО факту». */
  it("короткий предлог прописными опускается вместе с соседями", () => {
    expect(sectionTitle("РАБОТЫ ПО ФАКТУ")).toBe("Работы по факту");
    expect(sectionTitle("ДЕМОНТАЖ И ВЫВОЗ")).toBe("Демонтаж и вывоз");
  });

  it("двойные пробелы и пробелы у скобок убирает", () => {
    expect(sectionTitle("Стяжка  пола ( 50 мм )")).toBe("Стяжка пола (50 мм)");
  });

  it("строку без букв возвращает как есть", () => {
    expect(sectionTitle("12,5")).toBe("12,5");
    expect(sectionTitle("")).toBe("");
  });

  /* Работа идеmпотентна: повторный прогон ничего не меняет. Иначе заголовок
     менялся бы от числа перерисовок. */
  it("повторный прогон ничего не меняет", () => {
    const сырой = "ЧЕРНОВОЙ ЭЛЕКТРОМОНТАЖ ( ПО ФАКТУ)";
    const раз = sectionTitle(сырой);
    expect(sectionTitle(раз)).toBe(раз);
  });
});
