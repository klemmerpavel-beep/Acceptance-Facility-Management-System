import { describe, expect, it } from "vitest";
import { groupByDay, photoSections } from "./report.js";

describe("раскладка фотоотчёта по дням", () => {
  it("пустой список даёт пустую раскладку, а не день без записей", () => {
    expect(groupByDay([])).toEqual([]);
  });

  it("дни идут по убыванию: последнее сделанное сверху", () => {
    const дни = groupByDay([
      { at: "2026-09-01T08:00:00.000Z" },
      { at: "2026-09-11T08:00:00.000Z" },
      { at: "2026-09-05T08:00:00.000Z" },
    ]);
    expect(дни.map((день) => день.day)).toEqual(["2026-09-11", "2026-09-05", "2026-09-01"]);
  });

  it("записи одного дня собираются в один день, а не в три", () => {
    const дни = groupByDay([
      { at: "2026-09-11T08:00:00.000Z" },
      { at: "2026-09-11T14:30:00.000Z" },
      { at: "2026-09-11T23:59:59.000Z" },
    ]);
    expect(дни).toHaveLength(1);
    expect(дни[0]?.items).toHaveLength(3);
  });

  it("порядок внутри дня сохраняется: его задаёт выборка", () => {
    const дни = groupByDay([
      { at: "2026-09-11T08:00:00.000Z", id: "первый" },
      { at: "2026-09-11T14:00:00.000Z", id: "второй" },
    ]);
    expect(дни[0]?.items.map((item) => item.id)).toEqual(["первый", "второй"]);
  });

  it("ни одна запись не теряется и не удваивается", () => {
    const записи = Array.from({ length: 17 }, (_, i) => ({
      at: `2026-09-${String((i % 5) + 1).padStart(2, "0")}T10:00:00.000Z`,
    }));
    const всего = groupByDay(записи).reduce((сумма, день) => сумма + день.items.length, 0);
    expect(всего).toBe(17);
  });
});

describe("разделы отбора фотоотчёта", () => {
  const пакет = (sectionName: string, снимков: number) => ({
    sectionName, photos: Array.from({ length: снимков }, (_, i) => `${sectionName}-${i}`),
  });

  it("раздел без снимков в отбор не попадает", () => {
    const разделы = photoSections([пакет("Стены", 0), пакет("Полы", 1)]);
    expect(разделы.map((раздел) => раздел.name)).toEqual(["Полы"]);
  });

  it("снимки одного раздела складываются, а не считаются пакетами", () => {
    const разделы = photoSections([пакет("Стены", 3), пакет("Стены", 2)]);
    expect(разделы).toHaveLength(1);
    expect(разделы[0]?.photos).toBe(5);
  });

  it("одноимённые разделы разных редакций сметы сходятся в один", () => {
    /* Повторный импорт заводит разделы заново: имя то же, опознаватель
       другой. Для отчёта это по-прежнему один раздел объекта. */
    const разделы = photoSections([
      { sectionName: "Подготовительные работы", photos: ["редакция-1"] },
      { sectionName: "Подготовительные работы", photos: ["редакция-2"] },
    ]);
    expect(разделы).toHaveLength(1);
    expect(разделы[0]?.photos).toBe(2);
  });

  it("порядок по имени, а не по числу снимков", () => {
    const разделы = photoSections([
      пакет("Электрика", 9),
      пакет("Демонтаж", 1),
      пакет("Полы", 4),
    ]);
    expect(разделы.map((раздел) => раздел.name)).toEqual(["Демонтаж", "Полы", "Электрика"]);
  });

  it("пустой список пакетов даёт пустой отбор", () => {
    expect(photoSections([])).toEqual([]);
  });
});
