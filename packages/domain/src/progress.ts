/**
 * «Следующее действие» объекта (план, пункт 7.8).
 *
 * Блок «Выполнено N из M» на «Обзоре» отвечает на вопрос, с которым
 * руководитель открывает новый объект: что уже заведено и что делать
 * дальше. Шаги выводятся из данных объекта чистой функцией, а не хранятся
 * отметками: отметка «смета загружена» разошлась бы со сметой на первом же
 * повторном импорте или снятии.
 *
 * Перечень шагов утверждён заказчиком 02.10.2026, порядок — порядок работы
 * над объектом. Шаг, которого нет в данных, не выдумывается: у всех девяти
 * шагов есть источник в базе (замер, смета, график, прораб объекта, вход
 * заказчика, транш № 0, пакет приёмки, закрытый транш, дата подписания
 * акта), и исключённых нет.
 */

/** Ключ шага. */
export type ШагОбъекта =
  | "rooms" | "estimate" | "schedule" | "foreman" | "clientAccess"
  | "prepayment" | "acceptance" | "act" | "signed";

/** Факты объекта: выполнен ли каждый шаг. Сервер выводит их из базы. */
export type ФактыОбъекта = Readonly<Record<ШагОбъекта, boolean>>;

/** Шаги в порядке работы над объектом и их подписи — что сделать. */
export const ШАГИ_ОБЪЕКТА: readonly { readonly key: ШагОбъекта; readonly label: string }[] = [
  { key: "rooms", label: "Завести помещения замера" },
  { key: "estimate", label: "Загрузить смету" },
  { key: "schedule", label: "Составить график работ" },
  { key: "foreman", label: "Назначить прораба" },
  { key: "clientAccess", label: "Выдать вход заказчику" },
  { key: "prepayment", label: "Отметить оплату предоплаты — транш № 0" },
  { key: "acceptance", label: "Провести первую приёмку" },
  { key: "act", label: "Закрыть первый транш актом" },
  { key: "signed", label: "Отметить подписание акта" },
];

/** Итог: сколько выполнено из скольких и первый невыполненный шаг. */
export interface СледующееДействие {
  readonly done: number;
  readonly total: number;
  /** Первый невыполненный шаг по порядку или null — все выполнены. */
  readonly next: { readonly key: ШагОбъекта; readonly label: string } | null;
}

/**
 * Сколько шагов выполнено и какой следующий.
 *
 * Следующий — первый невыполненный по порядку, даже если позже по списку
 * что-то уже сделано: акт, подписанный без выданного входа заказчику, не
 * отменяет того, что вход так и не выдан. Один шаг, а не перечень: блок
 * отвечает на вопрос «что делать», а не «чего не хватает».
 */
export function nextAction(facts: ФактыОбъекта): СледующееДействие {
  const done = ШАГИ_ОБЪЕКТА.filter((шаг) => facts[шаг.key]).length;
  const next = ШАГИ_ОБЪЕКТА.find((шаг) => !facts[шаг.key]) ?? null;
  return { done, total: ШАГИ_ОБЪЕКТА.length, next };
}
