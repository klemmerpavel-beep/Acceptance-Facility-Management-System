import { readdirSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * Выгрузка-значение домена кем-то читается.
 *
 * `PREPAYMENT_NUMBER` объявлял номер транша предоплаты, а сервер, экран и
 * двойник демонстрации писали вместо него литерал `0` в пяти местах;
 * `DEFAULT_SPREAD` объявлял отклонение нового типа ремонта, а лист настроек
 * писал «15»; `planEndsOn` не звал никто (полный аудит 30.09.2026, П-49).
 * Мёртвая константа хуже отсутствующей: читающий верит, что правило одно и
 * живёт здесь, и правит его здесь — без последствий.
 *
 * Мёртвым считается значение, которое не упомянуто нигде, кроме своего
 * объявления: ни продуктом, ни своим модулем. Проверка тестом не в счёт —
 * тест проверяет правило, а не пользуется им.
 */
const КОРЕНЬ = new URL("../../../", import.meta.url).pathname;
const исходники = (путь: string): string[] =>
  readdirSync(`${КОРЕНЬ}${путь}`, { withFileTypes: true }).flatMap((запись) => {
    const полный = `${путь}/${запись.name}`;
    if (запись.isDirectory()) return ["node_modules", "dist"].includes(запись.name) ? [] : исходники(полный);
    return /\.(ts|tsx|mjs)$/u.test(запись.name) && !запись.name.includes(".test.") ? [полный] : [];
  });

const тексты = new Map(["apps", "packages", "scripts"].flatMap(исходники)
  .map((путь) => [путь, readFileSync(`${КОРЕНЬ}${путь}`, "utf8")] as const));

const значения = [...тексты].filter(([путь]) => путь.startsWith("packages/domain/src/"))
  .flatMap(([путь, текст]) => [...текст.matchAll(/^export (?:const|function) ([\p{L}\p{N}_]+)/gmu)]
    .map((пара) => ({ имя: пара[1] ?? "", путь })));

const упоминаний = (имя: string, текст: string): number =>
  (текст.match(new RegExp(`(?<![\\p{L}\\p{N}_$])${имя}(?![\\p{L}\\p{N}_])`, "gu")) ?? []).length;

describe("выгрузки домена", () => {
  it("значений выгружено много: правило проверяет не пустое место", () => {
    expect(значения.length).toBeGreaterThan(100);
  });

  it("каждое выгруженное значение где-то читается", () => {
    const мёртвые = значения.filter(({ имя, путь }) => [...тексты].every(([другой, текст]) =>
      упоминаний(имя, текст) <= (другой === путь ? 1 : 0)))
      .map(({ имя, путь }) => `${путь}: ${имя}`);
    expect(мёртвые).toEqual([]);
  });
});
