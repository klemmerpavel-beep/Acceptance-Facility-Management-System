/**
 * Транш — сумма платежа клиента, в счёт которой идёт выработка.
 *
 * Единственное место правил транша. Сервер зовёт отсюда, чтобы отказать до
 * записи; экран — чтобы отказать до обращения к сети (тот же приём, что у
 * `acceptanceFault` и `stageDateFault`).
 *
 * Почему транш хранит клиентскую сумму, а не стоимость работ
 * ----------------------------------------------------------
 * Транш есть сумма, которую платит клиент, а клиент платит смету с надбавкой
 * «сопровождение объекта». Расчёт остатка по стоимости работ без надбавки
 * расходится с экономикой объекта на 402 726 ₽ (`docs/01_PROJECT.md:178`).
 * Поэтому выработка переводится в клиентскую сумму до вычитания.
 *
 * Почему надбавка применяется одним умножением
 * --------------------------------------------
 * Поэлементное начисление надбавки с округлением до копейки на 132 позициях
 * даёт накопленное расхождение в рублях при целевом значении метрики
 * «расхождение расчёта оплаты труда с ручным — 0» (`docs/01_PROJECT.md:196`).
 * Надбавка применяется к итогу за транш целиком: округление происходит ровно
 * один раз, в `withSurcharge`.
 *
 * Единицы: деньги — целые копейки (`Kopecks`), доли — сотые доли процента
 * (`BasisPoints`, 1200 = 12,00 %). Дробных типов здесь нет ни одного.
 */

import { subtract, shareOf, withSurcharge, type BasisPoints, type Kopecks } from "./money.js";
import { accrualSummary, type AccrualRecord, type AccrualRow } from "./acceptance.js";

/** Состояние транша. Соответствует перечислению `TrancheStatus` в схеме базы. */
export type TrancheStatus = "OPEN" | "CLOSED" | "PAID";

/** Номер транша предоплаты. Ноль — потому что предоплата предшествует работам (Р12). */
export const PREPAYMENT_NUMBER = 0;

/**
 * Клиентская сумма выработки: надбавка одним умножением (БП-05).
 *
 * Отдельная функция, а не прямой вызов `withSurcharge`, потому что она
 * называет смысл величины: «сколько выработанное стоит клиенту». На месте
 * вызова `withSurcharge(produced, share)` читается как оформление, а не как
 * правило, и первый же рефакторинг переносит её на позицию.
 */
export function clientAmount(produced: Kopecks, share: BasisPoints): Kopecks {
  return withSurcharge(produced, share);
}

/**
 * Остаток транша: сумма транша минус клиентская сумма выработки.
 *
 * Отрицательный остаток — перевыработка. Это не ошибка, а нормальное
 * событие, требующее закрытия акта (`docs/03_DESIGN_SYSTEM.md`, раздел 5.6),
 * поэтому величина возвращается со знаком, а не обрезается нулём: обрезание
 * скрыло бы от руководителя ровно то, ради чего он смотрит на полосу.
 */
export function trancheRemainder(
  amount: Kopecks,
  produced: Kopecks,
  share: BasisPoints,
): Kopecks {
  return subtract(amount, clientAmount(produced, share));
}

/**
 * Заполнение полосы транша в сотых долях процента.
 *
 * Больше 10000 — перевыработка. Величина не ограничивается сверху: полоса
 * рисует переполнение своим цветом, а число говорит, насколько вышли.
 */
export function trancheFill(
  amount: Kopecks,
  produced: Kopecks,
  share: BasisPoints,
): BasisPoints {
  return shareOf(clientAmount(produced, share), amount);
}

/** Что заводят: сумма, вид транша и то, что у объекта уже есть. */
export interface TrancheRequest {
  /** Копейки. Сумма платежа клиента по этому траншу. */
  readonly amount: Kopecks;
  /** Заводится ли предоплата (транш № 0). */
  readonly prepayment: boolean;
  /** Номер уже открытого транша объекта или null. */
  readonly openNumber: number | null;
  /** Заведена ли у объекта предоплата. */
  readonly hasPrepayment: boolean;
}

/**
 * Причина отказа при заведении транша или null.
 *
 * Сумма в тексте не называется намеренно. Разделитель разрядов живёт в
 * `packages/ui` и в домен не тянется (тот же довод, что у количеств в
 * `acceptance.ts`), а «400000 ₽» без разделителя на суммах транша в
 * полмиллиона читается хуже, чем номер. Номер уникален у объекта и стоит
 * в списке — по нему транш и находят.
 */
export function trancheFault(request: TrancheRequest): string | null {
  if (request.amount <= 0n) {
    return "Сумма транша должна быть больше нуля.";
  }

  if (request.prepayment && request.hasPrepayment) {
    return "Предоплата уже заведена траншем № 0. Второй предоплаты у объекта не бывает.";
  }

  /* Предоплата заводится оплаченной и выработку не накапливает, поэтому
     открытый транш ей не помеха: деньги уже получены, работы ещё нет. */
  if (!request.prepayment && request.openNumber !== null) {
    return `У объекта уже открыт транш № ${String(request.openNumber)}. `
      + "Закройте его, прежде чем открывать следующий.";
  }

  return null;
}

/**
 * Номер следующего транша: наибольший из заведённых плюс один.
 *
 * Не «количество траншей»: предоплата занимает номер 0, и счёт по количеству
 * дал бы второму траншу номер 2 при существующих 0 и 1.
 */
export function nextTrancheNumber(numbers: readonly number[]): number {
  let наибольший = -1;
  for (const number of numbers) if (number > наибольший) наибольший = number;
  return наибольший + 1;
}

/** Начисление, знающее свой транш. Пакеты до появления траншей дают null. */
export interface TrancheAccrualRecord extends AccrualRecord {
  readonly trancheId: string | null;
}

/**
 * Свод начислений за транш (пункт 3.10).
 *
 * Отбор по траншу, а не по датам открытия и закрытия: транш открывается и
 * закрывается решением руководителя, а приёмка привязывается к нему в момент
 * записи. Отбор по датам разошёлся бы с этой привязкой на любом переносе
 * закрытия и приписал бы траншу чужую работу.
 */
export function accrualsByTranche(
  records: readonly TrancheAccrualRecord[],
  trancheId: string,
): readonly AccrualRow[] {
  return accrualSummary(records.filter((row) => row.trancheId === trancheId));
}
