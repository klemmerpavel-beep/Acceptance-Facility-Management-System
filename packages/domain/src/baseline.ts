import { PAYMENT_GRACE_DAYS } from "./accounting.js";
import { daysBetween } from "./portfolio.js";

/**
 * База метрик до этапа Э9 (решение допроса Э9-12, план доработок 6.5).
 *
 * Этап Э9 переносит в продукт согласование чеков и приёмку актов заказчиком
 * и показывает ему расчёты. Сказать через месяц после запуска, стало ли
 * быстрее, можно только против величин «до», снятых тем же правилом, каким
 * будут сниматься величины «после». Правило живёт здесь; скрипт
 * `scripts/measure-baseline.mjs` только читает базу и переводит моменты в
 * дни организации.
 *
 * Дни и порог берутся теми же правилами, что в продукте (`daysBetween`,
 * `PAYMENT_GRACE_DAYS`): просрочка в замере обязана совпадать с просрочкой на
 * экране денег, и стенд это сверяет (`scripts/verify-baseline.mjs`).
 *
 * Замер на стенде проверяет правило и за базу не выдаётся: данные стенда
 * придуманы. База снимается на рабочей базе заказчика.
 */

/**
 * Окно замера по умолчанию, дней, включая последний день. Три месяца —
 * чтобы окно застало несколько закрытых траншей; окно задаётся и явно, и
 * замер «после» берётся окном той же длины.
 */
export const ОКНО_ЗАМЕРА_ДНЕЙ = 90;

/** Платёж по траншу. Сторно — отрицательной суммой, тем же днём записи. */
export interface ПлатёжЗамера {
  /** ГГГГ-ММ-ДД: день прихода по выписке. */
  readonly день: string;
  /** Копейки. */
  readonly сумма: bigint;
}

export interface ТраншЗамера {
  /** Код объекта и номер транша — для перечня в отчёте. */
  readonly объект: string;
  readonly номер: number;
  /** ГГГГ-ММ-ДД: день закрытия по часовому поясу организации. */
  readonly закрыт: string;
  /** Копейки. */
  readonly сумма: bigint;
  /** Порог оплаты по договору заказчика; `null` — действует умолчание компании. */
  readonly порог: number | null;
  readonly платежи: readonly ПлатёжЗамера[];
  /** ГГГГ-ММ-ДД: день отметки «оплачен» руководителем; `null` — отметки нет. */
  readonly отметкаОплаты: string | null;
  /** ГГГГ-ММ-ДД: день подписи акта по отметке руководителя; `null` — не подписан. */
  readonly подписан: string | null;
}

export interface ЗаказчикЗамера {
  /** ГГГГ-ММ-ДД: день выдачи входа. */
  readonly выдан: string;
  /** ГГГГ-ММ-ДД: день снятия входа; `null` — вход действует. */
  readonly снят: string | null;
  /** ГГГГ-ММ-ДД: дни, в которые открывалась новая сессия (вход по ссылке). */
  readonly заходы: readonly string[];
}

export interface ЧекЗамера {
  /** ГГГГ-ММ-ДД: день записи чека в продукт. */
  readonly создан: string;
  readonly состояние: "DRAFT" | "CONFIRMED" | "REJECTED";
  /** ГГГГ-ММ-ДД: день решения; `null` — решения нет. */
  readonly решён: string | null;
  /**
   * Подтвердил тот же человек, что записал: руководитель, чей чек
   * подтверждается сразу. Разбора такой чек не ждал и в сроки разбора не
   * входит — иначе ноль дней руководителя разбавил бы ожидание прораба.
   */
  readonly самПодтвердил: boolean;
  readonly возмещаемый: boolean;
}

/** Распределение дней: `null` — считать не из чего. */
export interface Дни {
  readonly медиана: number | null;
  readonly наибольшее: number | null;
}

export interface ЗамерОплаты extends Дни {
  /** Закрыто в окне. */
  readonly закрыто: number;
  readonly оплаченоВСрок: number;
  readonly оплаченоСПросрочкой: number;
  /** Не оплачено, порог истёк к концу окна: просрочка, тем же правилом, что в продукте. */
  readonly просрочено: readonly string[];
  /** Не оплачено, порог к концу окна не истёк: исход ещё неизвестен. */
  readonly ждётВПределахПорога: number;
}

export interface ЗамерПодписи extends Дни {
  readonly закрыто: number;
  readonly подписано: number;
  /** Сколько дней ждёт подписи дольше всех неподписанных; `null` — таких нет. */
  readonly дольшеЖдёт: number | null;
}

export interface ЗамерВходов {
  /** Входов, действовавших хотя бы день окна. */
  readonly выдано: number;
  /** Из них заходили хотя бы раз за окно. */
  readonly заходили: number;
  /**
   * Дней с заходом в неделю на заказчика, медиана; десятые доли. Только по
   * входам, действовавшим в окне не меньше недели.
   */
  readonly днейВНеделю: number | null;
}

export interface ЗамерЧеков extends Дни {
  /** Записано в окне. */
  readonly записано: number;
  readonly возмещаемых: number;
  /** Ждали разбора: записаны не руководителем, подтвердившим сразу. */
  readonly ждалиРазбора: number;
  readonly подтверждено: number;
  readonly отклонено: number;
  /** Без решения к концу окна. */
  readonly безРешения: number;
  /** Сколько дней ждёт решения дольше всех; `null` — таких нет. */
  readonly дольшеЖдёт: number | null;
}

export interface ЗамерБазы {
  readonly с: string;
  readonly по: string;
  readonly оплата: ЗамерОплаты;
  readonly подпись: ЗамерПодписи;
  readonly входы: ЗамерВходов;
  readonly чеки: ЗамерЧеков;
}

export interface ДанныеЗамера {
  readonly с: string;
  readonly по: string;
  readonly транши: readonly ТраншЗамера[];
  readonly заказчики: readonly ЗаказчикЗамера[];
  readonly чеки: readonly ЧекЗамера[];
}

/** Строки ГГГГ-ММ-ДД сравниваются как строки: порядок символов совпадает с порядком дней. */
const вОкне = (день: string, с: string, по: string): boolean => день >= с && день <= по;

function дни(значения: readonly number[]): Дни {
  if (значения.length === 0) return { медиана: null, наибольшее: null };
  const ряд = [...значения].sort((a, b) => a - b);
  const середина = Math.floor(ряд.length / 2);
  const медиана = ряд.length % 2 === 1
    ? ряд[середина] ?? 0
    : ((ряд[середина - 1] ?? 0) + (ряд[середина] ?? 0)) / 2;
  return { медиана, наибольшее: ряд[ряд.length - 1] ?? null };
}

/**
 * День оплаты транша к концу окна.
 *
 * Оплаченным транш становится в день, с которого платежи покрывают его сумму
 * и уже не перестают покрывать: сторно, вернувшее платёж, отменяет и день
 * оплаты. Платежи одного дня складываются до сравнения — платёж и его сторно
 * одним днём не дают ложного дня оплаты.
 *
 * Отметка руководителя без покрывающих платежей даёт день отметки: так
 * продукт называет транш оплаченным и при недоборе (`moneyState`). Это
 * верхняя оценка — деньги приходят раньше, чем их отмечают.
 */
function деньОплаты(транш: ТраншЗамера, по: string): string | null {
  const поДням = new Map<string, bigint>();
  for (const платёж of транш.платежи) {
    if (платёж.день > по) continue;
    поДням.set(платёж.день, (поДням.get(платёж.день) ?? 0n) + платёж.сумма);
  }
  let накоплено = 0n;
  let день: string | null = null;
  for (const [когда, сумма] of [...поДням].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    накоплено += сумма;
    if (накоплено >= транш.сумма) день ??= когда;
    else день = null;
  }
  if (день !== null) return день;
  return транш.отметкаОплаты !== null && транш.отметкаОплаты <= по ? транш.отметкаОплаты : null;
}

/** Оплата раньше закрытия — предоплата — считается нулём дней, а не отрицательным числом. */
const неРаньше = (от: string, до: string): number => Math.max(0, daysBetween(от, до));

const порог = (транш: ТраншЗамера): number => транш.порог ?? PAYMENT_GRACE_DAYS;

function замерОплаты(транши: readonly ТраншЗамера[], по: string): ЗамерОплаты {
  const оплачено: number[] = [];
  let вСрок = 0;
  let сПросрочкой = 0;
  let ждёт = 0;
  const просрочено: string[] = [];
  for (const транш of транши) {
    const день = деньОплаты(транш, по);
    if (день !== null) {
      const дней = неРаньше(транш.закрыт, день);
      оплачено.push(дней);
      if (дней <= порог(транш)) вСрок += 1;
      else сПросрочкой += 1;
    } else if (неРаньше(транш.закрыт, по) > порог(транш)) {
      просрочено.push(`${транш.объект} № ${транш.номер}`);
    } else {
      ждёт += 1;
    }
  }
  return {
    закрыто: транши.length,
    ...дни(оплачено),
    оплаченоВСрок: вСрок,
    оплаченоСПросрочкой: сПросрочкой,
    просрочено: просрочено.sort(),
    ждётВПределахПорога: ждёт,
  };
}

function замерПодписи(транши: readonly ТраншЗамера[], по: string): ЗамерПодписи {
  const подписано: number[] = [];
  const ждут: number[] = [];
  for (const транш of транши) {
    if (транш.подписан !== null && транш.подписан <= по) подписано.push(неРаньше(транш.закрыт, транш.подписан));
    else ждут.push(неРаньше(транш.закрыт, по));
  }
  return {
    закрыто: транши.length,
    подписано: подписано.length,
    ...дни(подписано),
    дольшеЖдёт: ждут.length === 0 ? null : Math.max(...ждут),
  };
}

/**
 * Входы заказчика. Истории заходов продукт не хранит, и дни заходов
 * собирает скрипт из того, что сохранилось, — замер даёт нижнюю границу.
 * Считаются дни с заходом, а не сессии: два входа за вечер — один интерес к
 * объекту, а не два.
 *
 * Неделя меряется по сроку действия входа внутри окна: заказчик, получивший
 * вход за три недели до конца окна, не должен выглядеть равнодушным. Вход,
 * действовавший меньше недели, в частоту не входит: один заход за первый же
 * день дал бы «семь дней в неделю».
 */
const НЕДЕЛЯ = 7;

function замерВходов(заказчики: readonly ЗаказчикЗамера[], с: string, по: string): ЗамерВходов {
  const действовавшие = заказчики.filter((заказчик) =>
    заказчик.выдан <= по && (заказчик.снят === null || заказчик.снят >= с));
  const вНеделю: number[] = [];
  let заходили = 0;
  for (const заказчик of действовавшие) {
    const от = заказчик.выдан > с ? заказчик.выдан : с;
    const до = заказчик.снят !== null && заказчик.снят < по ? заказчик.снят : по;
    const днейЗахода = new Set(заказчик.заходы.filter((день) => вОкне(день, от, до))).size;
    if (днейЗахода > 0) заходили += 1;
    const днейДействия = daysBetween(от, до) + 1;
    if (днейДействия >= НЕДЕЛЯ) вНеделю.push(Math.round((днейЗахода / (днейДействия / НЕДЕЛЯ)) * 10) / 10);
  }
  return { выдано: действовавшие.length, заходили, днейВНеделю: дни(вНеделю).медиана };
}

function замерЧеков(чеки: readonly ЧекЗамера[], по: string): ЗамерЧеков {
  const ждали = чеки.filter((чек) => !чек.самПодтвердил);
  const срокиРешения: number[] = [];
  const ожидание: number[] = [];
  let подтверждено = 0;
  let отклонено = 0;
  for (const чек of ждали) {
    if (чек.состояние !== "DRAFT" && чек.решён !== null && чек.решён <= по) {
      срокиРешения.push(неРаньше(чек.создан, чек.решён));
      if (чек.состояние === "CONFIRMED") подтверждено += 1;
      else отклонено += 1;
    } else {
      ожидание.push(неРаньше(чек.создан, по));
    }
  }
  return {
    записано: чеки.length,
    возмещаемых: чеки.filter((чек) => чек.возмещаемый).length,
    ждалиРазбора: ждали.length,
    ...дни(срокиРешения),
    подтверждено,
    отклонено,
    безРешения: ожидание.length,
    дольшеЖдёт: ожидание.length === 0 ? null : Math.max(...ожидание),
  };
}

/**
 * Замер базы за окно `[с, по]`, оба края включительно.
 *
 * Транши отбираются по дню закрытия, чеки — по дню записи: замеряется то,
 * что началось в окне, а исход — к его концу. Всё, что случилось позже
 * `по`, не видно, и повторный замер того же окна даёт те же числа, пока
 * данные окна не правили.
 */
export function замерБазы(данные: ДанныеЗамера): ЗамерБазы {
  const { с, по } = данные;
  if (daysBetween(с, по) < 0) throw new Error(`Окно замера пусто: ${с} позже ${по}`);
  const транши = данные.транши.filter((транш) => вОкне(транш.закрыт, с, по));
  return {
    с,
    по,
    оплата: замерОплаты(транши, по),
    подпись: замерПодписи(транши, по),
    входы: замерВходов(данные.заказчики, с, по),
    чеки: замерЧеков(данные.чеки.filter((чек) => вОкне(чек.создан, с, по)), по),
  };
}

/** Доля целым процентом; `null` — делить не на что. */
export function процент(часть: number, целое: number): number | null {
  return целое === 0 ? null : Math.round((часть / целое) * 100);
}
