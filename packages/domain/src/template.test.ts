import { describe, expect, it } from "vitest";
import {
  fillTemplate, templateFault, templateVariables, unknownVariables, VARIABLES,
} from "./template.js";

describe("метки шаблона", () => {
  it("находит метки в порядке появления, без повторов", () => {
    const текст = "Объект {{объект.код}} по адресу {{объект.адрес}}, код {{объект.код}}.";
    expect(templateVariables(текст)).toEqual(["объект.код", "объект.адрес"]);
  });

  it("принимает пробелы внутри метки: вписанное руками — та же метка", () => {
    expect(templateVariables("{{ объект.код }}")).toEqual(["объект.код"]);
  });

  it("текст без меток не даёт ни одной", () => {
    expect(templateVariables("Стороны заключили договор.")).toEqual([]);
  });

  it("одиночная скобка меткой не считается", () => {
    expect(templateVariables("{объект.код} и {{{}}}")).toEqual([]);
  });

  it("называет неизвестные и молчит о известных", () => {
    expect(unknownVariables("{{объект.код}} {{объект.цвет}}")).toEqual(["объект.цвет"]);
    expect(unknownVariables("{{объект.код}} {{контрагент.реквизиты}}")).toEqual([]);
  });
});

describe("подстановка", () => {
  it("подставляет значение известной метки", () => {
    expect(fillTemplate("Объект {{объект.код}}", { "объект.код": "R-99" }))
      .toBe("Объект R-99");
  });

  it("известная метка без значения даёт прочерк, а не пустоту", () => {
    expect(fillTemplate("Реквизиты: {{исполнитель.реквизиты}}", { "исполнитель.реквизиты": null }))
      .toBe("Реквизиты: —");
    expect(fillTemplate("Реквизиты: {{исполнитель.реквизиты}}", {}))
      .toBe("Реквизиты: —");
    expect(fillTemplate("Реквизиты: {{исполнитель.реквизиты}}", { "исполнитель.реквизиты": "" }))
      .toBe("Реквизиты: —");
  });

  it("неизвестная метка остаётся меткой и видна в документе", () => {
    expect(fillTemplate("{{объект.цвет}}", { "объект.цвет": "синий" })).toBe("{{объект.цвет}}");
  });

  it("подставляет несколько меток за один проход", () => {
    const вышло = fillTemplate("{{объект.код}} — {{объект.адрес}}", {
      "объект.код": "R-99", "объект.адрес": "Воронеж, Кольцовская, 1",
    });
    expect(вышло).toBe("R-99 — Воронеж, Кольцовская, 1");
  });

  it("пробелы внутри метки подстановке не мешают", () => {
    expect(fillTemplate("{{ объект.код }}", { "объект.код": "R-42" })).toBe("R-42");
  });
});

describe("отказ при заведении шаблона", () => {
  const пункт = { title: "Предмет договора", body: "Объект {{объект.код}}." };

  it("возражений нет у исправного шаблона", () => {
    expect(templateFault({ name: "Договор подряда", clauses: [пункт] })).toBeNull();
  });

  it("шаблон без наименования отвергается", () => {
    expect(templateFault({ name: "  ", clauses: [пункт] }))
      .toBe("У шаблона нет наименования: в списке его будет не найти.");
  });

  it("шаблон без пунктов отвергается", () => {
    expect(templateFault({ name: "Договор", clauses: [] }))
      .toBe("В шаблоне нет ни одного пункта: выпускать нечего.");
  });

  it("пункт без заголовка отвергается", () => {
    expect(templateFault({ name: "Договор", clauses: [{ title: "", body: "текст" }] }))
      .toBe("У пункта нет заголовка.");
  });

  it("неизвестная переменная названа в отказе", () => {
    const отказ = templateFault({
      name: "Договор",
      clauses: [{ title: "Предмет", body: "Цвет {{объект.цвет}}" }],
    });
    expect(отказ).toContain("объект.цвет");
  });

  it("неизвестная переменная в заголовке тоже находится", () => {
    const отказ = templateFault({
      name: "Договор",
      clauses: [{ title: "Пункт {{раздел.имя}}", body: "текст" }],
    });
    expect(отказ).toContain("раздел.имя");
  });
});

describe("перечень переменных", () => {
  it("имена не повторяются", () => {
    const имена = VARIABLES.map((переменная) => переменная.name);
    expect(new Set(имена).size).toBe(имена.length);
  });

  it("каждое имя устроено как «группа.поле»", () => {
    for (const переменная of VARIABLES) {
      expect(переменная.name).toMatch(/^[а-яё]+\.[а-яё]+$/u);
    }
  });

  it("группа имени совпадает с объявленной группой переменной", () => {
    for (const переменная of VARIABLES) {
      const приставка = переменная.name.split(".")[0];
      /* Исполнитель и организация — одна сторона в разных ролях, поэтому
         приставка «исполнитель» законно стоит в своей группе. */
      expect(приставка).toBe(переменная.group);
    }
  });
});
