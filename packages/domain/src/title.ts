/**
 * Заголовок раздела сметы в человеческом виде.
 *
 * Смета приходит из `.xlsx`, и разделы в ней набраны так, как их набрал
 * сметчик: прописными, с двойными пробелами и с пробелом после открывающей
 * скобки — «ЧЕРНОВОЙ ЭЛЕКТРОМОНТАЖ ( ПО ФАКТУ)». До сих пор продукт печатал
 * это как есть в четырёх местах: составе сметы на карточке, списке разделов
 * приёмки, отборе фотоотчёта и самой таблице сметы. Прописные в три строки
 * читаются медленнее строчных и на узкой колонке ломаются посреди слова.
 *
 * Правится вид, а не содержание. Опечатка «( ВХОДЕ РАБОТЫ)» остаётся
 * опечаткой: исправлять слова заказчика продукт не вправе — он их
 * показывает. Данные не трогаются вовсе: в базе лежит исходная строка, и
 * сверка с файлом сметы остаётся возможной.
 *
 * Аббревиатуры короче четырёх букв остаются прописными: «ГВС», «ХВС»,
 * «СЭС» — это слова, а не крик.
 */

/** Длина прописного слова, начиная с которой оно считается криком, а не аббревиатурой. */
const КРИК = 4;

/**
 * Короткие служебные слова. Без этого списка «ПО ФАКТУ» превращается в
 * «ПО факту»: предлог из двух букв неотличим от аббревиатуры по длине, и
 * правило длины оставляет его прописным. Список закрытый и короткий —
 * предлоги и союзы, которые встречаются в названиях разделов сметы.
 */
const СЛУЖЕБНЫЕ = new Set([
  "по", "и", "в", "на", "с", "к", "у", "за", "из", "от", "до", "при",
  "для", "о", "об", "над", "под", "а", "или", "без",
]);

const строчными = (слово: string): string => слово.toLocaleLowerCase("ru-RU");

/** Прописное ли слово целиком: буквы есть, и все они верхнего регистра. */
const прописное = (слово: string): boolean => {
  const буквы = слово.match(/\p{L}/gu) ?? [];
  if (буквы.length === 0) return false;
  return буквы.every((знак) => знак === знак.toLocaleUpperCase("ru-RU")
    && знак !== знак.toLocaleLowerCase("ru-RU"));
};

/**
 * Слово, набранное криком. Аббревиатура короче четырёх букв — не крик:
 * «ГВС», «ХВС», «СЭС» так и пишутся. Служебное слово — тоже не крик, какой
 * бы длины оно ни было.
 */
const кричит = (слово: string): boolean => {
  if (!прописное(слово)) return false;
  const буквы = слово.match(/\p{L}/gu) ?? [];
  if (СЛУЖЕБНЫЕ.has(строчными(буквы.join("")))) return true;
  return буквы.length >= КРИК;
};

export function sectionTitle(raw: string): string {
  const прибранный = raw
    .replace(/\s+/gu, " ")
    .replace(/\(\s+/gu, "(")
    .replace(/\s+\)/gu, ")")
    .trim();

  /* Слова режутся по небуквенным знакам вместе с ними: «ВАННАЯ/САН УЗЕЛ»
     распадается на «ВАННАЯ», «/», «САН», « », «УЗЕЛ», и аббревиатура в
     середине переживает правку соседей. */
  const строка = прибранный
    .split(/(\P{L}+)/u)
    .map((кусок) => (кричит(кусок) ? строчными(кусок) : кусок))
    .join("");

  /* Первая буква строки — прописная, где бы она ни стояла: строка может
     начинаться со скобки или цифры. Замена по образцу срабатывает один раз
     и находит именно первую букву, а не первый знак. */
  return строка.replace(/\p{L}/u, (знак) => знак.toLocaleUpperCase("ru-RU"));
}
