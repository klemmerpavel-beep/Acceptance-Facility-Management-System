/**
 * Фотоотчёт: раскладка по дням.
 *
 * Правило вынесено из сервера сюда не ради красоты. На стенде все приёмки
 * заводятся в один заход и получают время сервера, поэтому двух дней там не
 * бывает, и проверка порядка поверх HTTP не может упасть ни при какой
 * ошибке сортировки. Проверка, которая не падает, ничего не стережёт —
 * значит, правилу место там, где его можно испытать: в домене, на
 * придуманных датах.
 */

/** Запись с отметкой времени в ISO. День берётся из неё, а не передаётся. */
export interface Dated { at: string }

export interface Day<T extends Dated> {
  /** `ГГГГ-ММ-ДД`. */
  day: string;
  items: T[];
}

/**
 * Раскладывает записи по дням: дни — по убыванию, записи внутри дня — в
 * порядке, в котором пришли.
 *
 * Убывание не украшение: отчёт открывают, чтобы увидеть последнее
 * сделанное. Порядок внутри дня сохраняется — его задаёт выборка, и
 * переставлять её здесь значило бы завести второе место, где решается
 * порядок.
 */
export function groupByDay<T extends Dated>(items: readonly T[]): Day<T>[] {
  const поДням = new Map<string, T[]>();
  for (const item of items) {
    const день = item.at.slice(0, 10);
    const список = поДням.get(день);
    if (список === undefined) поДням.set(день, [item]);
    else список.push(item);
  }
  return [...поДням.entries()]
    .sort(([левый], [правый]) => правый.localeCompare(левый))
    .map(([day, список]) => ({ day, items: список }));
}

/** Пакет отчёта в том виде, в каком он нужен для списка разделов отбора. */
export interface Shot {
  sectionName: string;
  photos: readonly unknown[];
}

export interface PhotoSection {
  name: string;
  photos: number;
}

/**
 * Разделы для отбора «по этапу»: имя и число снимков.
 *
 * Считается по имени, а не по опознавателю раздела. Отчёт охватывает все
 * редакции сметы, а новая редакция заводит разделы заново — с теми же
 * именами и другими опознавателями. По опознавателю получилось бы две
 * одинаковые надписи, каждая с половиной снимков; на объекте раздел один.
 *
 * Раздел без единого снимка в список не попадает — отбор, который ничего
 * не находит, это не отбор. Порядок по имени, а не по числу снимков: место
 * раздела не должно переезжать от того, что прораб снял сегодня.
 *
 * Правило живёт здесь, а не в сервере, по той же причине, что и раскладка
 * по дням: на стенде у каждого пакета ровно один снимок, и «считать
 * снимки» неотличимо от «считать пакеты». Здесь отличимо.
 */
export function photoSections(batches: readonly Shot[]): PhotoSection[] {
  const разделы = new Map<string, number>();
  for (const пакет of batches) {
    if (пакет.photos.length === 0) continue;
    разделы.set(пакет.sectionName, (разделы.get(пакет.sectionName) ?? 0) + пакет.photos.length);
  }
  return [...разделы.entries()]
    .map(([name, photos]) => ({ name, photos }))
    .sort((левый, правый) => левый.name.localeCompare(правый.name, "ru"));
}
