import { describe, expect, it } from "vitest";
import { замерБазы, процент, type ДанныеЗамера, type ТраншЗамера, type ЧекЗамера } from "./baseline.js";

const транш = (поля: Partial<ТраншЗамера> & Pick<ТраншЗамера, "закрыт">): ТраншЗамера => ({
  объект: "R-99", номер: 1, сумма: 100_000n, порог: null, платежи: [], отметкаОплаты: null, подписан: null, ...поля,
});

const чек = (поля: Partial<ЧекЗамера> & Pick<ЧекЗамера, "создан">): ЧекЗамера => ({
  состояние: "DRAFT", решён: null, самПодтвердил: false, возмещаемый: true, ...поля,
});

const окно = (поля: Partial<ДанныеЗамера>): ДанныеЗамера =>
  ({ с: "2026-09-01", по: "2026-09-30", транши: [], заказчики: [], чеки: [], ...поля });

describe("база метрик до Э9: дни до оплаты", () => {
  it("день оплаты — день, с которого платежи покрывают сумму", () => {
    const { оплата } = замерБазы(окно({
      транши: [транш({
        закрыт: "2026-09-01",
        платежи: [{ день: "2026-09-03", сумма: 40_000n }, { день: "2026-09-05", сумма: 60_000n }],
      })],
    }));
    expect(оплата).toMatchObject({ закрыто: 1, медиана: 4, наибольшее: 4, оплаченоВСрок: 1 });
  });

  it("сторно, вернувшее платёж, отменяет день оплаты; платёж и сторно одним днём оплатой не считаются", () => {
    const { оплата } = замерБазы(окно({
      транши: [
        транш({
          номер: 1,
          закрыт: "2026-09-01",
          платежи: [
            { день: "2026-09-02", сумма: 100_000n },
            { день: "2026-09-04", сумма: -100_000n },
            { день: "2026-09-12", сумма: 100_000n },
          ],
        }),
        транш({
          номер: 2,
          закрыт: "2026-09-01",
          платежи: [{ день: "2026-09-02", сумма: 100_000n }, { день: "2026-09-02", сумма: -100_000n }],
        }),
      ],
    }));
    expect(оплата.медиана).toBe(11);
    expect(оплата.оплаченоСПросрочкой).toBe(1);
    expect(оплата.просрочено).toEqual(["R-99 № 2"]);
  });

  it("отметка руководителя без покрывающих платежей даёт день отметки — недобор не прячет оплату", () => {
    const { оплата } = замерБазы(окно({
      транши: [транш({
        закрыт: "2026-09-10", платежи: [{ день: "2026-09-12", сумма: 99_500n }], отметкаОплаты: "2026-09-14",
      })],
    }));
    expect(оплата).toMatchObject({ медиана: 4, оплаченоВСрок: 1, просрочено: [] });
  });

  it("порог — договорный, при пустом поле — умолчание компании", () => {
    // Двадцать дней без оплаты: по договору в тридцать — ещё не просрочка, по умолчанию в семь — уже.
    const { оплата } = замерБазы(окно({
      транши: [
        транш({ номер: 1, закрыт: "2026-09-10", порог: 30 }),
        транш({ номер: 2, закрыт: "2026-09-10", порог: null }),
      ],
    }));
    expect(оплата.ждётВПределахПорога).toBe(1);
    expect(оплата.просрочено).toEqual(["R-99 № 2"]);
  });

  it("ровно порог дней — ещё в срок, тем же правилом, что просрочка в продукте", () => {
    const { оплата } = замерБазы(окно({
      по: "2026-09-08",
      транши: [
        транш({ закрыт: "2026-09-01" }),
        транш({ номер: 2, закрыт: "2026-09-01", платежи: [{ день: "2026-09-08", сумма: 100_000n }] }),
      ],
    }));
    expect(оплата).toMatchObject({ ждётВПределахПорога: 1, оплаченоВСрок: 1, просрочено: [] });
  });

  it("предоплата до закрытия — ноль дней, а не отрицательное число", () => {
    const { оплата } = замерБазы(окно({
      транши: [транш({ закрыт: "2026-09-10", платежи: [{ день: "2026-09-05", сумма: 100_000n }] })],
    }));
    expect(оплата.медиана).toBe(0);
  });

  it("окно отбирает по дню закрытия; платёж и отметка после конца окна не видны", () => {
    const { оплата } = замерБазы(окно({
      транши: [
        транш({ номер: 1, закрыт: "2026-08-31" }),
        транш({
          номер: 2, закрыт: "2026-09-20",
          платежи: [{ день: "2026-10-01", сумма: 100_000n }], отметкаОплаты: "2026-10-01",
        }),
      ],
    }));
    expect(оплата.закрыто).toBe(1);
    expect(оплата.медиана).toBeNull();
    expect(оплата.просрочено).toEqual(["R-99 № 2"]);
  });

  it("медиана чётного ряда — среднее двух средних", () => {
    const { оплата } = замерБазы(окно({
      транши: [1, 2, 3, 4].map((номер, i) => транш({
        номер, закрыт: "2026-09-01", порог: 30, платежи: [{ день: `2026-09-0${2 + i * 2}`, сумма: 100_000n }],
      })),
    }));
    expect(оплата).toMatchObject({ медиана: 4, наибольшее: 7 });
  });
});

describe("база метрик до Э9: дни до подписи акта", () => {
  it("подписанные — дни от закрытия; неподписанные — сколько ждёт дольше всех", () => {
    const { подпись } = замерБазы(окно({
      транши: [
        транш({ номер: 1, закрыт: "2026-09-01", подписан: "2026-09-06" }),
        транш({ номер: 2, закрыт: "2026-09-10" }),
        транш({ номер: 3, закрыт: "2026-09-25", подписан: "2026-10-02" }),
      ],
    }));
    expect(подпись).toMatchObject({ закрыто: 3, подписано: 1, медиана: 5, дольшеЖдёт: 20 });
  });
});

describe("база метрик до Э9: входы заказчика", () => {
  it("дни с заходом, а не сессии; неделя — по сроку действия входа внутри окна", () => {
    const { входы } = замерБазы(окно({
      заказчики: [
        // Действовал всё окно (30 дней), заходил три разных дня — 0,7 в неделю.
        {
          выдан: "2026-08-01", снят: null,
          заходы: ["2026-09-02", "2026-09-02", "2026-09-10", "2026-09-20", "2026-08-15"],
        },
        // Выдан за неделю до конца окна, заходил дважды — 2 в неделю.
        { выдан: "2026-09-24", снят: null, заходы: ["2026-09-24", "2026-09-26"] },
        // Выдан накануне конца окна: заходил, но в частоту не входит — иначе «7 в неделю».
        { выдан: "2026-09-29", снят: null, заходы: ["2026-09-29"] },
        // Снят до окна — не считается.
        { выдан: "2026-07-01", снят: "2026-08-20", заходы: ["2026-07-02"] },
        // Действовал, не заходил.
        { выдан: "2026-09-01", снят: "2026-09-14", заходы: [] },
      ],
    }));
    expect(входы).toEqual({ выдано: 4, заходили: 3, днейВНеделю: 0.7 });
  });

  it("без заказчиков — считать не из чего", () => {
    expect(замерБазы(окно({})).входы).toEqual({ выдано: 0, заходили: 0, днейВНеделю: null });
  });
});

describe("база метрик до Э9: разбор чеков", () => {
  it("чек руководителя, подтверждённый сразу, разбора не ждал и в сроки не входит", () => {
    const { чеки } = замерБазы(окно({
      чеки: [
        чек({
          создан: "2026-09-01", состояние: "CONFIRMED", решён: "2026-09-01", самПодтвердил: true, возмещаемый: false,
        }),
        чек({ создан: "2026-09-02", состояние: "CONFIRMED", решён: "2026-09-05" }),
        чек({ создан: "2026-09-03", состояние: "REJECTED", решён: "2026-09-04" }),
        чек({ создан: "2026-09-10" }),
        // Решён после конца окна — к концу окна без решения.
        чек({ создан: "2026-09-20", состояние: "CONFIRMED", решён: "2026-10-03" }),
        // Записан до окна — не считается.
        чек({ создан: "2026-08-30" }),
      ],
    }));
    expect(чеки).toEqual({
      записано: 5, возмещаемых: 4, ждалиРазбора: 4, медиана: 2, наибольшее: 3,
      подтверждено: 1, отклонено: 1, безРешения: 2, дольшеЖдёт: 20,
    });
  });
});

describe("база метрик до Э9: окно и доля", () => {
  it("окно, где начало позже конца, — ошибка, а не пустой замер", () => {
    expect(() => замерБазы(окно({ с: "2026-10-01", по: "2026-09-30" }))).toThrow(/Окно замера пусто/u);
  });

  it("дата не в формате ГГГГ-ММ-ДД — ошибка данных", () => {
    expect(() => замерБазы(окно({ по: "30.09.2026" }))).toThrow(/ГГГГ-ММ-ДД/u);
  });

  it("доля — целым процентом; делить не на что — null", () => {
    expect(процент(2, 3)).toBe(67);
    expect(процент(0, 0)).toBeNull();
  });
});
