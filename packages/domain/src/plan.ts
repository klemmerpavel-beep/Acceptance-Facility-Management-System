/**
 * Заведение графика из разделов сметы (стадия C.3).
 *
 * Сегодня этап заводится руками, по одному, и на смете в одиннадцать
 * разделов это одиннадцать листов подряд. Разделы при этом уже названы,
 * упорядочены и оценены — всё, из чего состоит черновик графика, в смете
 * лежит. Действие переносит его оттуда, а дальше человек тянет отрезки
 * указателем, как и раньше.
 *
 * Почему вес — деньги, а не число позиций
 * ---------------------------------------
 * Раздел из трёх позиций по полмиллиона делается дольше раздела из
 * тридцати позиций по тысяче. Число строк меряет подробность сметы, а не
 * объём работ; стоимость работ — единственная измеренная величина, которая
 * в смете есть. Она тоже не идеальна (дорогой материал не значит долгих
 * работ), но она измерена, а не выдумана — то же основание, по которому
 * готовность объекта взвешивается длительностью этапов.
 *
 * Почему этапы идут подряд, без перекрытий
 * ----------------------------------------
 * На объекте работы идут внахлёст: электрика тянется, пока штукатурят
 * дальнюю комнату. Но какие именно перекрываются — знает прораб, а не
 * система. Последовательная раскладка — заведомо грубый черновик, который
 * видно и легко поправить; выдуманное перекрытие выглядело бы решением,
 * которого никто не принимал.
 */

import { divideRoundHalfUp, type Kopecks } from "./money.js";
import { daysBetween } from "./portfolio.js";
import { shiftDay } from "./schedule.js";

/** Раздел сметы как вес в раскладке: имя, стоимость работ и число позиций. */
export interface SectionWeight {
  readonly id: string;
  readonly name: string;
  /** Стоимость работ раздела вместе с вложенными, копейки. */
  readonly total: Kopecks;
  /**
   * Позиции раздела вместе с вложенными. Раздел без единой позиции работ
   * не ведёт: это заголовок сметы, а не работа. Этап по нему нечего
   * принимать, и в графике он занимал бы день ни за что.
   */
  readonly positions: number;
}

/** Этап, предложенный раскладкой. Прогресс нулевой: работа не начата. */
export interface PlannedStage {
  readonly sectionId: string;
  readonly name: string;
  /** ГГГГ-ММ-ДД. */
  readonly startsOn: string;
  /** ГГГГ-ММ-ДД, включительно. */
  readonly endsOn: string;
  /** Длительность в днях, обе границы включительно. */
  readonly days: number;
}

/** Окно раскладки: обе границы включительно. */
export interface PlanBounds {
  readonly from: string;
  readonly to: string;
}

/**
 * Разделы, разложенные по окну пропорционально стоимости работ.
 *
 * Каждому разделу сперва отводится по дню, и лишь остаток окна делится по
 * стоимости. Порядок именно такой: дешёвый раздел иначе получал бы ноль
 * дней, его приходилось бы дотягивать до одного, и дотяжки копились —
 * последний этап уезжал за срок сдачи неизвестно почему. Дефект был
 * настоящим: одиннадцать разделов сметы R-99 раскладывались на день
 * дальше окна, потому что раздел без работ дотягивался до дня за счёт
 * последнего. Проверка стенда его и назвала.
 *
 * Остаток делится накопительно (доля первых i разделов от всей суммы), а
 * не длительностями порознь: порознь одиннадцать округлений дают до
 * одиннадцати дней расхождения с окном. Накопительный счёт держит сумму
 * ровной по построению — сумма длительностей равна числу дней окна точно.
 *
 * Единственный случай, когда раскладка выходит за окно: разделов больше,
 * чем в окне дней, и каждому по дню уже не хватает. Отказывать здесь
 * нечему — график, показывающий срыв, полезнее отсутствующего, и это то
 * же правило, по которому валидатор дат принимает срок позже сдачи и лишь
 * предупреждает о нём.
 *
 * Пустой список разделов даёт пустую раскладку, а не окно без этапов.
 */
export function planFromSections(
  входные: readonly SectionWeight[],
  bounds: PlanBounds,
): PlannedStage[] {
  /* Разделы-заголовки отсеиваются здесь, а не у вызывающего: иначе экран и
     сервер отсеивали бы их порознь и разошлись бы на первой правке —
     лист обещал бы этапов больше, чем завёл сервер. На стенде такой
     раздел есть: «Дополнительные расходы (в ходе работы)» — ноль позиций.
     Дефект нашёлся на нём, а не в рассуждении. */
  const sections = входные.filter((section) => section.positions > 0);
  if (sections.length === 0) return [];

  const дней = Math.max(1, daysBetween(bounds.from, bounds.to) + 1);
  const сумма = sections.reduce((итог, section) => итог + (section.total as bigint), 0n);
  /* Что остаётся сверх дня на раздел. Отрицательного не бывает: при
     нехватке дней делить нечего, и каждый раздел живёт своим днём. */
  const остаток = Math.max(0, дней - sections.length);

  const stages: PlannedStage[] = [];
  let начало = 0;
  let роздано = 0;
  let накоплено = 0n;

  for (const [индекс, section] of sections.entries()) {
    накоплено += section.total as bigint;
    /* Смета без цен — не повод отказать: разделы названы и упорядочены, а
       поровну поделённое окно остаётся честным черновиком. */
    const граница = сумма === 0n
      ? Math.round((остаток * (индекс + 1)) / sections.length)
      : Number(divideRoundHalfUp(накоплено * BigInt(остаток), сумма));
    const добавка = граница - роздано;
    роздано = граница;

    const дни = 1 + добавка;
    stages.push({
      sectionId: section.id,
      name: section.name,
      startsOn: shiftDay(bounds.from, начало),
      endsOn: shiftDay(bounds.from, начало + дни - 1),
      days: дни,
    });
    начало += дни;
  }

  return stages;
}

/** Последний день раскладки или `null`, если раскладывать нечего. */
export function planEndsOn(stages: readonly PlannedStage[]): string | null {
  const last = stages[stages.length - 1];
  return last?.endsOn ?? null;
}
