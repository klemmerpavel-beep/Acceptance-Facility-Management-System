import { kopecks, sum, type Kopecks } from "./money.js";

/**
 * Расход по объекту, подтверждённый чеком.
 *
 * Заказчик назвал утрату чеков одной из главных потерь: «это потеря чеков,
 * либо попросту забыл о его существовании» (`01_PROJECT.md`, раздел 3).
 * Бухгалтера в компании нет, и материалы возмещаются заказчиком по факту
 * предъявления — значит чек, которого нет в системе, это деньги, которых
 * студия не получит.
 *
 * Здесь только правила счёта и отказа. Ни базы, ни запроса, ни текущего
 * времени: «сегодня» приходит доводом, иначе правило было бы непроверяемым
 * — тест, зависящий от дня прогона, однажды падает сам.
 *
 * Расход НЕ входит ни в смету, ни в транш, ни в приёмку. Это учёт
 * потраченного, а не изменение цены работ: смета отвечает на вопрос
 * «сколько стоит», расход — на вопрос «сколько ушло», и складывать их
 * значило бы получить величину, которой никто не распоряжается.
 */

/**
 * Состояние расхода. Соответствует перечислению `ExpenseStatus` в схеме.
 *
 * Три, а не два. Отклонённый расход не удаляется: история не переписывается
 * (БП-04), и «почему этот чек не возместили» спрашивают через месяц — так
 * же, как «кто перевёл объект в паузу».
 */
export type ExpenseStatus = "DRAFT" | "CONFIRMED" | "REJECTED";

/** Вид расхода. Список закрытый — решение заказчика от 13.09.2026. */
export type ExpenseKind = "MATERIALS" | "DELIVERY" | "TOOLS" | "OTHER";

export interface ExpenseRecord {
  readonly status: ExpenseStatus;
  readonly amount: Kopecks;
  /** Возмещается ли заказчиком. Ложь — расход остаётся на студии. */
  readonly reimbursable: boolean;
}

export interface ExpenseTotals {
  /** Потрачено всего по подтверждённым. */
  readonly spent: Kopecks;
  /** Из потраченного — то, что предъявляется заказчику. */
  readonly reimbursable: Kopecks;
  /** Из потраченного — то, что остаётся на студии. */
  readonly own: Kopecks;
}

/**
 * Итоги расходов объекта.
 *
 * **Считаются только подтверждённые.** Черновик — заявка, а не расход:
 * вечерний вопрос «сколько ушло по объекту» не должен зависеть от того,
 * успел ли руководитель разобрать черновики. Отклонённый не считается тем
 * более — он остаётся историей, а не деньгами.
 *
 * Возмещаемое и своё разделены, а не сведены в одно: первое уходит в счёт
 * заказчику, второе — нет, и сумма, в которой они смешаны, не отвечает ни
 * на один вопрос целиком.
 */
export function expenseTotals(rows: readonly ExpenseRecord[]): ExpenseTotals {
  const учтённые = rows.filter((row) => row.status === "CONFIRMED");
  const возмещаемые = учтённые.filter((row) => row.reimbursable);
  const свои = учтённые.filter((row) => !row.reimbursable);
  return {
    spent: sum(учтённые.map((row) => row.amount)),
    reimbursable: sum(возмещаемые.map((row) => row.amount)),
    own: sum(свои.map((row) => row.amount)),
  };
}

/** Предел суммы одного чека: миллион рублей. Выше — почти наверняка промах. */
const ПРЕДЕЛ = kopecks(100_000_000);

export interface ExpenseInput {
  readonly amount: Kopecks;
  readonly seller: string;
  /** Дата покупки с чека в виде `ГГГГ-ММ-ДД`. */
  readonly spentAt: string;
}

/**
 * Отказ при заведении расхода, словами человека.
 *
 * `null` — принимается. Зовётся и сервером до записи, и экраном до
 * обращения к сети — тем же приёмом, что `acceptanceFault` и
 * `stageDateFault`: одно правило, два места применения, ни одной копии.
 *
 * Сегодняшний день приходит доводом, а не берётся из часов: правило,
 * зависящее от дня прогона, однажды падает само.
 */
export function expenseFault(input: ExpenseInput, today: string): string | null {
  if (input.amount <= 0n) {
    return "Сумма чека должна быть больше нуля.";
  }
  if (input.amount > ПРЕДЕЛ) {
    return "Сумма чека больше миллиона рублей — проверьте, не введены ли копейки вместо рублей.";
  }
  if (input.seller.trim().length < 2) {
    return "Назовите, где куплено: по чеку без продавца расход не проверить.";
  }
  /* Покупка в будущем — промах в дате, а не данные. Сравнение строк
     календарных дат равносильно сравнению самих дат: формат
     `ГГГГ-ММ-ДД` упорядочен лексикографически. */
  if (input.spentAt > today) {
    return "Дата покупки позже сегодняшней. Чек из будущего — промах в дате.";
  }
  return null;
}
