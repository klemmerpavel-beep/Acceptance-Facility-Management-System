/**
 * День организации.
 *
 * «Сегодня» продукт до этапа Э8 брал по UTC: в Воронеже сутки до трёх часов
 * ночи считались вчерашними, и «ждёт 3 дня» в полночь по местному времени
 * ещё было «2». Порог семи дней и «этап идёт сегодня» (этап Э8, ДР-1;
 * допущение задания) считаются по часовому поясу организации, и так же —
 * дни ожидания транша (ДР-4): одно число в двух местах обязано совпадать.
 *
 * Пояс берётся из настроек организации; неизвестное имя пояса — ошибка
 * данных, и тихий откат к UTC её бы спрятал.
 */
export function dayInZone(at: Date, timeZone: string): string {
  const части = new Intl.DateTimeFormat("en-CA", {
    timeZone, year: "numeric", month: "2-digit", day: "2-digit",
  }).formatToParts(at);
  const часть = (вид: Intl.DateTimeFormatPartTypes): string =>
    части.find((кусок) => кусок.type === вид)?.value ?? "";
  return `${часть("year")}-${часть("month")}-${часть("day")}`;
}
