import { describe, expect, it } from "vitest";
import { basisPoints } from "./money.js";
import {
  barGeometry,
  coversDay,
  dayIndex,
  dayOffset,
  isDayOff,
  monthWindow,
  shiftDay,
  shiftMonth,
  windowDays,
  stageDateFault,
  stageDateWarning,
  planWindow,
  projectReadiness,
  stageDays,
  windowAround,
  type ProjectRange,
  type StageSpan,
} from "./schedule.js";

/**
 * Контрольный набор — этапы объекта R-99 из наполнения стенда
 * (`apps/api/prisma/seed.mjs`). Числа сверены с базой, а не придуманы: если
 * наполнение разойдётся с этими значениями, тест это покажет.
 */
const стадия = (startsOn: string, endsOn: string, progress: number): StageSpan => ({
  startsOn,
  endsOn,
  progress: basisPoints(progress),
});

const R99: StageSpan[] = [
  стадия("2026-03-02", "2026-03-20", 10000),
  стадия("2026-03-21", "2026-04-15", 10000),
  стадия("2026-04-06", "2026-04-25", 10000),
  стадия("2026-04-20", "2026-05-30", 10000),
  стадия("2026-05-25", "2026-06-15", 10000),
  стадия("2026-06-10", "2026-07-20", 8000),
  стадия("2026-07-15", "2026-08-15", 3500),
];

describe("длительность этапа", () => {
  it("обе границы включительно: этап на один день длится один день", () => {
    expect(stageDays(стадия("2026-03-02", "2026-03-02", 0))).toBe(1);
  });

  it("считает через границу месяца", () => {
    // 21–31 марта — 11 дней, 1–15 апреля — 15, всего 26.
    expect(stageDays(R99[1]!)).toBe(26);
  });

  it("перевёрнутый отрезок даёт один день, а не отрицательный вес", () => {
    expect(stageDays(стадия("2026-05-30", "2026-04-20", 0))).toBe(1);
  });
});

describe("готовность объекта", () => {
  it("этапов нет — готовность не задана, а не ноль", () => {
    expect(projectReadiness([])).toBeNull();
  });

  it("R-99: 85,57 % при 201 дне графика", () => {
    // (19+26+20+41+22)×10000 + 41×8000 + 32×3500 = 1 720 000; /201 = 8557,2
    expect(R99.reduce((total, stage) => total + stageDays(stage), 0)).toBe(201);
    expect(projectReadiness(R99)).toBe(8557n);
  });

  it("взвешивание по длительности отличается от простого среднего", () => {
    // Простое среднее по семи этапам дало бы 8785 — на 228 пунктов больше.
    const простое = R99.reduce((t, s) => t + Number(s.progress), 0) / R99.length;
    expect(Math.round(простое)).toBe(8786);
    expect(projectReadiness(R99)).not.toBe(8786n);
  });

  it("длинный незавершённый этап тянет готовность вниз сильнее короткого", () => {
    const короткий = [стадия("2026-01-01", "2026-01-02", 10000), стадия("2026-01-03", "2026-01-04", 0)];
    const длинный = [стадия("2026-01-01", "2026-01-02", 10000), стадия("2026-01-03", "2026-02-01", 0)];
    expect(projectReadiness(короткий)).toBe(5000n);
    expect(projectReadiness(длинный)).toBe(625n);
  });

  it("все этапы завершены — ровно 100,00 %", () => {
    const готов = R99.map((stage) => ({ ...stage, progress: basisPoints(10000) }));
    expect(projectReadiness(готов)).toBe(10000n);
  });
});

describe("окно графика", () => {
  it("этапов нет — окна нет", () => {
    expect(planWindow([])).toBeNull();
  });

  it("R-99: от первого дня демонтажа до последнего дня отделки", () => {
    expect(planWindow(R99)).toEqual({ from: "2026-03-02", to: "2026-08-15", days: 167 });
  });

  it("крайние даты берутся по всем этапам, а не по первому и последнему", () => {
    // Порядок в списке произвольный; окно обязано это пережить.
    const вразнобой = [R99[3]!, R99[0]!, R99[6]!, R99[2]!];
    expect(planWindow(вразнобой)?.from).toBe("2026-03-02");
    expect(planWindow(вразнобой)?.to).toBe("2026-08-15");
  });
});

describe("геометрия отрезка", () => {
  const окно = planWindow(R99)!;

  it("первый этап прижат к левому краю окна", () => {
    const первый = barGeometry(R99[0]!, окно);
    expect(первый.offset).toBe(0);
    // 19 дней из 167 — 11,38 %.
    expect(первый.length).toBe(11.38);
  });

  it("последний этап заканчивается на правом краю", () => {
    const последний = barGeometry(R99[6]!, окно);
    expect(Math.round(последний.offset + последний.length)).toBe(100);
  });

  it("этап вне окна даёт нулевую длину, а не отрицательный отступ", () => {
    const чужой = стадия("2027-01-01", "2027-02-01", 0);
    expect(barGeometry(чужой, окно).length).toBe(0);
  });
});

describe("положение дня", () => {
  const окно = planWindow(R99)!;

  it("день вне окна не имеет положения", () => {
    expect(dayOffset("2026-09-05", окно)).toBeNull();
    expect(dayOffset("2026-03-01", окно)).toBeNull();
  });

  it("первый день окна стоит посреди своей клетки, а не на краю", () => {
    expect(dayOffset("2026-03-02", окно)).toBe(0.3);
  });

  it("последний день окна не выходит за сто процентов", () => {
    const край = dayOffset("2026-08-15", окно);
    expect(край).not.toBeNull();
    expect(край!).toBeLessThan(100);
  });
});

describe("окно вокруг дня", () => {
  it("квартал: месяц назад, текущий и следующий", () => {
    expect(windowAround("2026-09-05", 3)).toEqual({
      from: "2026-08-01",
      to: "2026-10-31",
      days: 92,
    });
  });

  it("назад отсчитывается ровно месяц независимо от ширины окна", () => {
    expect(windowAround("2026-09-05", 6).from).toBe("2026-08-01");
    expect(windowAround("2026-09-05", 12).from).toBe("2026-08-01");
  });

  it("год кончается последним днём двенадцатого месяца, а не первым числом", () => {
    expect(windowAround("2026-09-05", 12).to).toBe("2027-07-31");
  });

  it("переход через границу года считается верно", () => {
    expect(windowAround("2026-01-15", 3)).toEqual({
      from: "2025-12-01",
      to: "2026-02-28",
      days: 90,
    });
  });

  it("отрезок, начавшийся до окна, прижимается к левому краю", () => {
    const окно = windowAround("2026-09-05", 3);
    const длинный = стадия("2026-03-02", "2026-08-15", 5000);
    const { offset, length } = barGeometry(длинный, окно);
    expect(offset).toBe(0);
    // Из этапа в окно попадают только 1–15 августа: 15 дней из 92.
    expect(length).toBe(16.3);
  });

  it("отрезок целиком в прошлом окна виден не будет", () => {
    const окно = windowAround("2026-09-05", 3);
    expect(barGeometry(стадия("2026-03-02", "2026-03-20", 10000), окно).length).toBe(0);
  });

  it("сегодняшний день всегда внутри окна", () => {
    for (const months of [3, 6, 12]) {
      expect(dayOffset("2026-09-05", windowAround("2026-09-05", months))).not.toBeNull();
    }
  });
});

describe("coversDay: идёт ли работа в этот день", () => {
  const этап: StageSpan = { startsOn: "2026-09-01", endsOn: "2026-09-10", progress: basisPoints(0) };

  it("день внутри отрезка", () => {
    expect(coversDay(этап, "2026-09-05")).toBe(true);
  });

  it("границы включены: начатый сегодня этап сегодня и идёт", () => {
    expect(coversDay(этап, "2026-09-01")).toBe(true);
    expect(coversDay(этап, "2026-09-10")).toBe(true);
  });

  it("день до начала и после конца работой не считается", () => {
    expect(coversDay(этап, "2026-08-31")).toBe(false);
    expect(coversDay(этап, "2026-09-11")).toBe(false);
  });
});

/**
 * Валидатор дат этапа на настоящем материале.
 *
 * В графике производства работ заказчика семнадцать строк и восемь
 * дефектных дат: две пары с окончанием раньше начала, четыре года за
 * пределами проекта, одно 30 февраля (оно же с дефектным годом) и ещё одна
 * перевёрнутая пара. Проверка требует, чтобы отклонены были все восемь и
 * чтобы каждая назвала свою причину — это пункт 5.5 плана работ.
 */
describe("валидатор дат этапа: восемь дефектных дат исходного графика", () => {
  /* Сроки объекта по договору. Допуск ±1 год даёт 2024-2027. */
  const договор: ProjectRange = { from: "2025-12-15", to: "2026-08-15" };

  it("21.12.26 — 10.01.26: окончание раньше начала", () => {
    const fault = stageDateFault({ startsOn: "2026-12-21", endsOn: "2026-01-10" }, договор);
    expect(fault).toBe("Окончание 10.01.2026 раньше начала 21.12.2026. Проверьте порядок дат.");
  });

  it("31.03.26 — 07.03.26: окончание раньше начала", () => {
    const fault = stageDateFault({ startsOn: "2026-03-31", endsOn: "2026-03-07" }, договор);
    expect(fault).toBe("Окончание 07.03.2026 раньше начала 31.03.2026. Проверьте порядок дат.");
  });

  it("25.07.26 — 15.08.25: окончание раньше начала", () => {
    const fault = stageDateFault({ startsOn: "2026-07-25", endsOn: "2025-08-15" }, договор);
    expect(fault).toBe("Окончание 15.08.2025 раньше начала 25.07.2026. Проверьте порядок дат.");
  });

  it.each(["2028-07-24", "2029-07-24"])("%s: год за пределами проекта", (endsOn) => {
    const fault = stageDateFault({ startsOn: "2026-07-01", endsOn }, договор);
    expect(fault).toBe(`Год ${endsOn.slice(0, 4)} за пределами проекта 15.12.2025 — 15.08.2026.`);
  });

  /* 26.02.27 и 24.07.27 перечень заказчика относит к дефектам, но по
     правилу БП-11 «год в диапазоне проекта ±1» они законны. Отличить
     сорванный срок от опечатки система не может — и не отказывает, а
     предупреждает: см. stageDateWarning. */
  it.each(["2027-02-26", "2027-07-24"])("%s: не отказ, а предупреждение", (endsOn) => {
    expect(stageDateFault({ startsOn: "2026-08-01", endsOn }, договор)).toBeNull();
    expect(stageDateWarning({ startsOn: "2026-08-01", endsOn }, договор)).toContain(
      "позже срока сдачи 15.08.2026",
    );
  });

  it("30.02.28: несуществующая дата названа прежде дефектного года", () => {
    const fault = stageDateFault({ startsOn: "2026-07-01", endsOn: "2028-02-30" }, договор);
    expect(fault).toBe("30.02.2028 не существует. Укажите существующую дату окончания.");
  });

  it("несуществующее начало названо своим словом", () => {
    const fault = stageDateFault({ startsOn: "2026-04-31", endsOn: "2026-05-10" }, договор);
    expect(fault).toBe("31.04.2026 не существует. Укажите существующую дату начала.");
  });
});

describe("валидатор дат этапа: законные случаи", () => {
  const договор: ProjectRange = { from: "2025-12-15", to: "2026-08-15" };

  it("однодневный этап проходит: начало и окончание совпадают", () => {
    expect(stageDateFault({ startsOn: "2026-03-02", endsOn: "2026-03-02" }, договор)).toBeNull();
  });

  it("этап через границу года внутри допуска проходит", () => {
    expect(stageDateFault({ startsOn: "2025-12-20", endsOn: "2026-01-20" }, договор)).toBeNull();
  });

  it("29 февраля високосного года существует", () => {
    expect(stageDateFault({ startsOn: "2024-02-29", endsOn: "2024-03-01" }, договор)).toBeNull();
  });

  it("допуск ровно в год: 2024 и 2027 — края, за ними отказ", () => {
    expect(stageDateFault({ startsOn: "2024-12-01", endsOn: "2025-01-10" }, договор)).toBeNull();
    expect(stageDateFault({ startsOn: "2027-08-01", endsOn: "2027-08-10" }, договор)).toBeNull();
    expect(stageDateFault({ startsOn: "2023-12-01", endsOn: "2024-01-10" }, договор)).not.toBeNull();
  });
});

describe("предупреждение о выходе за срок сдачи", () => {
  const договор: ProjectRange = { from: "2025-12-15", to: "2026-08-15" };

  it("этап внутри договора предупреждения не даёт", () => {
    expect(stageDateWarning({ startsOn: "2026-03-02", endsOn: "2026-08-15" }, договор)).toBeNull();
  });

  it("этап за сроком называет, на сколько дней он выходит", () => {
    expect(stageDateWarning({ startsOn: "2026-08-01", endsOn: "2026-09-14" }, договор)).toBe(
      "Окончание 14.09.2026 позже срока сдачи 15.08.2026 на 30 дн.",
    );
  });

  it("при отказе предупреждения нет: причина уже названа", () => {
    expect(stageDateWarning({ startsOn: "2026-09-01", endsOn: "2026-08-01" }, договор)).toBeNull();
  });
});

describe("календарная арифметика окна правки", () => {
  it("сдвиг дня переходит через границу месяца", () => {
    expect(shiftDay("2026-03-31", 1)).toBe("2026-04-01");
    expect(shiftDay("2026-03-01", -1)).toBe("2026-02-28");
  });

  it("сдвиг дня знает високосный февраль", () => {
    expect(shiftDay("2028-02-28", 1)).toBe("2028-02-29");
    expect(shiftDay("2028-03-01", -1)).toBe("2028-02-29");
  });

  it("окно месяца берёт его длину из календаря", () => {
    expect(monthWindow("2026-02-17")).toEqual({ from: "2026-02-01", to: "2026-02-28", days: 28 });
    expect(monthWindow("2028-02-17").days).toBe(29);
    expect(monthWindow("2026-09-09")).toEqual({ from: "2026-09-01", to: "2026-09-30", days: 30 });
  });

  it("сдвиг месяца считается от первого числа, а не от переданного дня", () => {
    // 31 марта минус месяц «естественным» счётом даёт 3 марта: февраль короче.
    expect(shiftMonth("2026-03-31", -1)).toBe("2026-02-01");
    expect(shiftMonth("2026-12-15", 1)).toBe("2027-01-01");
    expect(shiftMonth("2026-01-15", -1)).toBe("2025-12-01");
  });

  it("номер дня в окне отсчитывается от нуля и допускает выход за края", () => {
    const окно = monthWindow("2026-09-09");
    expect(dayIndex("2026-09-01", окно)).toBe(0);
    expect(dayIndex("2026-09-30", окно)).toBe(29);
    expect(dayIndex("2026-08-31", окно)).toBe(-1);
    expect(dayIndex("2026-10-01", окно)).toBe(30);
  });

  it("дни окна идут подряд и включают обе границы", () => {
    const дни = windowDays(monthWindow("2026-09-09"));
    expect(дни).toHaveLength(30);
    expect(дни[0]).toBe("2026-09-01");
    expect(дни.at(-1)).toBe("2026-09-30");
  });

  it("выходными считаются суббота и воскресенье", () => {
    // 5 и 6 сентября 2026 — суббота и воскресенье.
    expect(isDayOff("2026-09-05")).toBe(true);
    expect(isDayOff("2026-09-06")).toBe(true);
    expect(isDayOff("2026-09-07")).toBe(false);
  });
});
