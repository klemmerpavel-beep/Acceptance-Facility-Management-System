/**
 * Заголовок с датой делает свидетельством весь свой раздел.
 *
 * Проверка по предложению этого не ловила: в таблице отчёта об этапе даты нет
 * ни в одной ячейке — она стоит в заголовке раздела над таблицей. Правило
 * опирается на собственный порядок этих документов: всё историческое здесь
 * датируется, и датируется разделом, а не строкой.
 */
const ДАТА = /\d{2}\.\d{2}\.\d{4}/u;

for (const путь of МЕСТА) {
  const строки = readFileSync(new URL(`../${путь}`, import.meta.url), "utf8").split("\n");
  /* Уровень датированного заголовка. Подраздел внутри датированного раздела
     остаётся свидетельством: «### Проверено» под «## Переход на устройство
     эталона, 05.09.2026» — часть того же отчёта, а не новое утверждение.
     Снимает пометку только заголовок того же или более высокого уровня.
     `0` — датированного раздела сейчас нет. */
  let датированныйУровень = 0;
  /* Преамбула — всё до первого раздела второго уровня. Дата в ней датирует
     саму преамбулу и больше ничего: там стоит строка версии документа, и
     распространить её на весь файл значило бы разоружить проверку целиком.
     Первая редакция этого правила так и сделала — откат показал, что
     `03_DESIGN_SYSTEM.md` перестал проверяться от шапки до конца. */
  let вПреамбуле = true;
  строки.forEach((строка, номер) => {
    const заголовок = /^(#{1,6})\s/u.exec(строка);
    if (заголовок !== null) {
      const уровень = (заголовок[1] ?? "").length;
      if (уровень >= 2) вПреамбуле = false;
      if (датированныйУровень !== 0 && уровень <= датированныйУровень) датированныйУровень = 0;
      if (ДАТА.test(строка)) датированныйУровень = уровень;
    }
    if (датированныйУровень !== 0) return;
    if (вПреамбуле && ДАТА.test(строка)) return;
    /* Разбор по предложению, а не по строке: в одной строке стоят рядом
       действующее утверждение и свидетельство о прошлом — «ведёт 42 пары.
       Прежняя редакция проверяла 21 пару». Правило по строке правило бы оба,
       то есть переписывало бы историю. */
    /* Признак ищется в двух строках подряд, а число — в своей.
       Документы переносятся по ширине, и утверждение живёт поперёк переноса:
       «…и девять вкладок / карточки объекта». Признак, разорванный переносом,
       не находился, и правило молчало — откат это и показал. Номер строки при
       этом остаётся точным: он берётся у той строки, где стоит число. */
    const контекст = `${строка} ${строки[номер + 1] ?? ""}`;
    for (const предложение of строка.split(/(?<=[.;])\s+/u)) {
      if (свидетельство(предложение)) continue;
      for (const величина of ВЕЛИЧИНЫ) {
        if (!величина.признак.test(контекст)) continue;
        for (const пара of предложение.matchAll(величина.слово)) {
          const заявлено = число(пара[1] ?? "");
          if (заявлено === null || заявлено !== величина.значение) {
            if (заявлено === null) continue;
            проблемы.push(`${путь}:${номер + 1}: заявлено ${заявлено} ${величина.имя},`
              + ` в сборке ${величина.значение}`);
          }
        }
      }
    }
  });
}

/* --- Снятый дефект не стоит открытым на странице публикации ------------------
 *
 * Реестр дефектов и его публикация — два документа об одном, и расходятся они
 * молча: правится реестр, страница остаётся. Сверка 18.09.2026 нашла на
 * `audit.html` четыре дефекта открытыми, из которых три были сняты в реестре
 * ещё 13–14.09. Страницу открывает заказчик, реестр — нет.
 * -------------------------------------------------------------------------- */
{
  const реестр = readFileSync(new URL("../docs/09_AUDIT.md", import.meta.url), "utf8");
  const снятые = new Set(
    [...реестр.matchAll(/\*\*(А-\d+)\.\s*~~/gu)].map((пара) => пара[1]));
  const страница = readFileSync(new URL("../design/audit.html", import.meta.url), "utf8");
  const открытые = [...страница.matchAll(
    /finding--open"[\s\S]{0,200}?<h4>(А-\d+)\./gu)].map((пара) => пара[1]);
  for (const дефект of открытые) {
    if (снятые.has(дефект)) {
      проблемы.push(`design/audit.html: дефект ${дефект} снят в реестре,`
        + " а на странице публикации стоит открытым");
    }
  }
  if (снятые.size === 0) {
    проблемы.push("docs/09_AUDIT.md: ни один дефект не помечен снятым — правило разоружено");
  }
}

/* --- Реестр интерфейса сходится сам с собой ---------------------------------
 *
 * Сводка по этапам называет находки, закрытые этапом. Если строка находки
 * пометки «закрыто» не несёт, реестр утверждает две разные вещи об одном, и
 * читающий не знает, какой половине верить. Второе свойство — опознаватель не
 * повторяется: «З-3» стояло дважды, и ссылка на него была неоднозначна.
 * -------------------------------------------------------------------------- */
{
  const строки = readFileSync(
    new URL("../docs/11_UI_AUDIT.md", import.meta.url), "utf8").split("\n");
  const состояние = new Map();
  const повторы = [];
  строки.forEach((строка, номер) => {
    const найдено = /^\|\s*([А-ЯЁ]-\d+)\s*\|/u.exec(строка);
    if (найдено === null) return;
    const ид = найдено[1] ?? "";
    if (состояние.has(ид)) повторы.push(`${ид} (строки ${состояние.get(ид).номер} и ${номер + 1})`);
    else состояние.set(ид, { номер: номер + 1, закрыто: /закрыт|снят/iu.test(строка) });
  });
  for (const повтор of повторы) {
    проблемы.push(`docs/11_UI_AUDIT.md: опознаватель ${повтор} занят дважды —`
      + " ссылка на него неоднозначна");
  }
  for (const строка of строки) {
    if (!/^\|\s*\d+[а-я]?\.\s/u.test(строка) || !/закрыт/iu.test(строка)) continue;
    /* Граница слова `\b` определена на латинице: перед кириллической «А» её
       нет, и выражение с ней не находило ничего — правило молчало на откате.
       Тот же недосмотр уже чинился в страже глаголов и в страже чисел; запись
       оставлена, чтобы он не повторился в четвёртый раз. */
    for (const пара of строка.matchAll(/(?<![А-ЯЁа-яё])([А-ЯЁ]-\d+)(?!\d)/gu)) {
      const ид = пара[1] ?? "";
      const запись = состояние.get(ид);
      if (запись === undefined) {
        проблемы.push(`docs/11_UI_AUDIT.md: этап называет находку ${ид},`
          + " которой в реестре нет");
      } else if (!запись.закрыто) {
        проблемы.push(`docs/11_UI_AUDIT.md:${запись.номер}: находка ${ид} названа`
          + " в закрытом этапе, а в реестре пометки «закрыто» не несёт");
      }
    }
  }
}

console.log(`Проверка документов: прогон дал ${всего} тестов в ${суммы.length} пакетах;`
  + ` пар контраста ${парКонтраста}, артбордов ${артбордов}, вкладок карточки ${вкладок},`
  + ` ролей продукта ${ролей}.`);
if (проблемы.length === 0) {
  console.log("  расхождений нет");
  process.exit(0);
}
for (const проблема of проблемы) console.log("  ✗", проблема);
process.exit(1);
