/**
 * Число из слова: цифра либо числительное словом.
 *
 * Словарь держит полные формы, а не основы. Первая редакция сравнивала по
 * основе и на «одиннадцатью строками теста» выдала «заявлено 100 тестов»:
 * основа «ст» для сотни совпала со словом «строками». Основа короче слова
 * ловит слова — это и есть цена сопоставления по началу.
 *
 * Возвращает `null`, если слово числом не является: выражения ниже берут
 * слово перед существительным, а там стоит что угодно.
 */
function число(слово) {
  const чистое = слово.replace(/[«»(),.:;—–-]/gu, "").toLowerCase();
  if (/^\d+$/u.test(чистое)) return Number.parseInt(чистое, 10);
  return ЧИСЛИТЕЛЬНЫЕ.get(чистое) ?? null;
}

/* --- Свидетельство против заявления -----------------------------------------
 *
 * Сверяется заявление о нынешнем составе, а не запись о том, что было.
 * «Проверено 11.09.2026: 316 тестов», «прежняя редакция ловила 21 пару»,
 * зачёркнутый текст — свидетельства, и править их значит переписывать историю.
 *
 * Дата в предложении — самый надёжный различитель: этот проект датирует всё
 * историческое, и правило опирается на его собственный порядок, а не на
 * перечень слов, который придётся дописывать.
 * -------------------------------------------------------------------------- */
const О_ПРОШЛОМ = /прежн|раньше|до того|был|проверял|содержал|существовал|ловил|снят|отменён|отменено|\d{2}\.\d{2}\.\d{4}/iu;
const ЗАЧЁРКНУТО = /~~/u;
const свидетельство = (предложение) =>
  О_ПРОШЛОМ.test(предложение) || ЗАЧЁРКНУТО.test(предложение);

