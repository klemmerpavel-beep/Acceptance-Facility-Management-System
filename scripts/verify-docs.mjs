/**
 * Числа в документах против чисел сборки.
 *
 * Норматив требует: «документ, отставший от сборки, хуже отсутствующего — ему
 * верят» (`docs/02_DEV_PROMPT.md`). Требование было, проверки не было, и за
 * четыре этапа число тестов в документах отстало с 412 до 316 — на четверть.
 *
 * Проверяется только то, что заявлено как действующее. Датированные записи —
 * отчёт аудита, журнал этапов, состояние плана на прошлое число — не
 * правятся и не проверяются: они свидетельство того, что было, а не обещание
 * того, что есть.
 *
 * Вход — вывод `pnpm test`: число берётся из прогона, а не пишется рядом.
 * Записанное рядом разошлось бы с прогоном ровно тем же способом, каким
 * документы разошлись со сборкой.
 */
import { readFileSync } from "node:fs";

/* Управляющие последовательности цвета снимаются до разбора. На своей машине
   vitest пишет без цвета, в сборке — с цветом, и выражение, проверенное
   локально, в сборке не находило ничего: между «Tests» и числом стоят
   escape-последовательности. Проверка, испытанная в одной среде, стережёт
   одну среду. */
/* Управляющий знак задаётся кодовой точкой, а не литералом в выражении:
   литерал запрещён правилом линта no-control-regex, и запрещён по делу —
   невидимый знак в исходнике не читается глазом и переживает правку молча. */
const УПРАВЛЯЮЩИЙ = String.fromCodePoint(0x1B);
const БЕЗ_ЦВЕТА = new RegExp(`${УПРАВЛЯЮЩИЙ}\\[[0-9;]*m`, "gu");
const вывод = process.argv[2] === undefined
  ? ""
  : readFileSync(process.argv[2], "utf8").replace(БЕЗ_ЦВЕТА, "");
const проблемы = [];

/* Vitest печатает по строке на пакет: «Tests  286 passed (286)». */
const суммы = [...вывод.matchAll(/Tests\s+(\d+) passed \(\d+\)/gu)]
  .map((пара) => Number.parseInt(пара[1] ?? "0", 10));
if (суммы.length === 0) {
  console.error("Проверка документов: в выводе прогона нет ни одной строки «Tests N passed».");
  console.error("Ожидался путь к файлу с выводом `pnpm test` первым доводом.");
  process.exit(2);
}
const всего = суммы.reduce((сумма, часть) => сумма + часть, 0);

