/**
 * Числа в документах против чисел сборки.
 *
 * Норматив требует: «документ, отставший от сборки, хуже отсутствующего — ему
 * верят» (`docs/02_DEV_PROMPT.md`). Требование было, проверки не было, и за
 * четыре этапа число тестов в документах отстало с 412 до 316 — на четверть.
 *
 * Проверяется только то, что заявлено как действующее. Датированные записи —
 * отчёт аудита, журнал этапов, состояние плана на прошлое число — не
 * правятся и не проверяются: они свидетельство того, что было, а не обещание
 * того, что есть.
 *
 * Вход — вывод `pnpm test`: число берётся из прогона, а не пишется рядом.
 * Записанное рядом разошлось бы с прогоном ровно тем же способом, каким
 * документы разошлись со сборкой.
 */
import { readFileSync } from "node:fs";

/* Управляющие последовательности цвета снимаются до разбора. На своей машине
   vitest пишет без цвета, в сборке — с цветом, и выражение, проверенное
   локально, в сборке не находило ничего: между «Tests» и числом стоят
   escape-последовательности. Проверка, испытанная в одной среде, стережёт
   одну среду. */
/* Управляющий знак задаётся кодовой точкой, а не литералом в выражении:
   литерал запрещён правилом линта no-control-regex, и запрещён по делу —
   невидимый знак в исходнике не читается глазом и переживает правку молча. */
const УПРАВЛЯЮЩИЙ = String.fromCodePoint(0x1B);
const БЕЗ_ЦВЕТА = new RegExp(`${УПРАВЛЯЮЩИЙ}\\[[0-9;]*m`, "gu");
const вывод = process.argv[2] === undefined
  ? ""
  : readFileSync(process.argv[2], "utf8").replace(БЕЗ_ЦВЕТА, "");
const проблемы = [];

/* Vitest печатает по строке на пакет: «Tests  286 passed (286)». */
const суммы = [...вывод.matchAll(/Tests\s+(\d+) passed \(\d+\)/gu)]
  .map((пара) => Number.parseInt(пара[1] ?? "0", 10));
if (суммы.length === 0) {
  console.error("Проверка документов: в выводе прогона нет ни одной строки «Tests N passed».");
  console.error("Ожидался путь к файлу с выводом `pnpm test` первым доводом.");
  process.exit(2);
}
const всего = суммы.reduce((сумма, часть) => сумма + часть, 0);

/* Места, заявляющие действующее число тестов. */
const МЕСТА = [
  "docs/02_DEV_PROMPT.md",
  "docs/06_PLAN.md",
  "README.md",
];
/* Число всей сборки заявляется там, где документ описывает её прогон.
   Счёт тестов отдельного модуля («18 тестов на округление») и датированные
   записи прошлых этапов («Проверено: 145 тестов») — не заявления о нынешнем
   составе, и сверять их с прогоном значило бы переписывать свидетельства.
   Первая редакция правила этого не различала и на пять срабатываний давала
   три ложных: порог, отличающий правило от шума, — это тоже часть правила. */
const ПРО_ВСЮ_СБОРКУ = /pnpm test|vitest run|«Быстрая»/u;

for (const путь of МЕСТА) {
  const строки = readFileSync(new URL(`../${путь}`, import.meta.url), "utf8").split("\n");
  строки.forEach((строка, номер) => {
    if (!ПРО_ВСЮ_СБОРКУ.test(строка)) return;
    /* Граница слова `\b` определена на латинице: после кириллического «тестов»
         её нет, и выражение с ней не находило ничего — проверка молчала бы
         на любом расхождении. Хвост отсекается запретом кириллической
         буквы следом. */
      for (const пара of строка.matchAll(/(\d{2,5})\s+тест(?:ов|а|)(?![а-яё])/giu)) {
      const заявлено = Number.parseInt(пара[1] ?? "0", 10);
      if (заявлено !== всего) {
        проблемы.push(`${путь}:${номер + 1}: заявлено ${заявлено} тестов, прогон дал ${всего}`);
      }
    }
  });
}

/* --- пары контраста ---------------------------------------------------------
 *
 * Второе число, которое уже расходилось: документы называли 21, 26 и 29 пар
 * при разной длине таблицы. Три разных устаревших числа в четырёх файлах —
 * признак того, что правится код, а документ правят «когда вспомнят».
 *
 * Число берётся из самой таблицы `PAIRS`, а не переписывается рядом: рядом
 * записанное разойдётся тем же способом, каким разошлось число тестов.
 * Считаются открывающие скобки пар — по одной на строку таблицы; внутри
 * таблицы других скобок такого вида нет.
 * -------------------------------------------------------------------------- */
const палитра = readFileSync(
  new URL("../packages/ui/src/design-system.test.ts", import.meta.url), "utf8");
const началоТаблицы = палитра.indexOf("const PAIRS");
const конецТаблицы = палитра.indexOf("];", началоТаблицы);
const парКонтраста = началоТаблицы < 0
  ? 0
  : (палитра.slice(началоТаблицы, конецТаблицы).match(/\["--/gu) ?? []).length;

if (парКонтраста === 0) {
  console.error("Проверка документов: таблица PAIRS не найдена или пуста.");
  process.exit(2);
}

/* Заявление о наборе пар опознаётся словом «пар» рядом с числом, но только
   там, где речь о самом наборе. «Обе пары внесены в проверку» — не
   заявление о его размере.

   Разбор идёт по предложению, а не по строке. В одной строке стоят рядом
   действующее утверждение и свидетельство о прошлом: «ведёт 26 пар.
   Прежняя редакция проверяла 21 пару». Правило по строке правило бы оба, то
   есть переписывало бы историю — ровно то, чего проверка чисел тестов
   избегает, не трогая датированные записи. */
const ПРО_НАБОР_ПАР = /набор|проверка контраста|ведёт|проверяет|вс[ей] пар/iu;
const О_ПРОШЛОМ = /прежн|раньше|до того|был|проверял|содержал|существовал|ловил/iu;
/* Норму ведёт дизайн-система — она одна и правится вместе с таблицей.
   `06_PLAN.md` и `08_AUDIT_UI.md` называют размер набора в записях о
   прошедших этапах («набор из 29 пар этого не ловил»), и сверять их с
   нынешней таблицей значило бы переписывать свидетельства — тем же доводом,
   по которому не проверяются датированные записи о числе тестов. */
for (const путь of ["docs/03_DESIGN_SYSTEM.md"]) {
  const строки = readFileSync(new URL(`../${путь}`, import.meta.url), "utf8").split("\n");
  строки.forEach((строка, номер) => {
    for (const предложение of строка.split(/(?<=\.)\s+/u)) {
      if (!ПРО_НАБОР_ПАР.test(предложение) || О_ПРОШЛОМ.test(предложение)) continue;
      for (const пара of предложение.matchAll(/(\d{1,3})\s+пар(?:у|ы|)(?![а-яё])/giu)) {
        const заявлено = Number.parseInt(пара[1] ?? "0", 10);
        if (заявлено !== парКонтраста) {
          проблемы.push(
            `${путь}:${номер + 1}: заявлено ${заявлено} пар контраста, в таблице ${парКонтраста}`);
        }
      }
    }
  });
}

console.log(`Проверка документов: прогон дал ${всего} тестов в ${суммы.length} пакетах;`
  + ` пар контраста в таблице ${парКонтраста}.`);
if (проблемы.length === 0) {
  console.log("  расхождений нет");
  process.exit(0);
}
for (const проблема of проблемы) console.log("  ✗", проблема);
process.exit(1);
